#!/bin/sh
# Copies the observability sources into the places that need their own copy
# (Helm can only read files inside the chart; Kustomize only inside its
# root), so the rules and the dashboard have one source each:
#
#   deploy/observability/prometheus/rules.yml
#     -> deploy/helm/xtandard-image/files/prometheus-rules.yml
#     -> deploy/kubernetes/components/monitoring/prometheusrule.yaml (wrapped)
#   deploy/observability/grafana/dashboards/xtandard-image.json
#     -> deploy/helm/xtandard-image/files/xtandard-image-dashboard.json
#     -> deploy/kubernetes/components/monitoring/xtandard-image-dashboard.json
#
#   sh deploy/scripts/gen.sh          # write
#   sh deploy/scripts/gen.sh --check  # fail when a copy differs (CI, task deploy:check)
set -eu
cd "$(dirname "$0")/.."

check=false
[ "${1:-}" = "--check" ] && check=true

rules=observability/prometheus/rules.yml
dash=observability/grafana/dashboards/xtandard-image.json

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

{
  echo "# GENERATED by deploy/scripts/gen.sh from deploy/$rules; do not edit."
  echo "apiVersion: monitoring.coreos.com/v1"
  echo "kind: PrometheusRule"
  echo "metadata:"
  echo "  name: xtandard-image"
  echo "spec:"
  grep -v '^#' "$rules" | sed 's/^\(.\)/  \1/'
} >"$tmp/prometheusrule.yaml"

# target source
pairs="
helm/xtandard-image/files/prometheus-rules.yml $rules
helm/xtandard-image/files/xtandard-image-dashboard.json $dash
kubernetes/components/monitoring/xtandard-image-dashboard.json $dash
kubernetes/components/monitoring/prometheusrule.yaml $tmp/prometheusrule.yaml
"

status=0
echo "$pairs" | while read -r target src; do
  [ -n "$target" ] || continue
  if $check; then
    if ! cmp -s "$src" "$target"; then
      echo "gen.sh: deploy/$target is out of date; run sh deploy/scripts/gen.sh" >&2
      exit 1
    fi
  else
    mkdir -p "$(dirname "$target")"
    cp "$src" "$target"
    echo "wrote deploy/$target"
  fi
done || status=1
exit "$status"

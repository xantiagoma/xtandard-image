// bunnyKey and bunnyExpires are the inputs of the official SDK test vectors
// (github.com/BunnyWay/BunnyCDN.TokenAuthentication e2e/inputs.json and the
// C# TokenSignerTests: key "SecurityKey", expiry 2020-08-21T15:43:07Z).
const (
	bunnyKey     = "SecurityKey"
	bunnyExpires = "1598024587"
)

func bunnyVerifier(tb testing.TB, o sign.BunnyOptions) *sign.BunnyVerifier {
	tb.Helper()
	if o.Keys == nil {
		o.Keys = rawKeyring(bunnyKey, "")
	}
	v, err := sign.NewBunnyVerifier(o)
	if err != nil {
		tb.Fatalf("NewBunnyVerifier: %v", err)
	}
	return v
}


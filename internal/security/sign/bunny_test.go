func TestBunnyVectors(t *testing.T) {
	t.Parallel()
	verifier := bunnyVerifier(t, sign.BunnyOptions{})
	for _, group := range []struct {
		name    string
		vectors []bunnyVector
		scheme  sign.Scheme
	}{
		{"hs256", bunnyHS256Vectors, sign.NewBunnyHS256Scheme()},
		{"sha256", bunnySHA256Vectors, sign.NewBunnySHA256Scheme()},
	} {
		for _, tc := range group.vectors {
			t.Run(group.name+"/"+tc.name, func(t *testing.T) {
				t.Parallel()
				msg, err := sign.BunnyMessage(tc.sig, tc.path, bunnyExpires, tc.params)
				if err != nil {
					t.Fatal(err)
				}
				res, err := verifier.Verify(tc.sig, msg)
				if err != nil || res != sign.Verified {
					t.Fatalf("Verify = %v, %v (message %q)", res, err, msg)
				}
				s, err := sign.NewSigner(group.scheme, rawKeyring(bunnyKey, ""))
				if err != nil {
					t.Fatal(err)
				}
				if got := mustSign(t, s, msg); got != tc.sig {
					t.Errorf("Sign = %q, want %q", got, tc.sig)
				}
				// Any change to a signed input breaks the token.
				for _, bad := range []struct{ path, expires string }{
					{tc.path + "x", bunnyExpires}, {tc.path, bunnyExpires + "0"},
				} {
					msg, _ := sign.BunnyMessage(tc.sig, bad.path, bad.expires, tc.params)
					if _, err := verifier.Verify(tc.sig, msg); err == nil && !hasTokenPath(tc.params) {
						t.Errorf("tampered %q/%q verified", bad.path, bad.expires)
					}
				}
			})
		}
	}
}

func hasTokenPath(params []sign.BunnyParam) bool {
	for _, p := range params {
		if p.Key == sign.BunnyTokenPathParam {
			return true
		}
	}
	return false
}

// TestBunnyBasic checks the basic layout, b64url(MD5(key ‖ path ‖
// expires)), against the PHP sample on bunny.net/docs/cdn/security/
// token-authentication/basic. Bunny's docs example token
// (m0EMEkV3pNAKFB33gZuv_Q, expires 1456761770) does not publish its key, so
// the expected value was computed independently with
// printf '%s' 'SecurityKey/300kb.jpg1598024587' | openssl md5 -binary | base64
// ("Ao9wBEuhqk4V/zyPZgkzkA==", made URL-safe and unpadded).
func TestBunnyBasic(t *testing.T) {
	t.Parallel()
	const want = "Ao9wBEuhqk4V_zyPZgkzkA"
	v := bunnyVerifier(t, sign.BunnyOptions{})
	params := []sign.BunnyParam{{Key: "width", Value: "400"}} // not covered by basic tokens
	msg, err := sign.BunnyMessage(want, "/300kb.jpg", bunnyExpires, params)
	if err != nil {
		t.Fatal(err)
	}
	if msg != "/300kb.jpg"+bunnyExpires {
		t.Fatalf("message %q", msg)
	}
	if res, err := v.Verify(want, msg); err != nil || res != sign.Verified {
		t.Fatalf("Verify = %v, %v", res, err)
	}
	if res, err := v.Verify(want+"==", msg); err != nil || res != sign.Verified {
		t.Fatalf("padded Verify = %v, %v", res, err)
	}
	s, err := sign.NewSigner(sign.NewBunnyBasicScheme(), rawKeyring(bunnyKey, ""))
	if err != nil {
		t.Fatal(err)
	}
	if got := mustSign(t, s, msg); got != want {
		t.Errorf("Sign = %q, want %q", got, want)
	}
}

func TestBunnyMessage(t *testing.T) {
	t.Parallel()
	const hs = "HS256-x"
	tests := []struct {
		name   string
		sig    string
		params []sign.BunnyParam
		want   string
		err    bool
	}{
		{name: "no_params", sig: hs, want: "/a.jpg1"},
		{
			name: "sorted_raw_values", sig: hs,
			params: []sign.BunnyParam{{Key: "width", Value: "4 0"}, {Key: "aspect_ratio", Value: "16:9"}, {Key: "b", Value: ""}},
			want:   "/a.jpg1aspect_ratio=16:9&b=&width=4 0",
		},
		{
			name: "token_and_expires_skipped", sig: hs,
			params: []sign.BunnyParam{{Key: "token", Value: "t"}, {Key: "expires", Value: "9"}, {Key: "bcdn_token", Value: "t"}, {Key: "q", Value: "1"}},
			want:   "/a.jpg1q=1",
		},
		{
			name: "token_path_replaces_path", sig: hs,
			params: []sign.BunnyParam{{Key: "token_path", Value: "/"}},
			want:   "/1token_path=/",
		},
		{
			name: "ignore_params", sig: hs,
			params: []sign.BunnyParam{{Key: "width", Value: "1"}, {Key: "token_path", Value: "/a"}, {Key: "token_ignore_params", Value: "true"}},
			want:   "/a1token_ignore_params=true&token_path=/a",
		},
		{
			name: "ignore_params_false", sig: hs,
			params: []sign.BunnyParam{{Key: "width", Value: "1"}, {Key: "token_ignore_params", Value: "false"}},
			want:   "/a.jpg1token_ignore_params=false&width=1",
		},
		{name: "basic_ignores_params", sig: "abc", params: []sign.BunnyParam{{Key: "w", Value: "1"}}, want: "/a.jpg1"},
		{name: "duplicate", sig: hs, params: []sign.BunnyParam{{Key: "w", Value: "1"}, {Key: "w", Value: "2"}}, err: true},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := sign.BunnyMessage(tc.sig, "/a.jpg", "1", tc.params)
			if tc.err {
				if !errors.Is(err, sign.ErrMalformedSignature) || errs.KindOf(err) != errs.KindUnauthorized {
					t.Fatalf("err = %v", err)
				}
				return
			}
			if err != nil || got != tc.want {
				t.Fatalf("BunnyMessage = %q, %v; want %q", got, err, tc.want)
			}
		})
	}
}

func TestBunnyVerifier(t *testing.T) {
	t.Parallel()
	plain := bunnyHS256Vectors[0]
	msg, err := sign.BunnyMessage(plain.sig, plain.path, bunnyExpires, nil)
	if err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name string
		opts sign.BunnyOptions
		sig  string
		want sign.Result
		err  error
	}{
		{name: "verified", sig: plain.sig, want: sign.Verified},
		{name: "absent_optional", sig: "", want: sign.Unsigned},
		{name: "absent_required", opts: sign.BunnyOptions{Required: true}, err: sign.ErrMissingSignature},
		{name: "mismatch", sig: "HS256-" + bunnySHA256Vectors[1].sig, err: sign.ErrSignatureMismatch},
		{name: "ip_locked", sig: "HS256-1-L2rISTLcujMY9UFf2tbZ41d5i-Bme1g1oTK_Z2QMLJk", err: sign.ErrMalformedSignature},
		{name: "bad_base64", sig: "HS256-!!!!", err: sign.ErrMalformedSignature},
		{name: "short", sig: "HS256-AAAA", err: sign.ErrMalformedSignature},
		{name: "layout_disabled", opts: sign.BunnyOptions{Layouts: sign.BunnyBasic}, sig: plain.sig, err: sign.ErrMalformedSignature},
		{name: "second_key", opts: sign.BunnyOptions{Keys: rawKeyring("other", "", bunnyKey, "")}, sig: plain.sig, want: sign.Verified},
		{name: "signing_off", opts: sign.BunnyOptions{Keys: sign.NewKeyring()}, sig: "garbage", want: sign.Unsigned},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			v := bunnyVerifier(t, tc.opts)
			res, err := v.Verify(tc.sig, msg)
			if tc.err != nil {
				if !errors.Is(err, tc.err) || errs.KindOf(err) != errs.KindUnauthorized || res != sign.Unsigned {
					t.Fatalf("Verify = %v, %v; want %v", res, err, tc.err)
				}
				return
			}
			if err != nil || res != tc.want {
				t.Fatalf("Verify = %v, %v; want %v", res, err, tc.want)
			}
		})
	}
	if _, err := sign.NewBunnyVerifier(sign.BunnyOptions{Layouts: 1 << 7}); err == nil {
		t.Error("unknown layout accepted")
	}
}

func BenchmarkBunnyVerify(b *testing.B) {
	v := bunnyVerifier(b, sign.BunnyOptions{})
	params := []sign.BunnyParam{
		{Key: "width", Value: "400"},
		{Key: "aspect_ratio", Value: "16:9"},
		{Key: "quality", Value: "80"},
		{Key: "token", Value: "x"},
		{Key: "expires", Value: bunnyExpires},
	}
	s, err := sign.NewSigner(sign.NewBunnyHS256Scheme(), rawKeyring(bunnyKey, ""))
	if err != nil {
		b.Fatal(err)
	}
	msg, err := sign.BunnyMessage("HS256-", "/a.jpg", bunnyExpires, params)
	if err != nil {
		b.Fatal(err)
	}
	token := mustSign(b, s, msg)
	b.ReportAllocs()
	for b.Loop() {
		m, _ := sign.BunnyMessage(token, "/a.jpg", bunnyExpires, params)
		_, _ = v.Verify(token, m)
	}
}

// FuzzBunnyVerify feeds attacker-controlled tokens, paths, expiries and a
// parameter to BunnyMessage and the verifier. Neither may panic, errors are
// 403s, and only the MAC of the message verifies.
func FuzzBunnyVerify(f *testing.F) {
	for _, s := range [][4]string{
		{bunnyHS256Vectors[0].sig, "/300kb.jpg", bunnyExpires, ""},
		{bunnySHA256Vectors[2].sig, "/abc/300kb.jpg", bunnyExpires, "token_path=/abc"},
		{"Ao9wBEuhqk4V_zyPZgkzkA==", "/300kb.jpg", bunnyExpires, "w=1"},
		{"HS256-1-x", "/", "", "token_ignore_params=true"},
		{"HS256-", "", "-1", "="},
		{"====", "\x00", "\xff", "a=b"},
	} {
		f.Add(s[0], s[1], s[2], s[3])
	}
	v := bunnyVerifier(f, sign.BunnyOptions{})
	signers := make([]*sign.Signer, 0, 3)
	for _, scheme := range []sign.Scheme{sign.NewBunnyBasicScheme(), sign.NewBunnySHA256Scheme(), sign.NewBunnyHS256Scheme()} {
		s, err := sign.NewSigner(scheme, rawKeyring(bunnyKey, ""))
		if err != nil {
			f.Fatal(err)
		}
		signers = append(signers, s)
	}
	f.Fuzz(func(t *testing.T, token, path, expires, param string) {
		k, val, _ := strings.Cut(param, "=")
		msg, err := sign.BunnyMessage(token, path, expires, []sign.BunnyParam{{Key: k, Value: val}})
		if err != nil {
			t.Fatalf("BunnyMessage: %v", err)
		}
		res, err := v.Verify(token, msg)
		if err != nil {
			if res != sign.Unsigned || errs.KindOf(err) != errs.KindUnauthorized {
				t.Fatalf("Verify(%q) = %v, %v", token, res, err)
			}
			return
		}
		if token == "" {
			if res != sign.Unsigned {
				t.Fatalf("empty token: %v", res)
			}
			return
		}
		for _, s := range signers {
			if strings.TrimRight(token, "=") == mustSign(t, s, msg) {
				return
			}
		}
		t.Fatalf("Verify(%q, %q) accepted a token that is not the MAC", token, msg)
	})
}

const refDir = "../../../testdata/ssim"

func decodeFile(tb testing.TB, path string) image.Image {
	tb.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		tb.Fatal(err)
	}
	img, _, err := image.Decode(bytes.NewReader(b))
	if err != nil {
		tb.Fatalf("decode %s: %v", path, err)
	}
	return img
}

// TestScikitImageReference checks the implementation against scikit-image,
// whose documentation states that gaussian_weights=True, sigma=1.5,
// use_sample_covariance=False and data_range=255 "match the implementation of
// Wang et al." (https://scikit-image.org/docs/0.26.x/api/skimage.metrics.html#skimage.metrics.structural_similarity).
//
// The distortions mirror Fig. 2 of Wang et al. 2004 (mean shift, contrast
// stretch, impulse noise, blur, JPEG) on the 160x120 greyscale reference in
// testdata/ssim (generated by testdata/gen, CC0). Expected values were
// produced with scikit-image 0.26.0 / NumPy float64:
//
//	uv run --no-project --with scikit-image python -c '
//	from skimage.io import imread; from skimage.metrics import structural_similarity as s
//	r = imread("testdata/ssim/ref.png").astype(float)
//	for n in ["meanshift","contrast","impulse","blur","jpeg"]:
//	    print(n, s(r, imread(f"testdata/ssim/{n}.png").astype(float),
//	        gaussian_weights=True, sigma=1.5, use_sample_covariance=False, data_range=255))'
func TestScikitImageReference(t *testing.T) {
	t.Parallel()
	ref := decodeFile(t, filepath.Join(refDir, "ref.png"))
	tests := []struct {
		name string
		want float64
	}{
		{"ref", 1},
		{"meanshift", 0.9539435528},
		{"contrast", 0.7833232209},
		{"impulse", 0.4321160211},
		{"blur", 0.8238808062},
		{"jpeg", 0.8140025394},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := Compare(ref, decodeFile(t, filepath.Join(refDir, tc.name+".png")))
			if err != nil {
				t.Fatal(err)
			}
			if math.Abs(got.SSIM-tc.want) > 1e-6 {
				t.Errorf("SSIM = %.10f, scikit-image = %.10f", got.SSIM, tc.want)
			}
			if d := DSSIM(got.SSIM); got.DSSIM != d {
				t.Errorf("DSSIM = %v, want (1-SSIM)/2 = %v", got.DSSIM, d)
			}
		})
	}
}

// TestClosedForm uses eq. 13 of Wang et al. 2004: for two constant images x
// and y the variances and covariance vanish, so SSIM reduces to the luminance
// term (2 mu_x mu_y + C1) / (mu_x^2 + mu_y^2 + C1) with C1 = (0.01 * 255)^2.
// It covers both the windowed path and the global path used below 11x11.
func TestClosedForm(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		a, b uint8
		size int
		want float64
	}{
		// (2*100*110 + 6.5025) / (100^2 + 110^2 + 6.5025)
		{"100_vs_110", 100, 110, 32, 0.9954764441},
		// (2*50*200 + 6.5025) / (50^2 + 200^2 + 6.5025)
		{"50_vs_200", 50, 200, 16, 0.4706692229},
		// black vs white: 6.5025 / (65025 + 6.5025)
		{"0_vs_255", 0, 255, 12, 0.0000999900},
		{"tiny_global_window", 100, 110, 5, 0.9954764441},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := Compare(uniform(tc.size, tc.a), uniform(tc.size, tc.b))
			if err != nil {
				t.Fatal(err)
			}
			if math.Abs(got.SSIM-tc.want) > 1e-9 {
				t.Errorf("SSIM = %.10f, want %.10f", got.SSIM, tc.want)
			}
		})
	}
}

func uniform(size int, v uint8) *image.Gray {
	img := image.NewGray(image.Rect(0, 0, size, size))
	for i := range img.Pix {
		img.Pix[i] = v
	}
	return img
}

// TestIdenticalIsZero: every decoder output type must score exactly SSIM 1 /
// DSSIM 0 against itself and against a copy in another pixel layout.
func TestIdenticalIsZero(t *testing.T) {
	t.Parallel()
	photo := decodeFile(t, "../../../testdata/fixtures/jpeg/baseline.jpg") // *image.YCbCr
	alpha := decodeFile(t, "../../../testdata/fixtures/png/rgba8.png")     // *image.NRGBA
	deep := decodeFile(t, "../../../testdata/fixtures/png/rgb16.png")      // *image.RGBA64
	pal := decodeFile(t, "../../../testdata/fixtures/png/palette.png")     // *image.Paletted
	tests := []struct {
		name string
		a, b image.Image
	}{
		{"ycbcr", photo, photo},
		{"ycbcr_vs_rgba", photo, toRGBA(photo)},
		{"nrgba", alpha, alpha},
		{"nrgba_vs_rgba", alpha, toRGBA(alpha)},
		{"rgba64", deep, deep},
		{"paletted", pal, pal},
		{"gray", uniform(20, 7), uniform(20, 7)},
		{"subimage_offset", toRGBA(photo).SubImage(image.Rect(10, 10, 60, 50)), toRGBA(photo).SubImage(image.Rect(10, 10, 60, 50))},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := Compare(tc.a, tc.b)
			if err != nil {
				t.Fatal(err)
			}
			if got.SSIM != 1 || got.DSSIM != 0 {
				t.Errorf("SSIM = %v, DSSIM = %v; want exactly 1 and 0", got.SSIM, got.DSSIM)
			}
		})
	}
}

func toRGBA(src image.Image) *image.RGBA {
	dst := image.NewRGBA(src.Bounds())
	draw.Draw(dst, dst.Bounds(), src, src.Bounds().Min, draw.Src)
	return dst
}

func TestErrors(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		a, b image.Image
		want error
	}{
		{"width", image.NewGray(image.Rect(0, 0, 10, 10)), image.NewGray(image.Rect(0, 0, 11, 10)), ErrSizeMismatch},
		{"height", image.NewRGBA(image.Rect(0, 0, 10, 10)), image.NewRGBA(image.Rect(0, 0, 10, 9)), ErrSizeMismatch},
		{"empty", image.NewGray(image.Rect(0, 0, 0, 0)), image.NewGray(image.Rect(0, 0, 0, 0)), ErrEmpty},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if _, err := Compare(tc.a, tc.b); !errors.Is(err, tc.want) {
				t.Errorf("err = %v, want %v", err, tc.want)
			}
		})
	}
}

// TestAlpha documents the alpha policy: alpha differences count, colour
// hidden under alpha 0 does not.
func TestAlpha(t *testing.T) {
	t.Parallel()
	base := func(alpha, hidden uint8) *image.NRGBA {
		img := image.NewNRGBA(image.Rect(0, 0, 32, 32))
		for y := range 32 {
			for x := range 32 {
				c := color.NRGBA{uint8(x * 8), uint8(y * 8), 90, 255}
				if x < 16 {
					c.A = alpha
					if alpha == 0 {
						c.R = hidden
					}
				}
				img.SetNRGBA(x, y, c)
			}
		}
		return img
	}
	tests := []struct {
		name     string
		a, b     image.Image
		wantZero bool
	}{
		{"alpha_differs", base(255, 0), base(128, 0), false},
		{"transparent_vs_opaque", base(0, 0), base(255, 0), false},
		{"hidden_colour_differs", base(0, 10), base(0, 250), true},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := Compare(tc.a, tc.b)
			if err != nil {
				t.Fatal(err)
			}
			if (got.DSSIM == 0) != tc.wantZero {
				t.Errorf("DSSIM = %v, want zero: %v", got.DSSIM, tc.wantZero)
			}
		})
	}
}

func TestHeatMap(t *testing.T) {
	t.Parallel()
	ref := decodeFile(t, filepath.Join(refDir, "ref.png"))
	res, err := Compare(ref, decodeFile(t, filepath.Join(refDir, "impulse.png")))
	if err != nil {
		t.Fatal(err)
	}
	hm := res.HeatMap()
	if got, want := hm.Bounds().Size(), (image.Point{160 - 10, 120 - 10}); got != want {
		t.Fatalf("heat map size = %v, want %v", got, want)
	}
	var buf bytes.Buffer
	if err := png.Encode(&buf, hm); err != nil {
		t.Fatal(err)
	}
	same, err := Compare(ref, ref)
	if err != nil {
		t.Fatal(err)
	}
	if c := same.HeatMap().RGBAAt(5, 5); c != (color.RGBA{0, 0, 0, 255}) {
		t.Errorf("identical heat map pixel = %v, want black", c)
	}
}

// BenchmarkCompare measures a VGA-sized photo pair (JPEG q85 re-encode) and
// a 1280x960 one.
func BenchmarkCompare(b *testing.B) {
	photo := toRGBA(decodeFile(b, "../../../testdata/fixtures/jpeg/baseline.jpg"))
	for _, scale := range []int{1, 4} {
		a := tile(photo, scale)
		var buf bytes.Buffer
		if err := jpeg.Encode(&buf, a, &jpeg.Options{Quality: 85}); err != nil {
			b.Fatal(err)
		}
		c, err := jpeg.Decode(&buf)
		if err != nil {
			b.Fatal(err)
		}
		sz := a.Bounds().Size()
		b.Run(sizeName(sz), func(b *testing.B) {
			b.ReportAllocs()
			b.SetBytes(int64(sz.X * sz.Y))
			for b.Loop() {
				if _, err := Compare(a, c); err != nil {
					b.Fatal(err)
				}
			}
		})
	}
}

func tile(src *image.RGBA, n int) *image.RGBA {
	s := src.Bounds().Size()
	dst := image.NewRGBA(image.Rect(0, 0, s.X*n, s.Y*n))
	for ty := range n {
		for tx := range n {
			draw.Draw(dst, image.Rect(tx*s.X, ty*s.Y, (tx+1)*s.X, (ty+1)*s.Y), src, image.Point{}, draw.Src)
		}
	}
	return dst
}

func sizeName(p image.Point) string { return fmt.Sprintf("%dx%d", p.X, p.Y) }

// corpusEntry is one URL built by the official SDKs
// (testdata/urlgen/generate.ts).
type corpusEntry struct {
	Name      string `json:"name"`
	Group     string `json:"group"` // urlgen, npm, signed
	URL       string `json:"url"`
	Path      string `json:"path"`
	Secret    string `json:"secret"`
	Algorithm string `json:"algorithm"` // sha1, sha256, sha256_long
}

func loadCorpus(tb testing.TB) []corpusEntry {
	tb.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", "urlgen", "corpus.json"))
	if err != nil {
		tb.Fatal(err)
	}
	var corpus []corpusEntry
	if err := json.Unmarshal(b, &corpus); err != nil {
		tb.Fatal(err)
	}
	return corpus
}

// corpusConfig picks the parser configuration an entry is checked with.
func corpusConfig(e *corpusEntry) string {
	switch e.Algorithm {
	case "sha1", "sha256_long":
		return "signed"
	case "sha256":
		return "sha256"
	}
	return ""
}

// TestSDKCorpus parses every URL generated by @cloudinary/url-gen and the
// cloudinary Node SDK; the expected requests are in golden/corpus.json.
// Signed entries must verify with the SDK's secret.
func TestSDKCorpus(t *testing.T) {
	t.Parallel()
	corpus := loadCorpus(t)
	if len(corpus) < 150 {
		t.Fatalf("corpus has %d entries, want >= 150", len(corpus))
	}
	cases := make([]testCase, 0, len(corpus))
	for i := range corpus {
		e := &corpus[i]
		if e.Secret != "" && e.Secret != apiSecret {
			t.Fatalf("%s: corpus secret differs from apiSecret", e.Name)
		}
		cases = append(cases, testCase{name: e.Name, cfg: corpusConfig(e), path: e.Path})
	}
	runGolden(t, "corpus", cases)

	for i := range corpus {
		e := &corpus[i]
		res, err := parse(t, corpusConfig(e), e.Path)
		switch {
		case e.Name == "fetch_plain" || e.Name == "fetch_query" || e.Name == "npm_fetch":
			if err != nil || res.Request.Source.Encoding != transform.SourcePlain {
				t.Errorf("%s: fetch source not plain: %v", e.Name, err)
			}
		case e.Group == "signed":
			if err != nil {
				t.Errorf("%s: %v", e.Name, err)
				continue
			}
			if res.Signature != sign.Verified {
				t.Errorf("%s: signature %v, want verified", e.Name, res.Signature)
			}
		}
	}
}

// TestUnpic parses the URLs of unpic's cloudinary provider tests
// (.refs/unpic/src/providers/cloudinary.test.ts), both the public shape
// (res.cloudinary.com/<cloud>/…) and the private-CDN / custom-domain shape
// (<cloud>-res.cloudinary.com/…, assets.custom.com/…) that unpic's
// privateRegex matches, and checks the width, height, format, quality and
// crop mode unpic's operations assert.
func TestUnpic(t *testing.T) {
	t.Parallel()
	type want struct {
		width, height int
		format        transform.Format
		autoFormat    bool // f_auto: negotiated, so Format stays unset
		quality       int
		resize        transform.ResizeType
		source, mount string
	}
	const id = "samples/animals/three-dogs.jpg"
	tests := []struct {
		name, url string
		want      want
	}{
		// extract: sampleImg, privateCdnImg, customDomainImg, operations.
		{
			"extract_public", "https://res.cloudinary.com/demo/image/upload/v1/samples/animals/three-dogs.jpg",
			want{format: transform.FormatJPEG, source: id, mount: "assets"},
		},
		{
			"extract_private_cdn", "https://demo-res.cloudinary.com/image/upload/v1/samples/animals/three-dogs.jpg",
			want{format: transform.FormatJPEG, source: id, mount: mountSource},
		},
		{
			"extract_custom_domain", "https://assets.custom.com/image/upload/v1/samples/animals/three-dogs.jpg",
			want{format: transform.FormatJPEG, source: id, mount: mountSource},
		},
		{
			"extract_operations", "https://res.cloudinary.com/demo/image/upload/w_300,h_200,c_fill/v1/folder/samples/animals/three-dogs.jpg",
			want{width: 300, height: 200, format: transform.FormatJPEG, resize: transform.ResizeFill, source: "folder/" + id, mount: "assets"},
		},
		// transform: the URLs unpic generates (defaults f_auto, c_lfill).
		{
			"transform_public_quality", "https://res.cloudinary.com/demo/image/upload/q_80,f_auto,c_lfill/v1/samples/animals/three-dogs.jpg",
			want{autoFormat: true, quality: 80, resize: transform.ResizeFillDown, source: id, mount: "assets"},
		},
		{
			"transform_private_cdn_size", "https://demo-res.cloudinary.com/image/upload/w_100,h_100,f_auto,c_lfill/v1/samples/animals/three-dogs.jpg",
			want{width: 100, height: 100, autoFormat: true, resize: transform.ResizeFillDown, source: id, mount: mountSource},
		},
		{
			"transform_custom_domain_fit", "https://assets.custom.com/image/upload/c_fit,f_auto/v1/samples/animals/three-dogs.jpg",
			want{autoFormat: true, resize: transform.ResizeFit, source: id, mount: mountSource},
		},
		// Signed and version-less shapes the regexes also accept.
		{
			"public_signed_shape", "https://res.cloudinary.com/demo/image/upload/s--AbCd1234--/w_640,f_auto,c_lfill/sample.png",
			want{width: 640, autoFormat: true, resize: transform.ResizeFillDown, source: "sample.png", mount: "assets"},
		},
		{
			"private_fetch_shape", "https://demo-res.cloudinary.com/image/fetch/w_640,q_75/https://example.com/a.webp",
			want{width: 640, quality: 75, resize: transform.ResizeFit, source: "https://example.com/a.webp"},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			u, err := url.Parse(tc.url)
			if err != nil {
				t.Fatal(err)
			}
			res, err := parse(t, "", u.EscapedPath())
			if err != nil {
				t.Fatal(err)
			}
			checkResult(t, res)
			r := res.Request
			pl := r.Pipelines[0]
			w := tc.want
			if pl.Resize.Width.Px != w.width || pl.Resize.Height.Px != w.height {
				t.Errorf("size %dx%d, want %dx%d", pl.Resize.Width.Px, pl.Resize.Height.Px, w.width, w.height)
			}
			if r.Output.Format != w.format {
				t.Errorf("format %v, want %v", r.Output.Format, w.format)
			}
			if w.autoFormat && r.Output.Format != transform.FormatUnset {
				t.Errorf("f_auto: format %v, want negotiated", r.Output.Format)
			}
			if r.Output.Quality != w.quality {
				t.Errorf("quality %d, want %d", r.Output.Quality, w.quality)
			}
			if w.resize != transform.ResizeUnset && pl.Resize.Type != w.resize {
				t.Errorf("resize %v, want %v", pl.Resize.Type, w.resize)
			}
			if res.SourceString != w.source || r.Source.Mount != w.mount {
				t.Errorf("source %q (mount %q), want %q (%q)", res.SourceString, r.Source.Mount, w.source, w.mount)
			}
			if len(r.Pipelines) != 1 {
				t.Errorf("%d pipelines, want 1", len(r.Pipelines))
			}
		})
	}
}

// TestParseUsesMountSource checks Parse passes the mount source through
// dialect.Input.
func TestParseUsesMountSource(t *testing.T) {
	t.Parallel()
	p := getFixture(t).parsers["nomap"]
	res, err := p.Parse(&dialect.Input{Path: "/image/upload/a.jpg", Mount: dialect.Mount{Source: "s"}})
	if err != nil {
		t.Fatal(err)
	}
	if res.Request.Source.Mount != "s" || res.Request.Source.Encoding != transform.SourceRelative {
		t.Errorf("source %+v", res.Request.Source)
	}
}

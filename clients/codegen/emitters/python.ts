// Python emitter (clients/python, package xtandard_image): writes
// src/xtandard_image/_generated/ from the spec.
//
//   options.py    one argument-tuple type alias per option, the options
//                 TypedDicts (every name and alias a key), the name tables
//   methods.py    the fluent builders' per-option methods (mixins)
//   constants.py  formats, containers, streams, query keys, imaginary,
//                 source schemes, signing and encryption constants, errors
//   responses.py  TypedDicts of the JSON bodies (InfoResponse, ErrorResponse)
//
// Python >= 3.10: Self, Unpack and Required come from typing_extensions
// before 3.11.
//
// This file is the refiner (WP-146): it lowers the neutral model (build.ts)
// into Python nodes (model.ts), which lang/python.ts prints.

import {
  catalogues,
  type CatalogueModel,
  defaultSegmentFormat,
  enums,
  imaginaryParams,
  nativeVideoKeys,
  type OptionModel,
  queryKeyNames,
  refName,
  responseSchemas,
  schemaTypes,
} from "../build.ts";
import { isIdent, ident, PythonPrinter } from "../lang/python.ts";
import { pascal, type Shape } from "../lib.ts";
import { type Expr, N, type Node, type TypeRef, union } from "../model.ts";
import type { CatalogueKind, Emitter, JSONSchema, Spec, SpecArg } from "../spec.ts";

const pkg = "clients/python/src/xtandard_image/_generated/";
const printer = new PythonPrinter();

/** Builder methods the per-option methods must not shadow. */
export const reservedMethods = new Set(["option", "options", "pipeline", "extension", "encoding", "with_pdf_password", "build", "param"]);

// ---- names and types ---------------------------------------------------------------

const t = (name: string, ...args: TypeRef[]) => N.tref(name, args);
const id = N.id;
const lit = (s: string) => N.tlit(N.str(s));
const literal = (values: readonly string[], layout: "auto" | "expanded" = "auto") => N.tref("Literal", values.map(lit), { layout });
const none = t("None");
const nullable = (x: TypeRef) => N.tunion([x, none]);
/** A union of distinct members; no member at all is `object`. */
const anyOf = (parts: readonly TypeRef[]) => (parts.length === 0 ? t("object") : union(parts));

/** The module docstring: what the file holds and the generated-code notice. */
const header = (what: string) =>
  N.doc([what, "", "Code generated by clients/codegen/emitters/python.ts from clients/spec/spec.json.", "DO NOT EDIT. Run `task clients:generate`.", ""].join("\n"));

/** `if sys.version_info >= (3, 11): from typing import X else: from typing_extensions import X`. */
const typingBackport = (name: string) =>
  N.if(
    N.binary(">=", N.get(id("sys"), "version_info"), N.tuple([N.int(3), N.int(11)])),
    [N.imp("typing", [name])],
    [N.imp("typing_extensions", [name])],
  );

/** The Python type of one argument. */
function argType(a: SpecArg): TypeRef {
  let x: TypeRef;
  switch (a.type) {
    case "integer":
      x = t("int");
      break;
    case "number":
      x = t("float");
      break;
    case "boolean":
      x = t("bool");
      break;
    case "enum":
      x = literal(a.enum ?? []);
      break;
    case "direction":
      x = N.tunion([literal(["down", "up", "left", "right"]), t("float")]);
      break;
    default:
      x = t("str");
  }
  return a.nullable ? nullable(x) : x;
}

/** tuple[a, b] or tuple[a, Unpack[tuple[rest, ...]]]. */
function shapeType(s: Shape): TypeRef {
  const elems = s.fixed.map(argType);
  if (s.rest) elems.push(t("Unpack", t("tuple", anyOf(s.rest.map(argType)), t("..."))));
  return N.tref("tuple", elems);
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };
const argsAlias = (o: OptionModel) => `${kindPrefix[o.kind]}${pascal(o.name)}Args`;
const valueAlias = (o: OptionModel) => `${kindPrefix[o.kind]}${pascal(o.name)}Value`;
const upper = (kind: CatalogueKind) => kind.toUpperCase();

function optionDoc(o: OptionModel): string {
  return [o.spec.doc, "", `URL names: ${o.names.join(", ")}; arguments ${o.spec.syntax}; default ${o.spec.default}.`, `${o.tags.join("; ")}.`].join(
    "\n",
  );
}

/** A TypedDict in its functional form (keys need not be identifiers): Name = TypedDict("Name", {…}, total=False). */
function typedDict(name: string, keys: readonly (readonly [string, TypeRef])[], doc: string): Node {
  const fields = N.map(
    keys.map(([k, v]) => N.entry(N.str(k), N.typeExpr(v))),
    { layout: "expanded" },
  );
  return N.const(name, N.call(id("TypedDict"), [N.str(name), fields, N.named("total", N.bool(false))], { layout: "expanded" }), {
    doc: N.doc(doc),
  });
}

/** A table constant: NAME: Final[Mapping[…]] = {k: v, …} (one entry per line). */
const table = (name: string, type: TypeRef, entries: readonly (readonly [Expr, Expr])[], doc?: string) =>
  N.const(name, N.map(entries.map(([k, v]) => N.entry(k, v)), { layout: "expanded" }), {
    type: t("Final", type),
    ...(doc === undefined ? {} : { doc: N.doc(doc) }),
  });

const mapping = (k: TypeRef, v: TypeRef) => t("Mapping", k, v);
const str = t("str");
const final = (name: string, value: Expr, doc?: string) =>
  N.const(name, value, { type: t("Final"), ...(doc === undefined ? {} : { doc: N.doc(doc) }) });
const tuple = (values: readonly (string | number)[]) => N.tuple(values.map(N.scalar));
const allOf = (names: readonly string[]) => N.const("__all__", N.list(names.map(N.str)));

// ---- options.py ----------------------------------------------------------------------

function catalogueItems(c: CatalogueModel): Node[] {
  const { kind } = c;
  const K = kindPrefix[kind];
  const out: Node[] = [N.line(`---- ${kind} ${"-".repeat(70 - kind.length)}`), N.blank()];
  for (const o of c.options) {
    const variants = o.shapes.map(shapeType);
    out.push(N.typeAlias(argsAlias(o), variants.length === 1 ? variants[0]! : N.tunion(variants), { doc: N.doc(`Argument tuples of ${kind} option \`${o.name}\`. ${o.spec.doc}`) }));
    const bare = o.bare.map((a) => argType({ ...a, nullable: false }));
    out.push(N.typeAlias(valueAlias(o), bare.length ? N.tunion([t(argsAlias(o)), anyOf(bare)]) : t(argsAlias(o))));
    out.push(N.blank());
  }
  out.push(
    typedDict(
      `${K}Options`,
      c.names.map(([n, canonical]) => [n, nullable(t(valueAlias(c.byName.get(canonical)!)))] as const),
      `${kind} options of one pipeline, keyed by canonical name or alias, in URL order. A value is the argument tuple, ` +
        'or the first argument alone when the rest are optional: `{"rs": ("fill", 300, 400), "q": 80}`. None inside a tuple is an empty argument; ' +
        "a None value skips the option.",
    ),
    N.blank(),
    N.typeAlias(`${K}OptionName`, literal(c.names.map(([n]) => n), "expanded"), { doc: N.doc(`Every ${kind} option name and alias.`) }),
    N.blank(),
    table(
      `${upper(kind)}_NAMES`,
      mapping(str, str),
      c.names.map(([n, canonical]) => [N.str(n), N.str(canonical)]),
      `${kind} option name or alias to canonical name.`,
    ),
    N.blank(),
    table(
      `${upper(kind)}_SHORT`,
      mapping(str, str),
      c.options.map((o) => [N.str(o.name), N.str(o.short)]),
      `Canonical ${kind} option name to the name builders write by default (the shortest).`,
    ),
    N.blank(),
  );
  return out;
}

function emitOptions(spec: Spec): Node {
  const cats = catalogues(spec);
  return N.file([
    header("Typed option tables of the processing, /info and /video catalogues."),
    N.blank(),
    N.imp("sys"),
    N.imp("collections.abc", ["Mapping"]),
    N.imp("typing", ["Final", "Literal", "TypedDict"]),
    N.blank(),
    typingBackport("Unpack"),
    N.blank(),
    ...cats.flatMap(catalogueItems),
    allOf(cats.flatMap(({ kind }) => [`${kindPrefix[kind]}Options`, `${kindPrefix[kind]}OptionName`, `${upper(kind)}_NAMES`, `${upper(kind)}_SHORT`])),
  ]);
}

// ---- methods.py ----------------------------------------------------------------------

function methodsMixin(c: CatalogueModel): Node {
  const { kind } = c;
  const self = N.param("self");
  const members: Node[] = [
    N.blank(),
    N.const("__slots__", N.tuple([])),
    N.blank(),
    N.func("option", [self, N.param("name", str), N.param("args", t("Arg"), { mods: ["variadic"] })], [N.throw(id("NotImplementedError"))], {
      returns: t("Self"),
      doc: N.doc("Appends one option occurrence."),
    }),
  ];
  const used = new Map<string, string>();
  for (const o of c.options) {
    const elem = anyOf(o.args.map(argType));
    for (const n of o.names) {
      const name = ident(n);
      if (reservedMethods.has(name)) throw new Error(`${kind} option ${n} collides with the builder method ${name}`);
      const prev = used.get(name);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Python method ${name}`);
      used.set(name, n);
      members.push(
        N.blank(),
        N.func(name, [self, N.param("args", elem, { mods: ["variadic"] })], [N.ret(N.invoke(id("self"), "option", [N.str(n), N.spread(id("args"))]))], {
          returns: t("Self"),
          doc: N.doc(optionDoc(o)),
        }),
      );
    }
  }
  return N.type("class", `${kindPrefix[kind]}Methods`, members, {
    doc: N.doc(`One method per ${kind} option name and alias; each appends that option, written with the name as called.`),
  });
}

function emitMethods(spec: Spec): Node {
  const [processing, info, video] = catalogues(spec) as [CatalogueModel, CatalogueModel, CatalogueModel];
  return N.file([
    header("Per-option methods of the fluent URL builders."),
    N.blank(),
    N.imp("sys"),
    N.imp("typing", ["Literal"]),
    N.blank(),
    typingBackport("Self"),
    N.blank(),
    N.typeAlias("Arg", N.tunion([str, t("int"), t("float"), t("bool"), none]), { doc: N.doc("One argument as written in a URL: booleans are 1/0, None is empty.") }),
    N.blank(),
    N.blank(),
    methodsMixin(processing),
    N.blank(),
    N.blank(),
    methodsMixin(info),
    N.blank(),
    N.blank(),
    methodsMixin(video),
    N.blank(),
    allOf(["Arg", "InfoMethods", "ProcessingMethods", "VideoMethods"]),
  ]);
}


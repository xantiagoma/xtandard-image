// Python emitter (clients/python, package xtandard_image): writes
// src/xtandard_image/_generated/ from the spec.
//
//   options.py    one argument-tuple type alias per option, the options
//                 TypedDicts (every name and alias a key), the name tables
//   methods.py    the fluent builders' per-option methods (mixins)
//   constants.py  formats, containers, streams, query keys, imaginary,
//                 source schemes, signing and encryption constants, errors
//   responses.py  TypedDicts of the JSON bodies (InfoResponse, ErrorResponse)
//
// Python >= 3.10: Self, Unpack and Required come from typing_extensions
// before 3.11.

import { allArgs, bareArgs, nameTable, pascal, type Shape, shapes } from "../lib.ts";
import type { CatalogueKind, Emitter, JSONSchema, Spec, SpecArg, SpecOption } from "../spec.ts";

const pkg = "clients/python/src/xtandard_image/_generated/";

const header = (what: string) =>
  [
    `"""${what}`,
    "",
    "Code generated by clients/codegen/emitters/python.ts from clients/spec/spec.json.",
    "DO NOT EDIT. Run `task clients:generate`.",
    '"""',
    "",
  ].join("\n");

const keywords = new Set(
  ("False None True and as assert async await break class continue def del elif else except finally for from " +
    "global if import in is lambda nonlocal not or pass raise return try while with yield").split(" "),
);

/** Builder methods the per-option methods must not shadow. */
export const reservedMethods = new Set([
  "option",
  "options",
  "pipeline",
  "extension",
  "encoding",
  "with_pdf_password",
  "build",
  "param",
]);

/** A Python identifier for an option name or alias. */
function ident(name: string): string {
  let id = name.replace(/[^A-Za-z0-9_]/g, "_");
  if (/^[0-9]/.test(id)) id = `_${id}`;
  return keywords.has(id) ? `${id}_` : id;
}

const str = (s: string) => JSON.stringify(s);

function doc(text: string, indent: string): string {
  const t = text.replaceAll("\\", "\\\\").replaceAll('"""', '\\"\\"\\"').trim();
  const lines = t.split("\n").map((l, i) => (i === 0 || l === "" ? l : indent + l));
  return `${indent}"""${lines.join("\n")}${lines.length > 1 ? `\n${indent}` : ""}"""`;
}

function union(parts: string[]): string {
  const uniq = [...new Set(parts)];
  return uniq.length === 0 ? "object" : uniq.join(" | ");
}

/** The Python type of one argument. */
function argType(a: SpecArg): string {
  let t: string;
  switch (a.type) {
    case "integer":
      t = "int";
      break;
    case "number":
      t = "float";
      break;
    case "boolean":
      t = "bool";
      break;
    case "enum":
      t = `Literal[${(a.enum ?? []).map(str).join(", ")}]`;
      break;
    case "direction":
      t = 'Literal["down", "up", "left", "right"] | float';
      break;
    default:
      t = "str";
  }
  return a.nullable ? `${t} | None` : t;
}

function shapeType(s: Shape): string {
  const elems = s.fixed.map(argType);
  if (s.rest) elems.push(`Unpack[tuple[${union(s.rest.map(argType))}, ...]]`);
  return `tuple[${elems.join(", ")}]`;
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

function argsAlias(kind: CatalogueKind, o: SpecOption): string {
  return `${kindPrefix[kind]}${pascal(o.name)}Args`;
}

function valueAlias(kind: CatalogueKind, o: SpecOption): string {
  return `${kindPrefix[kind]}${pascal(o.name)}Value`;
}

function optionDoc(o: SpecOption): string {
  const lines = [o.doc, "", `URL names: ${[o.name, ...o.aliases].join(", ")}; arguments ${o.syntax}; default ${o.default}.`];
  const tags: string[] = [];
  if (o.milestone) tags.push(`milestone ${o.milestone}`);
  tags.push(`scope ${o.scope}`);
  if (o.pro) tags.push("imgproxy Pro option (free here)");
  if (o.security) tags.push("security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS)");
  if (o.removed) tags.push("removed: accepted and ignored");
  lines.push(`${tags.join("; ")}.`);
  return lines.join("\n");
}

function emitOptions(spec: Spec): string {
  const out: string[] = [header("Typed option tables of the processing, /info and /video catalogues.")];
  out.push("import sys");
  out.push("from collections.abc import Mapping");
  out.push("from typing import Final, Literal, TypedDict");
  out.push("");
  out.push("if sys.version_info >= (3, 11):");
  out.push("    from typing import Unpack");
  out.push("else:");
  out.push("    from typing_extensions import Unpack");
  out.push("");
  const exports: string[] = [];
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    const K = kindPrefix[kind];
    out.push(`# ---- ${kind} ${"-".repeat(70 - kind.length)}`);
    out.push("");
    for (const o of opts) {
      const variants = shapes(o).map(shapeType);
      out.push(`${argsAlias(kind, o)} = ${variants.length === 1 ? variants[0] : variants.join(" | ")}`);
      out.push(doc(`Argument tuples of ${kind} option \`${o.name}\`. ${o.doc}`, ""));
      const bare = bareArgs(o).map((a) => argType({ ...a, nullable: false }));
      out.push(`${valueAlias(kind, o)} = ${bare.length ? `${argsAlias(kind, o)} | ${union(bare)}` : argsAlias(kind, o)}`);
      out.push("");
    }
    const names = nameTable(opts);
    const byName = new Map(opts.map((o) => [o.name, o]));
    out.push(`${K}Options = TypedDict(`);
    out.push(`    ${str(`${K}Options`)},`);
    out.push("    {");
    for (const [n, canonical] of names) out.push(`        ${str(n)}: ${valueAlias(kind, byName.get(canonical)!)} | None,`);
    out.push("    },");
    out.push("    total=False,");
    out.push(")");
    out.push(
      doc(
        `${kind} options of one pipeline, keyed by canonical name or alias, in URL order. A value is the argument tuple, ` +
          "or the first argument alone when the rest are optional: `{\"rs\": (\"fill\", 300, 400), \"q\": 80}`. None inside a tuple is an empty argument; " +
          "a None value skips the option.",
        "",
      ),
    );
    out.push("");
    out.push(`${K}OptionName = Literal[`);
    for (const [n] of names) out.push(`    ${str(n)},`);
    out.push("]");
    out.push(doc(`Every ${kind} option name and alias.`, ""));
    out.push("");
    out.push(`${kind.toUpperCase()}_NAMES: Final[Mapping[str, str]] = {`);
    for (const [n, c] of names) out.push(`    ${str(n)}: ${str(c)},`);
    out.push("}");
    out.push(doc(`${kind} option name or alias to canonical name.`, ""));
    out.push("");
    out.push(`${kind.toUpperCase()}_SHORT: Final[Mapping[str, str]] = {`);
    for (const o of opts) out.push(`    ${str(o.name)}: ${str(o.short)},`);
    out.push("}");
    out.push(doc(`Canonical ${kind} option name to the name builders write by default (the shortest).`, ""));
    out.push("");
    exports.push(`${K}Options`, `${K}OptionName`, `${kind.toUpperCase()}_NAMES`, `${kind.toUpperCase()}_SHORT`);
  }
  out.push(`__all__ = [${exports.map(str).join(", ")}]`);
  out.push("");
  return out.join("\n");
}

function methodsMixin(spec: Spec, kind: CatalogueKind): string {
  const K = kindPrefix[kind];
  const out: string[] = [];
  out.push(`class ${K}Methods:`);
  out.push(doc(`One method per ${kind} option name and alias; each appends that option, written with the name as called.`, "    "));
  out.push("");
  out.push("    __slots__ = ()");
  out.push("");
  out.push("    def option(self, name: str, *args: Arg) -> Self:");
  out.push('        """Appends one option occurrence."""');
  out.push("        raise NotImplementedError");
  const used = new Map<string, string>();
  for (const o of spec.options[kind]) {
    const elem = union(allArgs(o).map(argType));
    for (const n of [o.name, ...o.aliases]) {
      const id = ident(n);
      if (reservedMethods.has(id)) throw new Error(`${kind} option ${n} collides with the builder method ${id}`);
      const prev = used.get(id);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Python method ${id}`);
      used.set(id, n);
      out.push("");
      out.push(`    def ${id}(self, *args: ${elem}) -> Self:`);
      out.push(doc(optionDoc(o), "        "));
      out.push(`        return self.option(${str(n)}, *args)`);
    }
  }
  out.push("");
  return out.join("\n");
}

function emitMethods(spec: Spec): string {
  const out: string[] = [header("Per-option methods of the fluent URL builders.")];
  out.push("import sys");
  out.push("from typing import Literal");
  out.push("");
  out.push("if sys.version_info >= (3, 11):");
  out.push("    from typing import Self");
  out.push("else:");
  out.push("    from typing_extensions import Self");
  out.push("");
  out.push("Arg = str | int | float | bool | None");
  out.push('"""One argument as written in a URL: booleans are 1/0, None is empty."""');
  out.push("");
  out.push("");
  out.push(methodsMixin(spec, "processing"));
  out.push("");
  out.push(methodsMixin(spec, "info"));
  out.push("");
  out.push(methodsMixin(spec, "video"));
  out.push('__all__ = ["Arg", "InfoMethods", "ProcessingMethods", "VideoMethods"]');
  out.push("");
  return out.join("\n");
}

function literal(name: string, values: readonly string[], text: string): string[] {
  return [`${name} = Literal[${values.map(str).join(", ")}]`, doc(text, ""), ""];
}

function tuple(values: readonly (string | number)[]): string {
  const items = values.map((v) => (typeof v === "string" ? str(v) : String(v)));
  return items.length === 1 ? `(${items[0]},)` : `(${items.join(", ")})`;
}


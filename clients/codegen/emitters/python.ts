// ---- responses.py --------------------------------------------------------------------

const scalars: Record<string, string> = { string: "str", integer: "int", number: "float", boolean: "bool", null: "None" };

function schemaType(s: JSONSchema): TypeRef {
  if (s.$ref) return t(refName(s.$ref));
  const types = schemaTypes(s);
  if (s.enum) {
    const x = N.tref(
      "Literal",
      s.enum.filter((v) => v !== null).map((v) => N.tlit(N.scalar(v as string | number))),
    );
    return s.enum.includes(null) || types.includes("null") ? nullable(x) : x;
  }
  const parts: TypeRef[] = types.map((ty) => {
    if (scalars[ty]) return t(scalars[ty]);
    if (ty === "array") return t("list", s.items ? schemaType(s.items) : t("Any"));
    if (ty === "object") {
      if (s.properties) throw new Error("inline object schemas are not supported");
      return t("dict", str, typeof s.additionalProperties === "object" ? schemaType(s.additionalProperties) : t("Any"));
    }
    return t("Any");
  });
  if (parts.length === 0) return t("Any");
  // None last, as Python style has it.
  const isNone = (p: TypeRef) => p.k === "tref" && p.name === "None";
  return anyOf([...parts.filter((p) => !isNone(p)), ...parts.filter(isNone)]);
}

function emitResponses(spec: Spec): Node {
  const schemas = responseSchemas(spec);
  const items: Node[] = [
    header("TypedDicts of the JSON response bodies (the OpenAPI components)."),
    N.blank(),
    N.imp("__future__", ["annotations"]),
    N.blank(),
    N.imp("sys"),
    N.imp("typing", ["Any", "Literal", "TypedDict"]),
    N.blank(),
    typingBackport("Required"),
    N.blank(),
  ];
  for (const sm of schemas) {
    const fields: Node[] = [N.blank()];
    for (const [p, ps] of sm.properties) {
      if (!isIdent(p)) throw new Error(`${sm.name}.${p} is not a Python identifier`);
      const x = schemaType(ps);
      fields.push(N.field(p, sm.required.has(p) ? t("Required", x) : x, ps.description ? { doc: N.doc(ps.description) } : {}));
    }
    items.push(
      N.blank(),
      N.blank(),
      N.type("class", sm.name, fields, {
        supers: [t("TypedDict")],
        params: [N.param("total", undefined, { value: N.bool(false) })],
        doc: N.doc(sm.schema.description ?? sm.name),
      }),
    );
  }
  items.push(N.blank(), allOf(schemas.map((s) => s.name)));
  return N.file(items);
}

export const emitter: Emitter = {
  language: "python",
  emit(spec) {
    const files: Record<string, Node> = {
      "__init__.py": N.file([header("Generated tables; import from xtandard_image instead.")]),
      "options.py": emitOptions(spec),
      "methods.py": emitMethods(spec),
      "constants.py": emitConstants(spec),
      "responses.py": emitResponses(spec),
    };
    return Object.fromEntries(Object.entries(files).map(([f, n]) => [`${pkg}${f}`, printer.print(n)]));
  },
};

// .NET emitter (clients/dotnet, NuGet Xtandard.Image): writes
// src/Xtandard.Image/Generated/ from the spec.
//
//   OptionCatalog.g.cs     the name tables (name or alias to canonical,
//                          canonical to short) of the three catalogues
//   ProcessingChain.g.cs   the fluent builders' per-option methods, one per
//   InfoChain.g.cs         name and alias, typed from the option's forms
//   VideoChain.g.cs        (generic CRTP base classes of the chains)
//   ProcessingOption.g.cs  the typed option records (one per option, one
//   InfoOption.g.cs        constructor per argument form) that the options
//   VideoOption.g.cs       collections accept
//   Constants.g.cs         formats, containers, streams, query keys,
//                          imaginary, sources, signing, encryption, URL
//                          constants and error kinds
//   Responses.g.cs         the JSON bodies (InfoResponse, ErrorResponse, …)
//                          and their source-generated JsonSerializerContext
//
// Argument types: integer → long, number → double, boolean → bool,
// direction → OptionArg (a name or an angle), everything else → string.
// Every file is `// <auto-generated/>`, so analyzers and `dotnet format`
// skip it.


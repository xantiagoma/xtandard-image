const str = (s: string) => JSON.stringify(s);

function camel(name: string): string {
  const p = pascal(name);
  const id = p.length === 0 ? "arg" : p[0]!.toLowerCase() + p.slice(1);
  return keywords.has(id) ? `@${id}` : id;
}

/** A C# type or member name for an option name or alias ("c_obj" → "CObj", "min-width" → "MinWidth"). */
function member(name: string): string {
  const p = pascal(name);
  return /^[0-9]/.test(p) ? `_${p}` : p;
}

function plural(name: string): string {
  const w = words(name);
  const last = w.pop() ?? "value";
  const pl = /(s|x|ch|sh)$/.test(last) ? `${last}es` : /[^aeiou]y$/.test(last) ? `${last.slice(0, -1)}ies` : `${last}s`;
  return camel([...w, pl].join("_"));
}

/** XML-escapes doc text and turns `code` spans into <c>code</c>. */
function xml(s: string): string {
  return s
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replace(/`([^`\n]+)`/g, "<c>$1</c>");
}

/** A `///` comment block from paragraphs; each line prefixed by indent. */
function docLines(indent: string, tag: string, text: string, attrs = ""): string[] {
  const lines = xml(text.trim()).split("\n");
  if (lines.length === 1) return [`${indent}/// <${tag}${attrs}>${lines[0]}</${tag}>`];
  return [`${indent}/// <${tag}${attrs}>`, ...lines.map((l) => `${indent}/// ${l}`.trimEnd()), `${indent}/// </${tag}>`];
}

/** The C# type of one argument (non-nullable form). */
function baseType(a: SpecArg): string {
  switch (a.type) {
    case "integer":
      return "long";
    case "number":
      return "double";
    case "boolean":
      return "bool";
    case "direction":
      return "OptionArg";
    default:
      return "string";
  }
}

function nullableType(a: SpecArg): string {
  // OptionArg has its own empty value (OptionArg.Null).
  return a.type === "direction" ? "OptionArg" : `${baseType(a)}?`;
}

function argDoc(a: SpecArg): string {
  const parts: string[] = [];
  if (a.doc) parts.push(a.doc.replace(/\.?$/, "."));
  else parts.push(`${a.name.replaceAll("_", " ")} (${a.type}).`);
  if (a.enum?.length) parts.push(`One of ${a.enum.map((v) => `\`${v}\``).join(", ")}.`);
  if (a.type === "direction") parts.push("A direction (`down`, `up`, `left`, `right`) or an angle in degrees.");
  if (a.type === "base64") parts.push("URL-safe base64, written as given.");
  if (a.type === "color") parts.push("A hex colour (`ff0000`, `f00`, with optional alpha).");
  const range: string[] = [];
  if (a.min !== undefined) range.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) range.push(`≤ ${a.max}`);
  if (range.length) parts.push(`Range ${range.join(", ")}.`);
  if (a.nullable) parts.push("Null writes an empty argument.");
  return parts.join(" ");
}

interface Param {
  readonly name: string;
  readonly type: string;
  readonly arg: SpecArg;
  /** Enum values accepted here, across the forms merged into this parameter. */
  readonly enums: Set<string>;
  readonly optional: boolean;
}

function paramDoc(p: Param): string {
  return argDoc(p.enums.size ? { ...p.arg, enum: [...p.enums] } : p.arg);
}

const erased = (t: string) => t.replace(/^string\?$/, "string");

/** One C# overload of an option: positional parameters and an optional params group. */
interface Signature {
  readonly params: Param[];
  readonly required: number;
  readonly rest?: { readonly name: string; readonly type: string; readonly elems: { name: string; type: string }[]; readonly doc: string };
}

function uniqueName(name: string, used: Set<string>): string {
  let n = name;
  for (let i = 2; used.has(n); i++) n = `${name}${i}`;
  used.add(n);
  return n;
}

/**
 * The overloads of an option. A form without a rest group is one
 * signature: its first max(min_items, 1) arguments are required and the rest
 * optional (trailing nulls are not written). A form with a rest group gives
 * the shorter prefixes as one such signature and the full form (with the
 * rest elements that min_items requires) plus a `params` group. A
 * signature without a rest group whose parameter types start another such
 * signature with no more required parameters is folded into it (calls would
 * be ambiguous), merging the enum values of its parameters into the docs.
 */
function signatures(o: SpecOption): Signature[] {
  const all: Signature[] = [];
  const positional = (args: readonly SpecArg[], required: number, used: Set<string>): Param[] =>
    args.map((a, i) => ({
      name: uniqueName(camel(a.name), used),
      type: i < required ? (a.nullable ? nullableType(a) : baseType(a)) : nullableType(a),
      arg: a,
      enums: new Set(a.enum ?? []),
      optional: i >= required,
    }));
  for (const f of o.forms) for (const s of formSignatures(f, positional)) if (s.params.length > 0 || s.rest) all.push(s);
  const covers = (b: Signature, a: Signature) =>
    !a.rest &&
    !b.rest &&
    b.params.length >= a.params.length &&
    b.required <= a.required &&
    a.params.every((p, i) => erased(p.type) === erased(b.params[i]!.type));
  const out: Signature[] = [];
  all.forEach((a, i) => {
    const into = all.find((b, j) => j !== i && covers(b, a) && (!covers(a, b) || j < i));
    if (into === undefined) {
      const key = JSON.stringify([a.params.map((p) => erased(p.type)), a.rest?.type]);
      if (!out.some((x) => JSON.stringify([x.params.map((p) => erased(p.type)), x.rest?.type]) === key)) out.push(a);
      return;
    }
    a.params.forEach((p, k) => {
      for (const e of p.enums) into.params[k]!.enums.add(e);
    });
  });
  return out;
}

function formSignatures(
  f: SpecForm,
  positional: (args: readonly SpecArg[], required: number, used: Set<string>) => Param[],
): Signature[] {
  const min = Math.max(f.min_items, 1);
  const n = f.args.length;
  if (!f.rest || f.rest.length === 0) {
    const required = Math.min(min, n);
    return [{ params: positional(f.args, required, new Set()), required }];
  }
  const out: Signature[] = [];
  if (n > 1 && min < n) {
    const prefix = f.args.slice(0, n - 1);
    const required = Math.min(min, prefix.length);
    out.push({ params: positional(prefix, required, new Set()), required });
  }
  const fixed = [...f.args];
  for (let i = 0; fixed.length < min; i++) fixed.push(f.rest[i % f.rest.length]!);
  const used = new Set<string>();
  const params = positional(fixed, fixed.length, used);
  const rest = f.rest;
  const restDoc = `Repeated ${rest.length === 1 ? "argument" : "groups"}: ${rest.map((a) => `${a.name} — ${argDoc(a)}`).join(" ")}`;
  if (rest.length === 1) {
    const r = rest[0]!;
    out.push({
      params,
      required: params.length,
      rest: { name: uniqueName(plural(r.name), used), type: `${baseType(r)}[]`, elems: [], doc: restDoc },
    });
  } else {
    const elems = rest.map((a) => ({ name: member(a.name), type: baseType(a) }));
    out.push({
      params,
      required: params.length,
      rest: {
        name: uniqueName("groups", used),
        type: `(${elems.map((e) => `${e.type} ${e.name}`).join(", ")})[]`,
        elems,
        doc: restDoc,
      },
    });
  }
  return out;
}

function paramList(s: Signature): string {
  const ps = s.params.map((p) => `${p.type} ${p.name}${p.optional ? (p.type === "OptionArg" ? " = default" : " = null") : ""}`);
  if (s.rest) ps.push(`params ${s.rest.type} ${s.rest.name}`);
  return ps.join(", ");
}

/** The expression building the OptionArg[] of a signature without a rest group. */
function argsExpr(s: Signature): string {
  const list = `[${s.params.map((p) => p.name).join(", ")}]`;
  return s.params.some((p) => p.optional) ? `OptionArgs.Trim(${list}, ${s.required})` : list;
}

/** Statements collecting the OptionArg list `args` of a signature with a rest group. */
function restStatements(s: Signature, indent: string): string[] {
  const r = s.rest!;
  const width = Math.max(r.elems.length, 1);
  const init = s.params.length ? ` { ${s.params.map((p) => p.name).join(", ")} }` : "";
  const lines = [
    `${indent}ArgumentNullException.ThrowIfNull(${r.name});`,
    `${indent}var args = new List<OptionArg>(${s.params.length} + (${r.name}.Length * ${width}))${init};`,
    `${indent}foreach (var e in ${r.name})`,
    `${indent}{`,
  ];
  if (r.elems.length === 0) lines.push(`${indent}    args.Add(e);`);
  else for (const el of r.elems) lines.push(`${indent}    args.Add(e.${el.name});`);
  lines.push(`${indent}}`, "");
  return lines;
}

/** The body of a chain method. */
function argsBody(s: Signature, indent: string, finish: (args: string) => string): string[] {
  if (!s.rest) return [`${indent}=> ${finish(argsExpr(s))};`];
  return [`${indent.slice(4)}{`, ...restStatements(s, indent), `${indent}return ${finish("[.. args]")};`, `${indent.slice(4)}}`];
}

function optionSummary(o: SpecOption): string {
  return o.doc.trim().replace(/\.?$/, ".");
}

function optionRemarks(o: SpecOption): string {
  const tags: string[] = [];
  tags.push(`URL names: ${[o.name, ...o.aliases].map((n) => `\`${n}\``).join(", ")}; arguments \`${o.syntax}\`; default ${o.default}.`);
  if (o.milestone) tags.push(`Milestone ${o.milestone}; scope ${o.scope}.`);
  else tags.push(`Scope ${o.scope}.`);
  if (o.pro) tags.push("imgproxy Pro option (free here).");
  if (o.security) tags.push("Security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS).");
  if (o.removed) tags.push("Removed: accepted and ignored.");
  return tags.join(" ");
}

function signatureDocs(o: SpecOption, s: Signature, indent: string, returns: string): string[] {
  const out = [...docLines(indent, "summary", optionSummary(o)), ...docLines(indent, "remarks", optionRemarks(o))];
  for (const p of s.params) out.push(...docLines(indent, "param", paramDoc(p), ` name="${p.name.replace(/^@/, "")}"`));
  if (s.rest) out.push(...docLines(indent, "param", s.rest.doc, ` name="${s.rest.name.replace(/^@/, "")}"`));
  if (returns) out.push(...docLines(indent, "returns", returns));
  return out;
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

function emitChain(spec: Spec, kind: CatalogueKind): string {
  const K = kindPrefix[kind];
  const out: string[] = [header(`Per-option methods of the fluent ${kind} URL builders.`)];
  out.push("namespace Xtandard.Image;", "");
  out.push(
    ...docLines(
      "",
      "summary",
      `The ${kind} option methods of a fluent URL builder: one per option name and alias, each appending that option written with the name as called.`,
    ),
  );
  out.push(`/// <typeparam name="TSelf">The concrete builder, returned by every method.</typeparam>`);
  out.push(`public abstract partial class ${K}Chain<TSelf> : OptionChain<TSelf>`);
  out.push(`    where TSelf : ${K}Chain<TSelf>`);
  out.push("{");
  out.push(`    private protected ${K}Chain(ChainState state)`);
  out.push("        : base(state)");
  out.push("    {");
  out.push("    }");
  const used = new Map<string, string>();
  for (const o of spec.options[kind]) {
    const sigs = signatures(o);
    for (const n of [o.name, ...o.aliases]) {
      const id = member(n);
      if (reservedMethods.has(id)) throw new Error(`${kind} option ${n} collides with the builder method ${id}`);
      const prev = used.get(id);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the C# method ${id}`);
      used.set(id, n);
      for (const s of sigs) {
        out.push("");
        out.push(...signatureDocs(o, s, "    ", "This builder."));
        out.push(`    public TSelf ${id}(${paramList(s)})`);
        out.push(...argsBody(s, "        ", (args) => `Option(${str(n)}, ${args})`));
      }
    }
  }
  out.push("}", "");
  return out.join("\n");
}

function emitOptionRecords(spec: Spec, kind: CatalogueKind): string {
  const K = kindPrefix[kind];
  const out: string[] = [header(`Typed ${kind} option records.`)];
  out.push("namespace Xtandard.Image;", "");
  out.push(`public abstract partial record ${K}Option`, "{");
  const used = new Set<string>();
  let first = true;
  for (const o of spec.options[kind]) {
    const id = member(o.name);
    if (used.has(id) || id === `${K}Option` || id === "Name" || id === "Arguments") {
      throw new Error(`${kind} option ${o.name} cannot be the record ${id}`);
    }
    used.add(id);
    if (!first) out.push("");
    first = false;
    out.push(...docLines("    ", "summary", `\`${o.name}\`: ${optionSummary(o)}`));
    out.push(...docLines("    ", "remarks", optionRemarks(o)));
    out.push(`    public sealed record ${id} : ${K}Option`, "    {");
    signatures(o).forEach((s, i) => {
      if (i > 0) out.push("");
      out.push(...signatureDocs(o, s, "        ", ""));
      out.push(`        public ${id}(${paramList(s)})`);
      if (!s.rest) {
        out.push(`            : base(${str(o.name)}, ${argsExpr(s)})`, "        {", "        }");
      } else {
        const call = [...s.params.map((p) => p.name), s.rest.name].join(", ");
        out.push(`            : base(${str(o.name)}, Args${i}(${call}))`, "        {", "        }", "");
        out.push(`        private static OptionArg[] Args${i}(${paramList(s).replaceAll(/ = (null|default)/g, "").replace("params ", "")})`, "        {");
        out.push(...restStatements(s, "            "), "            return [.. args];", "        }");
      }
    });
    out.push("    }");
  }
  out.push("}", "");
  return out.join("\n");
}

function dictLiteral(entries: [string, string][], indent: string): string[] {
  return entries.map(([k, v]) => `${indent}[${str(k)}] = ${str(v)},`);
}

function emitCatalog(spec: Spec): string {
  const out: string[] = [header("Name tables of the processing, /info and /video option catalogues.")];
  out.push("using System.Collections.Frozen;", "", "namespace Xtandard.Image;", "");
  out.push("/// <summary>The option catalogues' name tables, from the server's catalogues.</summary>");
  out.push("public static class OptionCatalog", "{");
  let first = true;
  for (const kind of ["processing", "info", "video"] as const) {
    const K = kindPrefix[kind];
    const opts = spec.options[kind];
    const names: [string, string][] = [];
    for (const o of opts) {
      names.push([o.name, o.name]);
      for (const a of o.aliases) names.push([a, o.name]);
    }
    names.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    if (!first) out.push("");
    first = false;
    out.push(`    /// <summary>Every ${kind} option name and alias to its canonical name.</summary>`);
    out.push(`    public static FrozenDictionary<string, string> ${K}Names { get; } = new Dictionary<string, string>(StringComparer.Ordinal)`);
    out.push("    {", ...dictLiteral(names, "        "), "    }.ToFrozenDictionary(StringComparer.Ordinal);", "");
    out.push(`    /// <summary>Canonical ${kind} option name to the name builders write by default (the shortest).</summary>`);
    out.push(`    public static FrozenDictionary<string, string> ${K}ShortNames { get; } = new Dictionary<string, string>(StringComparer.Ordinal)`);
    out.push("    {", ...dictLiteral(opts.map((o) => [o.name, o.short]), "        "), "    }.ToFrozenDictionary(StringComparer.Ordinal);");
  }
  out.push("}", "");
  return out.join("\n");
}

function strArray(values: readonly string[]): string {
  return `[${values.map(str).join(", ")}]`;
}

function stringStruct(name: string, summary: string, values: { name: string; doc: string }[]): string[] {
  const out: string[] = [];
  out.push(...docLines("", "summary", summary));
  out.push(`/// <param name="Value">The value as written in URLs.</param>`);
  out.push(`public readonly partial record struct ${name}(string Value)`, "{");
  for (const v of values) {
    out.push(...docLines("    ", "summary", v.doc));
    out.push(`    public static ${name} ${member(v.name)} { get; } = new(${str(v.name)});`, "");
  }
  out.push(`    /// <summary>Converts a value as written in URLs.</summary>`);
  out.push(`    /// <param name="value">The value as written in URLs.</param>`);
  out.push(`    public static implicit operator ${name}(string value) => new(value);`, "");
  out.push(`    /// <summary>Converts a value as written in URLs.</summary>`);
  out.push(`    /// <param name="value">The value as written in URLs.</param>`);
  out.push(`    /// <returns>The ${name}.</returns>`);
  out.push(`    public static ${name} FromString(string value) => new(value);`, "");
  out.push(`    /// <inheritdoc/>`);
  out.push(`    public override string ToString() => Value ?? string.Empty;`);
  out.push("}", "");
  return out;
}

function constClass(name: string, summary: string, values: readonly string[], what: (v: string) => string): string[] {
  const out = [...docLines("", "summary", summary), `public static class ${name}`, "{"];
  const used = new Set<string>();
  values.forEach((v, i) => {
    let id = member(v);
    if (id === "" || used.has(id)) id = `${id}_${i}`;
    used.add(id);
    if (i > 0) out.push("");
    out.push(...docLines("    ", "summary", what(v)));
    out.push(`    public const string ${id} = ${str(v)};`);
  });
  out.push("}", "");
  return out;
}


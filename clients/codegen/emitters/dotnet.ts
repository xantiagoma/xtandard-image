/** new Dictionary<K, V>(StringComparer.Ordinal) { [k] = v, … }.ToFrozenDictionary(StringComparer.Ordinal). */
function frozen(key: TypeRef, value: TypeRef, entries: readonly (readonly [Expr, Expr])[]): Expr {
  const dict = init(N.new(t("Dictionary", key, value), [ordinal]), entries.map(([k, v]) => N.entry(k, v)), "expanded");
  return N.invoke(dict, "ToFrozenDictionary", [ordinal]);
}

const getter = (name: string, type: TypeRef, value: Expr, doc: string): Node[] => [
  summary(doc),
  N.field(name, type, { mods: ["public", "static", "get"], value }),
];

const strDict = (entries: readonly (readonly [string, string])[]) =>
  frozen(t("string"), t("string"), entries.map(([k, v]) => [N.str(k), N.str(v)]));

function emitCatalog(spec: Spec): Node {
  const members: Node[] = [];
  for (const c of catalogues(spec)) {
    const K = kindPrefix[c.kind];
    const type = t("FrozenDictionary", t("string"), t("string"));
    if (members.length) members.push(N.blank());
    members.push(
      ...getter(`${K}Names`, type, strDict(c.names), `Every ${c.kind} option name and alias to its canonical name.`),
      N.blank(),
      ...getter(
        `${K}ShortNames`,
        type,
        strDict(c.options.map((o) => [o.name, o.short])),
        `Canonical ${c.kind} option name to the name builders write by default (the shortest).`,
      ),
    );
  }
  return file("Name tables of the processing, /info and /video option catalogues.", ["System.Collections.Frozen"], [
    summary("The option catalogues' name tables, from the server's catalogues."),
    N.type("class", "OptionCatalog", members, { mods: ["public", "static"] }),
  ]);
}


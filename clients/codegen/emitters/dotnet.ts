const strList = (values: readonly string[]) => N.list(values.map(N.str));
const strings = t("IReadOnlyList", t("string"));

function stringStruct(name: string, doc: string, values: readonly { name: string; doc: string }[]): Node[] {
  const self = t(name);
  const value = N.param("value", t("string"));
  const members: Node[] = [];
  for (const v of values) {
    members.push(summary(v.doc), N.field(member(v.name), self, { mods: ["public", "static", "get"], value: newOf(N.str(v.name)) }), N.blank());
  }
  const converts = [summary("Converts a value as written in URLs."), xdoc("param", "The value as written in URLs.", [["name", "value"]])];
  members.push(
    ...converts,
    N.func(name, [value], newOf(id("value")), { mods: ["public", "static", "implicit", "operator"] }),
    N.blank(),
    ...converts,
    xdoc("returns", `The ${name}.`),
    N.func("FromString", [value], newOf(id("value")), { mods: ["public", "static"], returns: self }),
    N.blank(),
    xdoc("inheritdoc", undefined),
    N.func("ToString", [], N.binary("??", id("Value"), N.get(id("string"), "Empty")), { mods: ["public", "override"], returns: t("string") }),
  );
  return [
    summary(doc),
    xdoc("param", "The value as written in URLs.", [["name", "Value"]]),
    N.type("struct", name, members, { mods: ["public", "readonly", "partial", "record"], params: [N.param("Value", t("string"))] }),
    N.blank(),
  ];
}

function constClass(name: string, doc: string, values: readonly string[], what: (v: string) => string): Node[] {
  const members: Node[] = [];
  const used = new Set<string>();
  values.forEach((v, i) => {
    let field = member(v);
    if (field === "" || used.has(field)) field = `${field}_${i}`;
    used.add(field);
    if (i > 0) members.push(N.blank());
    members.push(summary(what(v)), N.field(field, t("string"), { mods: ["public", "const"], value: N.str(v) }));
  });
  return [summary(doc), N.type("class", name, members, { mods: ["public", "static"] }), N.blank()];
}


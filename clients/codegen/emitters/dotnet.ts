/** The C# type of a schema (non-nullable form) and whether JSON null is allowed. */
function schemaType(s: JSONSchema): { type: TypeRef; nullable: boolean } {
  if (s.$ref) return { type: t(refName(s.$ref)), nullable: false };
  const types = schemaTypes(s);
  const nullable = types.includes("null") || (s.enum?.includes(null) ?? false);
  const rest = types.filter((x) => x !== "null");
  const json = { type: t("JsonElement"), nullable: false };
  const withNull = (x: { type: TypeRef; nullable: boolean }) => (x.nullable && x.type.k === "tref" ? { ...x.type, nullable: true } : x.type);
  if (s.enum) return { type: t("string"), nullable };
  if (rest.length !== 1) return { type: t("JsonElement"), nullable };
  switch (rest[0]) {
    case "string":
      return { type: t("string"), nullable };
    case "integer":
      return { type: t((s as { format?: string }).format === "int32" ? "int" : "long"), nullable };
    case "number":
      return { type: t("double"), nullable };
    case "boolean":
      return { type: t("bool"), nullable };
    case "array":
      return { type: t("IReadOnlyList", withNull(s.items ? schemaType(s.items) : json)), nullable };
    case "object": {
      if (s.properties) throw new Error("inline object schemas are not supported");
      const ap = s.additionalProperties;
      const v = typeof ap === "object" && (ap.type !== undefined || ap.$ref !== undefined) ? schemaType(ap) : json;
      return { type: t("IReadOnlyDictionary", t("string"), withNull(v)), nullable };
    }
    default:
      return { type: t("JsonElement"), nullable };
  }
}

function emitResponses(spec: Spec): Node {
  const schemas = responseSchemas(spec);
  const items: Node[] = [];
  for (const sm of schemas) {
    const desc = (sm.schema.description ?? `The ${sm.name} object of the server's JSON responses.`).split("\n\n")[0]!;
    const members: Node[] = [];
    sm.properties.forEach(([p, ps], i) => {
      const name = member(p);
      if (name === sm.name) throw new Error(`${sm.name}.${p} has the class's name`);
      const x = schemaType(ps);
      const required = sm.required.has(p) && !x.nullable;
      const value = required ? (x.type.k === "tref" && x.type.name === "string" ? N.get(id("string"), "Empty") : ps.$ref ? newOf() : undefined) : undefined;
      const type = required || x.type.k !== "tref" ? x.type : { ...x.type, nullable: true };
      if (i > 0) members.push(N.blank());
      members.push(
        summary(ps.description ?? `\`${p}\`.`),
        N.field(name, type, {
          mods: ["public", "get", "init"],
          annotations: [N.annotation("JsonPropertyName", [N.str(p)])],
          ...(value ? { value } : {}),
        }),
      );
    });
    items.push(summary(desc), N.type("class", sm.name, members, { mods: ["public", "sealed"] }), N.blank());
  }
  const serializable = (name: string) => N.annotation("JsonSerializable", [N.call(id("typeof"), [N.typeExpr(t(name))])]);
  items.push(
    summary("Source-generated System.Text.Json metadata of the response bodies (trimming- and AOT-safe)."),
    N.type("class", "XtandardJsonContext", [], {
      mods: ["public", "sealed", "partial"],
      supers: [t("JsonSerializerContext")],
      annotations: [
        N.annotation("JsonSourceGenerationOptions", [N.named("GenerationMode", N.get(id("JsonSourceGenerationMode"), "Metadata"))]),
        ...schemas.map((s) => serializable(s.name)),
        serializable("JsonElement"),
      ],
    }),
  );
  return file(
    "The JSON response bodies (the OpenAPI components) and their source-generated serializer context.",
    ["System.Text.Json", "System.Text.Json.Serialization"],
    items,
  );
}


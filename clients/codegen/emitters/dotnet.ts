function refName(ref: string): string {
  return ref.replace("#/components/schemas/", "");
}

/** The C# type of a schema (non-nullable form) and whether JSON null is allowed. */
function schemaType(s: JSONSchema): { type: string; nullable: boolean; reference: boolean } {
  if (s.$ref) return { type: refName(s.$ref), nullable: false, reference: true };
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  const nullable = types.includes("null") || (s.enum?.includes(null) ?? false);
  const t = types.filter((x) => x !== "null");
  if (s.enum) return { type: "string", nullable, reference: true };
  if (t.length !== 1) return { type: "JsonElement", nullable, reference: false };
  switch (t[0]) {
    case "string":
      return { type: "string", nullable, reference: true };
    case "integer":
      return { type: (s as { format?: string }).format === "int32" ? "int" : "long", nullable, reference: false };
    case "number":
      return { type: "double", nullable, reference: false };
    case "boolean":
      return { type: "bool", nullable, reference: false };
    case "array": {
      const it = s.items ? schemaType(s.items) : { type: "JsonElement", nullable: false, reference: false };
      return { type: `IReadOnlyList<${it.type}${it.nullable ? "?" : ""}>`, nullable, reference: true };
    }
    case "object": {
      if (s.properties) throw new Error("inline object schemas are not supported");
      const ap = s.additionalProperties;
      const v =
        typeof ap === "object" && (ap.type !== undefined || ap.$ref !== undefined)
          ? schemaType(ap)
          : { type: "JsonElement", nullable: false, reference: false };
      return { type: `IReadOnlyDictionary<string, ${v.type}${v.nullable ? "?" : ""}>`, nullable, reference: true };
    }
    default:
      return { type: "JsonElement", nullable, reference: false };
  }
}

function emitResponses(spec: Spec): string {
  const out: string[] = [header("The JSON response bodies (the OpenAPI components) and their source-generated serializer context.")];
  out.push("using System.Text.Json;", "using System.Text.Json.Serialization;", "", "namespace Xtandard.Image;", "");
  const names = Object.keys(spec.response_schemas).sort();
  for (const name of names) {
    const s = spec.response_schemas[name]!;
    const desc = (s.description ?? `The ${name} object of the server's JSON responses.`).split("\n\n")[0]!;
    out.push(...docLines("", "summary", desc));
    out.push(`public sealed class ${name}`, "{");
    const req = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {}).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    props.forEach(([p, ps], i) => {
      const id = member(p);
      if (id === name) throw new Error(`${name}.${p} has the class's name`);
      const t = schemaType(ps);
      const required = req.has(p) && !t.nullable;
      if (i > 0) out.push("");
      out.push(...docLines("    ", "summary", ps.description ?? `\`${p}\`.`));
      out.push(`    [JsonPropertyName(${str(p)})]`);
      if (required) {
        const init = t.type === "string" ? " = string.Empty;" : ps.$ref ? " = new();" : "";
        out.push(`    public ${t.type} ${id} { get; init; }${init}`);
      } else {
        out.push(`    public ${t.type}? ${id} { get; init; }`);
      }
    });
    out.push("}", "");
  }
  out.push("/// <summary>Source-generated System.Text.Json metadata of the response bodies (trimming- and AOT-safe).</summary>");
  out.push("[JsonSourceGenerationOptions(GenerationMode = JsonSourceGenerationMode.Metadata)]");
  for (const name of names) out.push(`[JsonSerializable(typeof(${name}))]`);
  out.push("[JsonSerializable(typeof(JsonElement))]");
  out.push("public sealed partial class XtandardJsonContext : JsonSerializerContext", "{", "}", "");
  return out.join("\n");
}


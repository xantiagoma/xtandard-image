const t = (name: string, ...args: TypeRef[]) => N.tref(name, args);
const nullable = (name: string) => N.tref(name, [], { nullable: true });
const id = N.id;
const camel = (name: string) => escape(camelName(name));
const ordinal = N.get(id("StringComparer"), "Ordinal");
const summary = (text: string) => xdoc("summary", text);
const newOf = (...args: Expr[]) => N.call(id("new"), args);

function plural(name: string): string {
  const w = words(name);
  const last = w.pop() ?? "value";
  const pl = /(s|x|ch|sh)$/.test(last) ? `${last}es` : /[^aeiou]y$/.test(last) ? `${last.slice(0, -1)}ies` : `${last}s`;
  return camel([...w, pl].join("_"));
}

/** The C# type name of one argument (non-nullable form). */
function baseName(a: SpecArg): string {
  switch (a.type) {
    case "integer":
      return "long";
    case "number":
      return "double";
    case "boolean":
      return "bool";
    case "direction":
      return "OptionArg";
    default:
      return "string";
  }
}

// OptionArg has its own empty value (OptionArg.Null).
const nullableType = (a: SpecArg): TypeRef => (a.type === "direction" ? t("OptionArg") : nullable(baseName(a)));

/** A type's identity for overload resolution: string? and string are one CLR type. */
const erased = (x: TypeRef) => JSON.stringify(x.k === "tref" && x.name === "string" ? t("string") : x);

function argDoc(a: SpecArg): string {
  const parts: string[] = [];
  if (a.doc) parts.push(a.doc.replace(/\.?$/, "."));
  else parts.push(`${a.name.replaceAll("_", " ")} (${a.type}).`);
  if (a.enum?.length) parts.push(`One of ${a.enum.map((v) => `\`${v}\``).join(", ")}.`);
  if (a.type === "direction") parts.push("A direction (`down`, `up`, `left`, `right`) or an angle in degrees.");
  if (a.type === "base64") parts.push("URL-safe base64, written as given.");
  if (a.type === "color") parts.push("A hex colour (`ff0000`, `f00`, with optional alpha).");
  const range: string[] = [];
  if (a.min !== undefined) range.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) range.push(`≤ ${a.max}`);
  if (range.length) parts.push(`Range ${range.join(", ")}.`);
  if (a.nullable) parts.push("Null writes an empty argument.");
  return parts.join(" ");
}

interface Param {
  /** The identifier, keyword-escaped. */
  readonly name: string;
  readonly type: TypeRef;
  readonly arg: SpecArg;
  /** Enum values accepted here, across the forms merged into this parameter. */
  readonly enums: Set<string>;
  readonly optional: boolean;
}

const paramDoc = (p: Param) => argDoc(p.enums.size ? { ...p.arg, enum: [...p.enums] } : p.arg);

/** One C# overload of an option: positional parameters and an optional params group. */
interface Signature {
  readonly params: Param[];
  readonly required: number;
  readonly rest?: { readonly name: string; readonly type: TypeRef; readonly elems: string[]; readonly doc: string };
}

function uniqueName(name: string, used: Set<string>): string {
  let n = name;
  for (let i = 2; used.has(n); i++) n = `${name}${i}`;
  used.add(n);
  return n;
}

const shapeKey = (s: Signature) => JSON.stringify([s.params.map((p) => erased(p.type)), s.rest ? erased(s.rest.type) : undefined]);

/**
 * The overloads of an option. A form without a rest group is one
 * signature: its first max(min_items, 1) arguments are required and the rest
 * optional (trailing nulls are not written). A form with a rest group gives
 * the shorter prefixes as one such signature and the full form (with the
 * rest elements that min_items requires) plus a `params` group. A
 * signature without a rest group whose parameter types start another such
 * signature with no more required parameters is folded into it (calls would
 * be ambiguous), merging the enum values of its parameters into the docs.
 */
function signatures(o: SpecOption): Signature[] {
  const all: Signature[] = [];
  for (const f of o.forms) for (const s of formSignatures(f)) if (s.params.length > 0 || s.rest) all.push(s);
  const covers = (b: Signature, a: Signature) =>
    !a.rest &&
    !b.rest &&
    b.params.length >= a.params.length &&
    b.required <= a.required &&
    a.params.every((p, i) => erased(p.type) === erased(b.params[i]!.type));
  const out: Signature[] = [];
  all.forEach((a, i) => {
    const into = all.find((b, j) => j !== i && covers(b, a) && (!covers(a, b) || j < i));
    if (into === undefined) {
      if (!out.some((x) => shapeKey(x) === shapeKey(a))) out.push(a);
      return;
    }
    a.params.forEach((p, k) => {
      for (const e of p.enums) into.params[k]!.enums.add(e);
    });
  });
  return out;
}

function positional(args: readonly SpecArg[], required: number, used: Set<string>): Param[] {
  return args.map((a, i) => ({
    name: uniqueName(camel(a.name), used),
    type: i < required ? (a.nullable ? nullableType(a) : t(baseName(a))) : nullableType(a),
    arg: a,
    enums: new Set(a.enum ?? []),
    optional: i >= required,
  }));
}

function formSignatures(f: SpecForm): Signature[] {
  const min = Math.max(f.min_items, 1);
  const n = f.args.length;
  if (!f.rest || f.rest.length === 0) {
    const required = Math.min(min, n);
    return [{ params: positional(f.args, required, new Set()), required }];
  }
  const out: Signature[] = [];
  if (n > 1 && min < n) {
    const prefix = f.args.slice(0, n - 1);
    const required = Math.min(min, prefix.length);
    out.push({ params: positional(prefix, required, new Set()), required });
  }
  const fixed = [...f.args];
  for (let i = 0; fixed.length < min; i++) fixed.push(f.rest[i % f.rest.length]!);
  const used = new Set<string>();
  const params = positional(fixed, fixed.length, used);
  const rest = f.rest;
  const doc = `Repeated ${rest.length === 1 ? "argument" : "groups"}: ${rest.map((a) => `${a.name} — ${argDoc(a)}`).join(" ")}`;
  if (rest.length === 1) {
    const r = rest[0]!;
    out.push({ params, required: params.length, rest: { name: uniqueName(plural(r.name), used), type: array(t(baseName(r))), elems: [], doc } });
  } else {
    const elems = rest.map((a) => [t(baseName(a)), member(a.name)] as const);
    out.push({
      params,
      required: params.length,
      rest: { name: uniqueName("groups", used), type: array(tupleType(elems)), elems: elems.map(([, e]) => e), doc },
    });
  }
  return out;
}

/** The parameters of a signature; declared: with the defaults and `params` of a public signature. */
function paramNodes(s: Signature, declared: boolean): PNode[] {
  const ps = s.params.map((p) =>
    N.param(p.name, p.type, declared && p.optional ? { value: p.arg.type === "direction" ? id("default") : N.null() } : {}),
  );
  if (s.rest) ps.push(N.param(s.rest.name, s.rest.type, declared ? { mods: ["params"] } : {}));
  return ps;
}

/** The OptionArg[] of a signature without a rest group. */
function argsExpr(s: Signature): Expr {
  const list = N.list(s.params.map((p) => id(p.name)));
  return s.params.some((p) => p.optional) ? N.invoke(id("OptionArgs"), "Trim", [list, N.int(s.required)]) : list;
}

/** Statements collecting the OptionArg list `args` of a signature with a rest group. */
function restStatements(s: Signature): Stmt[] {
  const r = s.rest!;
  const width = Math.max(r.elems.length, 1);
  const capacity = N.binary("+", N.int(s.params.length), paren(N.binary("*", N.get(id(r.name), "Length"), N.int(width))));
  const add = (e: Expr) => N.stmt(N.invoke(id("args"), "Add", [e]));
  return [
    N.stmt(N.invoke(id("ArgumentNullException"), "ThrowIfNull", [id(r.name)])),
    N.let("args", init(N.new(t("List", t("OptionArg")), [capacity]), s.params.map((p) => id(p.name)), "auto")),
    N.forEach("e", id(r.name), r.elems.length === 0 ? [add(id("e"))] : r.elems.map((el) => add(N.get(id("e"), el)))),
    N.blank(),
  ];
}

const collected = () => N.list([N.spread(id("args"))]);

function optionSummary(o: SpecOption): string {
  return o.doc.trim().replace(/\.?$/, ".");
}

function optionRemarks(o: SpecOption): string {
  const tags: string[] = [];
  tags.push(`URL names: ${[o.name, ...o.aliases].map((n) => `\`${n}\``).join(", ")}; arguments \`${o.syntax}\`; default ${o.default}.`);
  if (o.milestone) tags.push(`Milestone ${o.milestone}; scope ${o.scope}.`);
  else tags.push(`Scope ${o.scope}.`);
  if (o.pro) tags.push("imgproxy Pro option (free here).");
  if (o.security) tags.push("Security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS).");
  if (o.removed) tags.push("Removed: accepted and ignored.");
  return tags.join(" ");
}

/** The <param> name of an identifier: without the keyword escape. */
const docName = (name: string) => name.replace(/^@/, "");

function signatureDocs(o: SpecOption, s: Signature, returns?: string): Comment[] {
  const out = [summary(optionSummary(o)), xdoc("remarks", optionRemarks(o))];
  for (const p of s.params) out.push(xdoc("param", paramDoc(p), [["name", docName(p.name)]]));
  if (s.rest) out.push(xdoc("param", s.rest.doc, [["name", docName(s.rest.name)]]));
  if (returns) out.push(xdoc("returns", returns));
  return out;
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

/** A generated file: the notice, #nullable enable, the usings and the namespace's items. */
function file(what: string, usings: readonly string[], items: Node[]): Node {
  while (items.at(-1)?.k === "blank") items.pop();
  return N.file([
    N.line("<auto-generated/>"),
    N.line(what),
    N.line("Code generated by clients/codegen/emitters/dotnet.ts from clients/spec/spec.json."),
    N.line("DO NOT EDIT. Run `task clients:generate`."),
    N.blank(),
    directive("nullable", "enable"),
    N.blank(),
    ...(usings.length ? [...usings.map((u) => N.imp(u)), N.blank()] : []),
    N.namespace("Xtandard.Image", items),
  ]);
}

// ---- chains ------------------------------------------------------------------------------

function emitChain(c: CatalogueModel): Node {
  const { kind } = c;
  const K = kindPrefix[kind];
  const self = t("TSelf");
  const members: Node[] = [
    ctor(N.func(`${K}Chain`, [N.param("state", t("ChainState"))], [], { mods: ["private", "protected"] }), [id("state")]),
  ];
  const used = new Map<string, string>();
  for (const o of c.options) {
    const sigs = signatures(o.spec);
    for (const n of o.names) {
      const name = member(n);
      if (reservedMethods.has(name)) throw new Error(`${kind} option ${n} collides with the builder method ${name}`);
      const prev = used.get(name);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the C# method ${name}`);
      used.set(name, n);
      for (const s of sigs) {
        const option = (args: Expr) => N.call(id("Option"), [N.str(n), args]);
        const body = s.rest ? [...restStatements(s), N.ret(option(collected()))] : option(argsExpr(s));
        members.push(
          N.blank(),
          ...signatureDocs(o.spec, s, "This builder."),
          N.func(name, paramNodes(s, true), body, { returns: self, mods: ["public", ARROW_NEXT_LINE] }),
        );
      }
    }
  }
  return file(`Per-option methods of the fluent ${kind} URL builders.`, [], [
    summary(`The ${kind} option methods of a fluent URL builder: one per option name and alias, each appending that option written with the name as called.`),
    xdoc("typeparam", "The concrete builder, returned by every method.", [["name", "TSelf"]]),
    N.type("class", `${K}Chain`, members, {
      mods: ["public", "abstract", "partial"],
      typeParams: [typeParam("TSelf", t(`${K}Chain`, self))],
      supers: [t("OptionChain", self)],
    }),
  ]);
}

// ---- option records ------------------------------------------------------------------------

function optionRecord(o: OptionModel, K: string): Node[] {
  const name = member(o.name);
  const members: Node[] = [];
  signatures(o.spec).forEach((s, i) => {
    if (i > 0) members.push(N.blank());
    members.push(...signatureDocs(o.spec, s));
    if (!s.rest) {
      members.push(ctor(N.func(name, paramNodes(s, true), [], { mods: ["public"] }), [N.str(o.name), argsExpr(s)]));
      return;
    }
    const helper = `Args${i}`;
    members.push(
      ctor(N.func(name, paramNodes(s, true), [], { mods: ["public"] }), [
        N.str(o.name),
        N.call(id(helper), paramNodes(s, false).map((p) => id(p.name))),
      ]),
      N.blank(),
      N.func(helper, paramNodes(s, false), [...restStatements(s), N.ret(collected())], {
        mods: ["private", "static"],
        returns: array(t("OptionArg")),
      }),
    );
  });
  return [
    summary(`\`${o.name}\`: ${optionSummary(o.spec)}`),
    xdoc("remarks", optionRemarks(o.spec)),
    N.type("record", name, members, { mods: ["public", "sealed"], supers: [t(`${K}Option`)] }),
  ];
}

function emitOptionRecords(c: CatalogueModel): Node {
  const { kind } = c;
  const K = kindPrefix[kind];
  const used = new Set<string>();
  const members: Node[] = [];
  for (const o of c.options) {
    const name = member(o.name);
    if (used.has(name) || name === `${K}Option` || name === "Name" || name === "Arguments") {
      throw new Error(`${kind} option ${o.name} cannot be the record ${name}`);
    }
    used.add(name);
    if (members.length) members.push(N.blank());
    members.push(...optionRecord(o, K));
  }
  return file(`Typed ${kind} option records.`, [], [N.type("record", `${K}Option`, members, { mods: ["public", "abstract", "partial"] })]);
}


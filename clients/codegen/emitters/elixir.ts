/** The struct module of a $ref. */
const refModule = (s: JSONSchema) => (s.$ref ? `XtandardImage.${refName(s.$ref)}` : undefined);

function fieldType(s: JSONSchema): TypeRef {
  const r = refModule(s);
  if (r) return N.tunion([t(`${r}.t`), nil]);
  const parts: TypeRef[] = [];
  for (const ty of schemaTypes(s)) {
    switch (ty) {
      case "string":
        parts.push(stringT);
        break;
      case "integer":
        parts.push(t("integer"));
        break;
      case "number":
        parts.push(t("number"));
        break;
      case "boolean":
        parts.push(t("boolean"));
        break;
      case "array": {
        const ir = s.items ? refModule(s.items) : undefined;
        parts.push(X.tlist(ir ? t(`${ir}.t`) : s.items ? X.nonNil(fieldType(s.items)) : t("term")));
        break;
      }
      case "object":
        if (s.properties) throw new Error("inline object schemas are not supported");
        parts.push(X.tmap(t("optional", stringT), t("term")));
        break;
      case "null":
        break;
      default:
        parts.push(t("term"));
    }
  }
  if (s.enum) parts.splice(0, parts.length, stringT);
  if (parts.length === 0) parts.push(t("term"));
  return union([...parts, nil]);
}

/** How from_map/1 reads a property: map["p"], or decoded into its struct(s). */
function fieldDecode(p: string, s: JSONSchema): Expr {
  const value = N.index(id("map"), N.str(p));
  const decode = (fn: string, mod: string) => N.invoke(id("Decode"), fn, [value, id(mod)]);
  const r = refModule(s);
  if (r) return decode("one", r);
  const ir = s.items ? refModule(s.items) : undefined;
  if (schemaTypes(s).includes("array") && ir) return decode("many", ir);
  return value;
}

const decodes = (s: JSONSchema) => fieldDecode("", s).k === "call";

function decodeModule(): Node {
  const v = id("v");
  const mod = id("mod");
  const any = id("_");
  const structOrNil = (x: TypeRef) => N.tunion([x, nil]);
  return N.namespace("XtandardImage.Generated.Decode", [
    X.attr("moduledoc", N.bool(false)),
    N.blank(),
    X.attr("doc", N.bool(false)),
    X.spec("one", [t("term"), t("module")], structOrNil(t("struct"))),
    X.def("one", [v, mod], N.invoke(mod, "from_map", [v]), N.call(id("is_map"), [v])),
    X.def("one", [any, any], N.null()),
    N.blank(),
    X.attr("doc", N.bool(false)),
    X.spec("many", [t("term"), t("module")], structOrNil(X.tlist(t("struct")))),
    X.def("many", [v, mod], N.invoke(id("Enum"), "map", [v, X.capture(N.call(id("one"), [X.arg(1), mod]))]), N.call(id("is_list"), [v])),
    X.def("many", [any, any], N.null()),
  ]);
}

function emitResponses(spec: Spec): Node {
  const items: Node[] = [...header, decodeModule()];
  for (const sm of responseSchemas(spec)) {
    const fields = new Map<string, string>();
    for (const [p] of sm.properties) {
      const f = snake(p);
      if (fields.has(f)) throw new Error(`${sm.name}.${p} and ${sm.name}.${fields.get(f)} are both the field ${f}`);
      if (!/^[a-z_][a-z0-9_]*$/.test(f)) throw new Error(`${sm.name}.${p} is not an Elixir field`);
      fields.set(f, p);
    }
    const fieldDocs = sm.properties.map(
      ([p, ps]) => `  * \`${snake(p)}\`${snake(p) === p ? "" : ` (\`${p}\`)`}${ps.description ? `: ${ps.description}` : ""}`,
    );
    const body: Node[] = [
      moduledoc([sm.schema.description ?? sm.name, "", "Built from the decoded JSON body by `from_map/1`. Fields:", "", ...fieldDocs].join("\n")),
      N.blank(),
    ];
    if (sm.properties.some(([, ps]) => decodes(ps))) body.push(N.imp("XtandardImage.Generated.Decode"), N.blank());
    const map = id("map");
    body.push(
      X.command("defstruct", [N.list(sm.properties.map(([p]) => N.sym(snake(p))))]),
      N.blank(),
      N.typeAlias("t", X.tstruct(sm.properties.map(([p, ps]) => [snake(p), fieldType(ps)] as const))),
      N.blank(),
      doc("Builds the struct from a decoded JSON object (string keys); unknown keys are dropped."),
      X.spec("from_map", [t("map")], t("t")),
      X.def(
        "from_map",
        [map],
        [N.stmt(N.new(t("__MODULE__"), sm.properties.map(([p, ps]) => N.named(snake(p), fieldDecode(p, ps))), { layout: "expanded" }))],
        N.call(id("is_map"), [map]),
      ),
    );
    items.push(N.blank(), N.namespace(`XtandardImage.${sm.name}`, body));
  }
  return N.file(items);
}

export const emitter: Emitter = {
  language: "elixir",
  emit(spec) {
    const files: Record<string, Node> = {
      "catalogue.ex": emitCatalogue(spec),
      "spec.ex": emitSpec(spec),
      "responses.ex": emitResponses(spec),
    };
    for (const kind of kinds) files[`${kind}.ex`] = emitCatalogueModule(catalogue(spec, kind));
    return Object.fromEntries(Object.entries(files).map(([f, n]) => [`${dir}${f}`, printer.print(n)]));
  },
};

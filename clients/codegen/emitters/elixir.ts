// Elixir emitter (clients/elixir, Hex xtandard_image): writes
// lib/xtandard_image/generated/ from the spec.
//
//   catalogue.ex   XtandardImage.Generated.Catalogue: every name and alias to
//                  its canonical name, canonical to short, per catalogue
//   processing.ex  XtandardImage.Processing, XtandardImage.Info and
//   info.ex        XtandardImage.Video: one typespec per option (argument
//   video.ex       tuples, lists, bare values), the options keyword type,
//                  one pipe-friendly function per name and alias, and the
//                  chain's control functions
//   spec.ex        XtandardImage.Spec: formats, containers, streams, query
//                  keys, imaginary, sources, signing, encryption, URL rules,
//                  error kinds (functions and types)
//   responses.ex   structs of the JSON bodies (InfoResponse, ErrorResponse,
//                  …) with from_map/1
//
// Elixir >= 1.17. The files are excluded from `mix format` and Credo
// (.formatter.exs, .credo.exs); Dialyzer checks them.

import { allArgs, bareArgs, nameTable, type Shape, shapes, snake } from "../lib.ts";
import type { CatalogueKind, Emitter, JSONSchema, Spec, SpecArg, SpecOption } from "../spec.ts";

const dir = "clients/elixir/lib/xtandard_image/generated/";

const header = [
  "# Code generated by clients/codegen/emitters/elixir.ts from clients/spec/spec.json.",
  "# DO NOT EDIT. Run `task clients:generate`.",
  "",
].join("\n");

/** Elixir's reserved words: a function cannot be named after them. */
const reserved = new Set(
  "true false nil when and or not in fn do end catch rescue after else".split(" "),
);

/** Chain control functions every catalogue module delegates; option functions must not collide. */
export const controls: Record<CatalogueKind, readonly string[]> = {
  processing: ["option", "options", "pipeline", "extension", "encoding", "with_pdf_password", "param", "build", "build!"],
  info: ["option", "options", "encoding", "with_pdf_password", "build", "build!"],
  video: ["option", "options", "extension", "encoding", "build", "build!"],
};

const moduleOf: Record<CatalogueKind, string> = {
  processing: "XtandardImage.Processing",
  info: "XtandardImage.Info",
  video: "XtandardImage.Video",
};

/** An Elixir string literal (no interpolation). */
function str(s: string): string {
  return JSON.stringify(s).replaceAll("#{", "\\#{");
}

/** An Elixir atom literal. */
function atom(s: string): string {
  return /^[a-z_][A-Za-z0-9_]*$/.test(s) ? `:${s}` : `:${str(s)}`;
}

/** A function name for an option name or alias. */
function ident(name: string): string {
  let id = name.replace(/[^A-Za-z0-9_]/g, "_").toLowerCase();
  if (/^[0-9]/.test(id)) id = `o_${id}`;
  return reserved.has(id) ? `${id}_` : id;
}

/** A ~S heredoc (no interpolation, no escapes), indented. */
function heredoc(text: string, indent: string): string {
  const lines = text.trim().split("\n");
  return [`~S"""`, ...lines.map((l) => (l === "" ? "" : indent + l)), `${indent}"""`].join("\n");
}

/** A union of types, each member once, `nil` last. */
function union(parts: string[]): string {
  const members = [...new Set(parts.flatMap((p) => p.split(" | ")))];
  return [...members.filter((m) => m !== "nil"), ...members.filter((m) => m === "nil")].join(" | ");
}

/** The typespec of one argument. */
function argType(a: SpecArg): string {
  let t: string;
  switch (a.type) {
    case "integer":
      t = "integer()";
      break;
    case "number":
      t = "number()";
      break;
    case "boolean":
      t = "boolean()";
      break;
    case "enum":
      t = union([...(a.enum ?? []).map(atom), "String.t()"]);
      break;
    case "direction":
      t = ":down | :up | :left | :right | number() | String.t()";
      break;
    default:
      t = "String.t()";
  }
  return a.nullable ? `${t} | nil` : t;
}

function shapeType(s: Shape): string | undefined {
  if (s.rest) return undefined; // a tuple type cannot repeat; the list form covers it
  return `{${s.fixed.map(argType).join(", ")}}`;
}

const kindDoc: Record<CatalogueKind, string> = {
  processing: "processing (imgproxy dialect `/…` and the query dialect's `o=`)",
  info: "`/info`",
  video: "`/video` (and the query dialect's `/q/video`)",
};

/** Inline code, unless the text has its own backquotes. */
function code(text: string): string {
  return text.includes("`") ? text : `\`${text}\``;
}

function optionDoc(o: SpecOption): string {
  const lines = [
    o.doc,
    "",
    `URL names: ${[o.name, ...o.aliases].map((n) => `\`${n}\``).join(", ")}; arguments ${code(o.syntax)}; default ${o.default}.`,
  ];
  const tags: string[] = [];
  if (o.milestone) tags.push(`milestone ${o.milestone}`);
  tags.push(`scope ${o.scope}`);
  if (o.pro) tags.push("imgproxy Pro option (free here)");
  if (o.security) tags.push("security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS)");
  if (o.removed) tags.push("removed: accepted and ignored");
  lines.push(`${tags.join("; ")}.`);
  return lines.join("\n");
}

function emitCatalogueModule(spec: Spec, kind: CatalogueKind): string {
  const opts = spec.options[kind];
  const mod = moduleOf[kind];
  const out: string[] = [header];
  out.push(`defmodule ${mod} do`);
  out.push(
    `  @moduledoc ${heredoc(
      [
        `Options of the ${kindDoc[kind]} catalogue.`,
        "",
        "One typespec per option and one pipe-friendly function per option name and alias,",
        "which appends that option to an `XtandardImage.Chain`, written with the name as",
        "called (or as the builder's `option_names` says).",
        "",
        "Each function takes the chain and the option's arguments: a tuple or a list, or the",
        "first argument alone when the others are optional. `nil` is an empty argument.",
        "Enum values may be atoms or strings.",
        "",
        "The chain's control functions are here too, so one alias is enough:",
        "",
        kind === "processing"
          ? [
              "    iex> alias XtandardImage.Processing, as: P",
              "    iex> XtandardImage.imgproxy(source_encoding: :plain)",
              '    ...> |> XtandardImage.Imgproxy.image("s3://b/cat.jpg")',
              "    ...> |> P.resize({:fill, 300, 400})",
              "    ...> |> P.quality(80)",
              '    ...> |> P.extension("webp")',
              "    ...> |> P.build!()",
              '    "/insecure/rs:fill:300:400/q:80/plain/s3://b/cat.jpg@webp"',
            ].join("\n")
          : kind === "info"
            ? [
                "    iex> alias XtandardImage.Info",
                "    iex> XtandardImage.imgproxy(source_encoding: :plain)",
                '    ...> |> XtandardImage.Imgproxy.info("s3://b/cat.jpg")',
                "    ...> |> Info.size(true)",
                "    ...> |> Info.dimensions(true)",
                "    ...> |> Info.build!()",
                '    "/info/insecure/s:1/d:1/plain/s3://b/cat.jpg"',
              ].join("\n")
            : [
                "    iex> alias XtandardImage.Video",
                "    iex> XtandardImage.imgproxy(source_encoding: :plain)",
                '    ...> |> XtandardImage.Imgproxy.video("s3://m/talk.mov")',
                "    ...> |> Video.start(12)",
                "    ...> |> Video.mute(true)",
                '    ...> |> Video.extension("mp4")',
                "    ...> |> Video.build!()",
                '    "/video/insecure/vs:12/mu:1/plain/s3://m/talk.mov@mp4"',
              ].join("\n"),
        "",
        "Generated from the server's catalogue (clients/spec/spec.json).",
      ].join("\n"),
      "  ",
    )}`,
  );
  out.push("");
  out.push("  alias XtandardImage.Chain");
  out.push("");
  const names = nameTable(opts);
  const byName = new Map(opts.map((o) => [o.name, o]));
  for (const o of opts) {
    const base = snake(o.name);
    const tuples = shapes(o)
      .map(shapeType)
      .filter((t): t is string => t !== undefined);
    const elem = union(allArgs(o).map(argType));
    const bare = bareArgs(o).map((a) => argType({ ...a, nullable: false }));
    out.push(`  @typedoc ${str(`Arguments of \`${o.name}\`: ${o.syntax}.`)}`);
    out.push(`  @type ${base}_value ::`);
    const parts = [...tuples, `nonempty_list(${elem})`, ...(bare.length ? [union(bare)] : [])];
    out.push(parts.map((p, i) => `          ${i === 0 ? "" : "| "}${p}`).join("\n"));
    out.push("");
  }
  out.push(`  @typedoc "Every ${kind} option name and alias."`);
  out.push("  @type name ::");
  out.push(names.map(([n], i) => `          ${i === 0 ? "" : "| "}${atom(n)}`).join("\n"));
  out.push("");
  out.push(`  @typedoc "One ${kind} option: a name or alias (atom or string) and its arguments."`);
  out.push("  @type option ::");
  const optParts = names.map(([n, c]) => `{${atom(n)}, ${snake(byName.get(c)!.name)}_value()}`);
  optParts.push("{String.t(), Chain.arg_value()}");
  out.push(optParts.map((p, i) => `          ${i === 0 ? "" : "| "}${p}`).join("\n"));
  out.push("");
  out.push(
    `  @typedoc "One ${kind} pipeline: options in URL order (a keyword list), or a map. A \`nil\` value skips the option."`,
  );
  out.push("  @type options :: [option()] | %{optional(atom() | String.t()) => Chain.arg_value() | nil}");
  out.push("");
  const used = new Map<string, string>();
  const ctl = new Set(controls[kind]);
  for (const o of opts) {
    for (const n of [o.name, ...o.aliases]) {
      const id = ident(n);
      if (ctl.has(id)) throw new Error(`${kind} option ${n} collides with the chain function ${id}`);
      const prev = used.get(id);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Elixir function ${id}`);
      used.set(id, n);
      out.push(`  @doc ${heredoc(optionDoc(o), "  ")}`);
      out.push(`  @spec ${id}(Chain.t(), ${snake(o.name)}_value()) :: Chain.t()`);
      out.push(`  def ${id}(chain, args), do: Chain.option(chain, ${str(n)}, args)`);
      out.push("");
    }
  }
  out.push("  # The chain's control functions (XtandardImage.Chain).");
  const delegates: Record<string, string> = {
    option: "option(chain, name, args)",
    options: "options(chain, options)",
    pipeline: "pipeline(chain)",
    extension: "extension(chain, ext)",
    encoding: "encoding(chain, encoding)",
    with_pdf_password: "with_pdf_password(chain, password)",
    param: "param(chain, key, value)",
    build: "build(chain)",
    "build!": "build!(chain)",
  };
  for (const c of controls[kind]) {
    out.push(`  @doc "See \`XtandardImage.Chain.${c}/${delegates[c]!.split(",").length}\`."`);
    out.push(`  defdelegate ${delegates[c]}, to: Chain`);
  }
  out.push("end");
  out.push("");
  return out.join("\n");
}

function emitCatalogue(spec: Spec): string {
  const out: string[] = [header];
  out.push("defmodule XtandardImage.Generated.Catalogue do");
  out.push("  @moduledoc false");
  out.push("  # Option names of the processing, /info and /video catalogues.");
  out.push("");
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    out.push(`  @${kind}_names %{`);
    out.push(nameTable(opts).map(([n, c]) => `    ${str(n)} => ${str(c)}`).join(",\n"));
    out.push("  }");
    out.push("");
    out.push(`  @${kind}_short %{`);
    out.push(opts.map((o) => `    ${str(o.name)} => ${str(o.short)}`).join(",\n"));
    out.push("  }");
    out.push("");
  }
  out.push("  @typedoc false");
  out.push("  @type kind :: :processing | :info | :video");
  out.push("");
  out.push("  @doc false");
  out.push("  @spec names(kind()) :: %{optional(String.t()) => String.t()}");
  for (const kind of ["processing", "info", "video"]) out.push(`  def names(:${kind}), do: @${kind}_names`);
  out.push("");
  out.push("  @doc false");
  out.push("  @spec short(kind()) :: %{optional(String.t()) => String.t()}");
  for (const kind of ["processing", "info", "video"]) out.push(`  def short(:${kind}), do: @${kind}_short`);
  out.push("end");
  out.push("");
  return out.join("\n");
}

function list(values: readonly (string | number)[]): string {
  return `[${values.map((v) => (typeof v === "string" ? str(v) : String(v))).join(", ")}]`;
}

function atomType(values: readonly string[]): string {
  return union([...values.map(atom), "String.t()"]);
}


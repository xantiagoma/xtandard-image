/** The typespec of one argument. */
function argType(a: SpecArg): TypeRef {
  let x: TypeRef;
  switch (a.type) {
    case "integer":
      x = t("integer");
      break;
    case "number":
      x = t("number");
      break;
    case "boolean":
      x = t("boolean");
      break;
    case "enum":
      x = union([...(a.enum ?? []).map(atom), stringT]);
      break;
    case "direction":
      x = N.tunion([...["down", "up", "left", "right"].map(atom), t("number"), stringT]);
      break;
    default:
      x = stringT;
  }
  return a.nullable ? N.tunion([x, nil]) : x;
}

/** A tuple type of a shape; none for a shape with a rest group (a tuple type cannot repeat; the list form covers it). */
const shapeType = (s: Shape): TypeRef | undefined => (s.rest ? undefined : N.ttuple(s.fixed.map(argType)));

const kindDoc: Record<CatalogueKind, string> = {
  processing: "processing (imgproxy dialect `/…` and the query dialect's `o=`)",
  info: "`/info`",
  video: "`/video` (and the query dialect's `/q/video`)",
};

/** Inline code, unless the text has its own backquotes. */
const code = (text: string) => (text.includes("`") ? text : `\`${text}\``);

function optionDoc(o: OptionModel): string {
  return [
    o.spec.doc,
    "",
    `URL names: ${o.names.map((n) => `\`${n}\``).join(", ")}; arguments ${code(o.spec.syntax)}; default ${o.spec.default}.`,
    `${o.tags.join("; ")}.`,
  ].join("\n");
}


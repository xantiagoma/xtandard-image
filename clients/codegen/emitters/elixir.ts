const moduledoc = (text: string) => X.attr("moduledoc", X.heredoc(text));
const doc = (text: string) => X.attr("doc", N.str(text));
const typedoc = (text: string) => X.attr("typedoc", N.str(text));
const valueType = (o: OptionModel) => t(`${snake(o.name)}_value`);

// ---- processing.ex, info.ex, video.ex -------------------------------------------------

function emitCatalogueModule(c: CatalogueModel): Node {
  const { kind } = c;
  const items: Node[] = [
    moduledoc(
      [
        `Options of the ${kindDoc[kind]} catalogue.`,
        "",
        "One typespec per option and one pipe-friendly function per option name and alias,",
        "which appends that option to an `XtandardImage.Chain`, written with the name as",
        "called (or as the builder's `option_names` says).",
        "",
        "Each function takes the chain and the option's arguments: a tuple or a list, or the",
        "first argument alone when the others are optional. `nil` is an empty argument.",
        "Enum values may be atoms or strings.",
        "",
        "The chain's control functions are here too, so one alias is enough:",
        "",
        ...examples[kind],
        "",
        "Generated from the server's catalogue (clients/spec/spec.json).",
      ].join("\n"),
    ),
    N.blank(),
    N.imp("XtandardImage.Chain"),
    N.blank(),
  ];
  for (const o of c.options) {
    const tuples = o.shapes.map(shapeType).filter((x): x is TypeRef => x !== undefined);
    const elem = union(o.args.map(argType));
    const bare = o.bare.map((a) => argType({ ...a, nullable: false }));
    items.push(
      typedoc(`Arguments of \`${o.name}\`: ${o.spec.syntax}.`),
      N.typeAlias(`${snake(o.name)}_value`, N.tunion([...tuples, t("nonempty_list", elem), ...(bare.length ? [union(bare)] : [])]), {
        mods: ["expanded"],
      }),
      N.blank(),
    );
  }
  items.push(
    typedoc(`Every ${kind} option name and alias.`),
    N.typeAlias("name", N.tunion(c.names.map(([n]) => atom(n))), { mods: ["expanded"] }),
    N.blank(),
    typedoc(`One ${kind} option: a name or alias (atom or string) and its arguments.`),
    N.typeAlias(
      "option",
      N.tunion([...c.names.map(([n, canonical]) => N.ttuple([atom(n), valueType(c.byName.get(canonical)!)])), N.ttuple([stringT, t("Chain.arg_value")])]),
      { mods: ["expanded"] },
    ),
    N.blank(),
    typedoc(`One ${kind} pipeline: options in URL order (a keyword list), or a map. A \`nil\` value skips the option.`),
    N.typeAlias(
      "options",
      N.tunion([X.tlist(t("option")), X.tmap(t("optional", N.tunion([t("atom"), stringT])), N.tunion([t("Chain.arg_value"), nil]))]),
    ),
    N.blank(),
  );
  const used = new Map<string, string>();
  const ctl = new Set(controls[kind]);
  for (const o of c.options) {
    for (const n of o.names) {
      const name = ident(n);
      if (ctl.has(name)) throw new Error(`${kind} option ${n} collides with the chain function ${name}`);
      const prev = used.get(name);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Elixir function ${name}`);
      used.set(name, n);
      items.push(
        X.attr("doc", X.heredoc(optionDoc(o))),
        X.spec(name, [chainT, valueType(o)], chainT),
        X.def(name, [id("chain"), id("args")], N.invoke(id("Chain"), "option", [id("chain"), N.str(n), id("args")])),
        N.blank(),
      );
    }
  }
  items.push(N.line("The chain's control functions (XtandardImage.Chain)."));
  for (const fn of controls[kind]) {
    const params = controlParams[fn]!;
    items.push(doc(`See \`XtandardImage.Chain.${fn}/${params.length}\`.`), X.defdelegate(fn, params, "Chain"));
  }
  return N.file([...header, N.namespace(moduleOf[kind], items)]);
}

// ---- catalogue.ex ---------------------------------------------------------------------

const kinds = ["processing", "info", "video"] as const;
const stringMap = X.tmap(t("optional", stringT), stringT);

function emitCatalogue(spec: Spec): Node {
  const items: Node[] = [X.attr("moduledoc", N.bool(false)), N.line("Option names of the processing, /info and /video catalogues."), N.blank()];
  for (const kind of kinds) {
    const c = catalogue(spec, kind);
    items.push(
      X.attr(`${kind}_names`, N.map(c.names.map(([n, canonical]) => N.entry(N.str(n), N.str(canonical))), { layout: "expanded" })),
      N.blank(),
      X.attr(`${kind}_short`, N.map(c.options.map((o) => N.entry(N.str(o.name), N.str(o.short))), { layout: "expanded" })),
      N.blank(),
    );
  }
  items.push(
    X.attr("typedoc", N.bool(false)),
    N.typeAlias("kind", N.tunion(kinds.map(atom))),
    N.blank(),
  );
  for (const [fn, suffix] of [
    ["names", "names"],
    ["short", "short"],
  ] as const) {
    items.push(X.attr("doc", N.bool(false)), X.spec(fn, [t("kind")], stringMap));
    for (const kind of kinds) items.push(X.def(fn, [N.sym(kind)], X.at(`${kind}_${suffix}`)));
    if (fn === "names") items.push(N.blank());
  }
  return N.file([...header, N.namespace("XtandardImage.Generated.Catalogue", items)]);
}


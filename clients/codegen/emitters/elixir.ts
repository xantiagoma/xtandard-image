// ---- responses -------------------------------------------------------------

const ref = (s: JSONSchema) => (s.$ref ? `XtandardImage.${s.$ref.replace("#/components/schemas/", "")}` : undefined);

function fieldType(s: JSONSchema): string {
  const r = ref(s);
  if (r) return `${r}.t() | nil`;
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  const parts: string[] = [];
  for (const t of types) {
    switch (t) {
      case "string":
        parts.push("String.t()");
        break;
      case "integer":
        parts.push("integer()");
        break;
      case "number":
        parts.push("number()");
        break;
      case "boolean":
        parts.push("boolean()");
        break;
      case "array": {
        const ir = s.items ? ref(s.items) : undefined;
        parts.push(ir ? `[${ir}.t()]` : `[${s.items ? fieldType(s.items).replace(" | nil", "") : "term()"}]`);
        break;
      }
      case "object":
        if (s.properties) throw new Error("inline object schemas are not supported");
        parts.push("%{optional(String.t()) => term()}");
        break;
      case "null":
        break;
      default:
        parts.push("term()");
    }
  }
  if (s.enum) parts.splice(0, parts.length, "String.t()");
  if (parts.length === 0) parts.push("term()");
  return `${union(parts)} | nil`;
}

function fieldDecode(p: string, s: JSONSchema): string {
  const r = ref(s);
  if (r) return `Decode.one(map[${str(p)}], ${r})`;
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  if (types.includes("array") && s.items && ref(s.items)) return `Decode.many(map[${str(p)}], ${ref(s.items)})`;
  return `map[${str(p)}]`;
}

function emitResponses(spec: Spec): string {
  const out: string[] = [header];
  out.push("defmodule XtandardImage.Generated.Decode do");
  out.push("  @moduledoc false");
  out.push("");
  out.push("  @doc false");
  out.push("  @spec one(term(), module()) :: struct() | nil");
  out.push("  def one(v, mod) when is_map(v), do: mod.from_map(v)");
  out.push("  def one(_, _), do: nil");
  out.push("");
  out.push("  @doc false");
  out.push("  @spec many(term(), module()) :: [struct()] | nil");
  out.push("  def many(v, mod) when is_list(v), do: Enum.map(v, &one(&1, mod))");
  out.push("  def many(_, _), do: nil");
  out.push("end");
  for (const name of Object.keys(spec.response_schemas).sort()) {
    const s = spec.response_schemas[name]!;
    const props = Object.entries(s.properties ?? {}).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    const fields = new Map<string, string>();
    for (const [p] of props) {
      const f = snake(p);
      if (fields.has(f)) throw new Error(`${name}.${p} and ${name}.${fields.get(f)} are both the field ${f}`);
      if (!/^[a-z_][a-z0-9_]*$/.test(f)) throw new Error(`${name}.${p} is not an Elixir field`);
      fields.set(f, p);
    }
    const decodes = props.some(([, ps]) => fieldDecode("", ps).startsWith("Decode."));
    out.push("");
    out.push(`defmodule XtandardImage.${name} do`);
    const fieldDocs = props.map(
      ([p, ps]) => `  * \`${snake(p)}\`${snake(p) === p ? "" : ` (\`${p}\`)`}${ps.description ? `: ${ps.description}` : ""}`,
    );
    out.push(
      `  @moduledoc ${heredoc(
        [s.description ?? name, "", "Built from the decoded JSON body by `from_map/1`. Fields:", "", ...fieldDocs].join("\n"),
        "  ",
      )}`,
    );
    out.push("");
    if (decodes) {
      out.push("  alias XtandardImage.Generated.Decode");
      out.push("");
    }
    out.push(`  defstruct [${props.map(([p]) => `:${snake(p)}`).join(", ")}]`);
    out.push("");
    out.push("  @type t :: %__MODULE__{");
    out.push(props.map(([p, ps]) => `          ${snake(p)}: ${fieldType(ps)}`).join(",\n"));
    out.push("        }");
    out.push("");
    out.push(`  @doc "Builds the struct from a decoded JSON object (string keys); unknown keys are dropped."`);
    out.push("  @spec from_map(map()) :: t()");
    out.push("  def from_map(map) when is_map(map) do");
    out.push("    %__MODULE__{");
    out.push(props.map(([p, ps]) => `      ${snake(p)}: ${fieldDecode(p, ps)}`).join(",\n"));
    out.push("    }");
    out.push("  end");
    out.push("end");
  }
  out.push("");
  return out.join("\n");
}

export const emitter: Emitter = {
  language: "elixir",
  emit(spec) {
    const out: Record<string, string> = {
      [`${dir}catalogue.ex`]: emitCatalogue(spec),
      [`${dir}spec.ex`]: emitSpec(spec),
      [`${dir}responses.ex`]: emitResponses(spec),
    };
    for (const kind of ["processing", "info", "video"] as const) out[`${dir}${kind}.ex`] = emitCatalogueModule(spec, kind);
    return out;
  },
};

// ---- query parameters -------------------------------------------------------

function emitParams(name: string, doc: string, keys: { name: string; aliases: string[]; doc: string }[]): string {
  const out: string[] = [header(doc)];
  out.push(
    kdoc(
      [
        kd(doc),
        "",
        "Keys are written in the order they are added, after `url`; booleans are `true` or `false` and numbers",
        "are written as ECMAScript writes them. [param] adds any key.",
      ],
      "",
    ),
  );
  out.push(`public class ${name} : ParamList<${name}>() {`);
  out.push("    override fun self(): " + name + " = this");
  const used = new Set<string>();
  for (const k of keys) {
    for (const n of [k.name, ...k.aliases]) {
      const id = camel(n);
      if (reservedMethods.has(id)) throw new Error(`${name} key ${n} collides with the method ${id}`);
      if (used.has(id)) throw new Error(`${name} keys collide on ${id}`);
      used.add(id);
      for (const [t, what] of [
        ["String", "the value"],
        ["Number", "the value"],
        ["Boolean", "the value, written true or false"],
      ] as const) {
        out.push("");
        out.push(
          kdoc(
            [
              kd(k.doc || `The ${k.name} parameter.`),
              "",
              kd(`Key ${n}${k.aliases.length ? ` (names: ${[k.name, ...k.aliases].join(", ")})` : ""}.`),
              "",
              `@param value ${what}`,
              "@return this",
            ],
            "    ",
          ),
        );
        out.push(`    public fun ${id}(value: ${t}): ${name} = param(${str(n)}, value)`);
      }
    }
  }
  out.push("}");
  out.push("");
  return out.join("\n");
}


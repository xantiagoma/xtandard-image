// Kotlin Multiplatform emitter (clients/kotlin, package
// io.github.xantiagoma.xtandard.image.kmp): writes src/generated/kotlin/ from
// the spec. That directory is a second commonMain source root, outside what
// ktlint checks.
//
//   ProcessingMethods, InfoMethods, VideoMethods
//                    generic interfaces with one default method per option
//                    name and alias and argument shape (the typed option
//                    values); the options lists and the fluent chains
//                    implement them
//   OptionTables     name or alias to canonical name, canonical to short
//   QueryParams, ImaginaryParams
//                    native query keys and imaginary parameters, one typed
//                    method per key and alias
//   ImageFormat, VideoContainer, StreamProtocol, SegmentFormat,
//   SourceEncoding, SourceScheme, ImaginaryEndpoint, ErrorKind
//                    enums of the spec's value lists
//   Constants        signing, encryption, URL and stream constants
//   Responses        InfoResponse, ErrorResponse and the classes they
//                    reference, as kotlinx.serialization data classes
//
// Numeric arguments are Number (Int, Long, Double, Float all fit), so the
// integer and number forms of an argument share one overload; shapes whose
// JVM signatures would clash are merged, nullable where either is.

import { nameTable, type Shape, shapes, words } from "../lib.ts";
import type { CatalogueKind, Emitter, JSONSchema, Spec, SpecArg, SpecOption } from "../spec.ts";

const dir = "clients/kotlin/src/generated/kotlin/io/github/xantiagoma/xtandard/image/kmp/";
const pkg = "io.github.xantiagoma.xtandard.image.kmp";

const kotlinKeywords = new Set(
  (
    "as break class continue do else false for fun if in interface is null object package return super this throw " +
    "true try typealias typeof val var when while"
  ).split(" "),
);

/** Builder methods the per-option methods must not shadow (and kotlin.Any's). */
export const reservedMethods = new Set([
  "option",
  "options",
  "pipeline",
  "extension",
  "encoding",
  "withPdfPassword",
  "build",
  "param",
  "params",
  "entries",
  "isEmpty",
  "self",
  "toString",
  "equals",
  "hashCode",
]);

/** camelCase Kotlin identifier of a name ("min-width" → "minWidth", "R" → "r"). */
function camel(name: string): string {
  const ws = words(name);
  let id = ws.map((w, i) => (i === 0 ? w.toLowerCase() : w[0]!.toUpperCase() + w.slice(1).toLowerCase())).join("");
  if (id === "") id = "value";
  if (/^[0-9]/.test(id)) id = `v${id}`;
  return kotlinKeywords.has(id) ? `${id}Value` : id;
}

/** UPPER_SNAKE constant name of a value ("fill-down" → "FILL_DOWN", "m3u8" → "M3U8"). */
function constant(value: string): string {
  let id = words(value)
    .map((w) => w.toUpperCase())
    .join("_");
  if (/^[0-9]/.test(id)) id = `V${id}`;
  return id;
}

/** A Kotlin string literal ("$" escaped). */
const str = (s: string) => JSON.stringify(s).replaceAll("$", "\\$");

const header = (what: string) =>
  [
    `// Code generated by clients/codegen/emitters/kotlin.ts from clients/spec/spec.json. DO NOT EDIT.`,
    `// Run \`task clients:generate\`. ${what}`,
    "",
    `package ${pkg}`,
    "",
  ].join("\n");

/** Text for a KDoc comment: no comment openers or terminators, no Markdown links. */
function kd(text: string): string {
  return text
    .replaceAll("*/", "*&#47;")
    .replaceAll("/*", "&#47;*")
    .replaceAll("[", "\\[")
    .replaceAll("]", "\\]")
    .replaceAll("`", "'");
}

/** A KDoc block at an indent; lines starting with "@" are block tags. */
function kdoc(lines: string[], indent: string): string {
  const out = [`${indent}/**`];
  for (const l of lines) {
    for (const part of l.split("\n")) out.push(part === "" ? `${indent} *` : `${indent} * ${part}`);
  }
  out.push(`${indent} */`);
  return out.join("\n");
}

// ---- option methods ---------------------------------------------------------

interface Param {
  /** Kotlin type without nullability. */
  base: string;
  nullable: boolean;
  name: string;
  doc: string;
}

/** Kotlin type of one argument (without "?"). */
function argBase(a: SpecArg): string {
  switch (a.type) {
    case "integer":
    case "number":
      return "Number";
    case "boolean":
      return "Boolean";
    case "direction":
      return "Any";
    default:
      return "String";
  }
}

function argDoc(a: SpecArg): string {
  const parts: string[] = [];
  if (a.doc) parts.push(a.doc);
  if (a.type === "integer") parts.push("an integer");
  if (a.type === "enum" && a.enum) parts.push(`one of ${a.enum.map((v) => `"${v}"`).join(", ")}`);
  if (a.type === "direction") parts.push(`"down", "up", "left", "right" or a number`);
  if (a.type === "color") parts.push("a hex colour");
  if (a.type === "base64") parts.push("URL-safe base64");
  if (a.min !== undefined && a.max !== undefined) parts.push(`${a.min} to ${a.max}`);
  else if (a.min !== undefined) parts.push(`at least ${a.min}`);
  else if (a.max !== undefined) parts.push(`at most ${a.max}`);
  if (a.nullable) parts.push("null writes an empty argument");
  return parts.join("; ") || a.name;
}

interface Sig {
  params: Param[];
  rest?: Param;
}

function shapeSig(s: Shape): Sig {
  const used = new Map<string, number>();
  const name = (n: string) => {
    let id = camel(n);
    const c = used.get(id) ?? 0;
    used.set(id, c + 1);
    if (c > 0) id = `${id}${c + 1}`;
    return id;
  };
  const params = s.fixed.map((a) => ({ base: argBase(a), nullable: a.nullable, name: name(a.name), doc: argDoc(a) }));
  if (!s.rest) return { params };
  const bases = [...new Set(s.rest.map(argBase))];
  const base = bases.length === 1 ? bases[0]! : "Any";
  const nullable = bases.length > 1 || s.rest.some((a) => a.nullable);
  const restDoc = `repeated ${s.rest.map((a) => a.name).join(", ")}: ${s.rest.map(argDoc).join(" / ")}`;
  return {
    params,
    rest: { base, nullable, name: name(s.rest.length === 1 ? `${s.rest[0]!.name}s` : "rest"), doc: restDoc },
  };
}

/** The JVM-level identity of a signature (nullability is not part of it). */
function erasure(s: Sig): string {
  return [...s.params.map((p) => p.base), ...(s.rest ? [`${s.rest.base}[]`] : [])].join(",");
}

/** Shapes with the same erasure become one signature, nullable where any of them is. */
function mergedSigs(o: SpecOption): Sig[] {
  const out = new Map<string, Sig>();
  for (const sh of shapes(o)) {
    const sig = shapeSig(sh);
    const key = erasure(sig);
    const prev = out.get(key);
    if (!prev) {
      out.set(key, sig);
      continue;
    }
    prev.params.forEach((p, i) => (p.nullable ||= sig.params[i]!.nullable));
    if (prev.rest && sig.rest) prev.rest.nullable ||= sig.rest.nullable;
  }
  return [...out.values()];
}

const typeOf = (p: Param) => `${p.base}${p.nullable ? "?" : ""}`;

function optionDoc(o: SpecOption): string[] {
  const lines = [kd(o.doc), "", kd(`URL names: ${[o.name, ...o.aliases].join(", ")}; arguments ${o.syntax}; default ${o.default}.`)];
  const tags: string[] = [];
  if (o.milestone) tags.push(`milestone ${o.milestone}`);
  tags.push(`scope ${o.scope}`);
  if (o.pro) tags.push("imgproxy Pro option (free here)");
  if (o.security) tags.push("security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS)");
  if (o.removed) tags.push("removed: accepted and ignored");
  lines.push(kd(`${tags.join("; ")}.`));
  return lines;
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

function emitMethods(spec: Spec, kind: CatalogueKind): string {
  const K = kindPrefix[kind];
  const out: string[] = [header(`The typed ${kind} option methods.`)];
  out.push(
    kdoc(
      [
        `One method per ${kind} option name and alias, with one overload per argument shape; each appends`,
        "that option, written with the name as called ([OptionNameStyle.GIVEN]), its short name (the default)",
        "or its canonical name.",
        "",
        "Numbers are written as ECMAScript writes them (`300`, `1.5`), booleans as `1` and `0`, and a null",
        "argument is an empty one.",
        "",
        "@param S the implementing type, returned by every method",
      ],
      "",
    ),
  );
  out.push(`public interface ${K}Methods<S> {`);
  out.push(
    kdoc(
      [
        "Appends one option occurrence (what the per-option methods call).",
        "",
        "@param name an option name or alias",
        "@param args the arguments: strings, numbers, booleans or null (an empty argument)",
        "@return this",
      ],
      "    ",
    ),
  );
  out.push("    public fun option(name: String, vararg args: Any?): S");
  const used = new Map<string, string>();
  for (const o of spec.options[kind]) {
    const sigs = mergedSigs(o);
    if (sigs.length === 0) throw new Error(`${kind} option ${o.name} has no argument shapes`);
    for (const n of [o.name, ...o.aliases]) {
      const id = camel(n);
      if (reservedMethods.has(id)) throw new Error(`${kind} option ${n} collides with the builder method ${id}`);
      const prev = used.get(id);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Kotlin method ${id}`);
      used.set(id, n);
      for (const sh of sigs) {
        const ps = [...sh.params, ...(sh.rest ? [sh.rest] : [])];
        out.push("");
        out.push(kdoc([...optionDoc(o), "", ...ps.map((p) => `@param ${p.name} ${kd(p.doc)}`), "@return this"], "    "));
        const sig = [
          ...sh.params.map((p) => `${p.name}: ${typeOf(p)}`),
          ...(sh.rest ? [`vararg ${sh.rest.name}: ${typeOf(sh.rest)}`] : []),
        ].join(", ");
        const args = [...sh.params.map((p) => p.name), ...(sh.rest ? [`*${sh.rest.name}`] : [])].join(", ");
        out.push(`    public fun ${id}(${sig}): S = option(${str(n)}${args ? `, ${args}` : ""})`);
      }
    }
  }
  out.push("}");
  out.push("");
  return out.join("\n");
}

function mapLiteral(entries: [string, string][], indent: string): string {
  return entries.map(([k, v]) => `${indent}${str(k)} to ${str(v)},`).join("\n");
}

function emitTables(spec: Spec): string {
  const out: string[] = [header("Option name tables of the processing, /info and /video catalogues.")];
  out.push("/** Option name tables: every name and alias to its canonical name, and canonical to short names. */");
  out.push("internal object OptionTables {");
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    const K = kind.toUpperCase();
    out.push(`    /** ${kind} option name or alias to canonical name. */`);
    out.push(`    val ${K}_NAMES: Map<String, String> =`);
    out.push("        mapOf(");
    out.push(mapLiteral(nameTable(opts), "            "));
    out.push("        )");
    out.push("");
    out.push(`    /** Canonical ${kind} option name to the name builders write by default (the shortest). */`);
    out.push(`    val ${K}_SHORT: Map<String, String> =`);
    out.push("        mapOf(");
    out.push(mapLiteral(opts.map((o) => [o.name, o.short]), "            "));
    out.push("        )");
    if (kind !== "video") out.push("");
  }
  out.push("}");
  out.push("");
  return out.join("\n");
}

// ---- enums and constants ----------------------------------------------------

interface EnumValue {
  value: string;
  doc?: string;
  /** Extra constructor arguments, as Kotlin expressions. */
  extra?: string[];
}

function emitEnum(
  name: string,
  doc: string,
  values: EnumValue[],
  extraParams: string[] = [],
  companion: string[] = [],
): string {
  const out: string[] = [header(doc)];
  out.push(`/** ${kd(doc)} */`);
  const params = ["/** The value as written in URLs. */ public val value: String", ...extraParams];
  out.push(`public enum class ${name}(`);
  for (const p of params) out.push(`    ${p},`);
  out.push(") {");
  values.forEach((v, i) => {
    out.push(`    /** ${v.doc ? kd(v.doc) : `\`${kd(v.value)}\`.`} */`);
    const args = [str(v.value), ...(v.extra ?? [])].join(", ");
    out.push(`    ${constant(v.value)}(${args})${i === values.length - 1 ? ";" : ","}`);
  });
  out.push("");
  out.push("    override fun toString(): String = value");
  out.push("");
  out.push(`    /** Lookup by URL value. */`);
  out.push("    public companion object {");
  out.push("        /**");
  out.push("         * The constant written [value] in URLs.");
  out.push("         *");
  out.push("         * @param value the URL value");
  out.push("         * @return the constant, or null for an unknown value");
  out.push("         */");
  out.push(`        public fun of(value: String): ${name}? = entries.firstOrNull { it.value == value }`);
  for (const c of companion) out.push(c);
  out.push("    }");
  out.push("}");
  out.push("");
  return out.join("\n");
}

function listLiteral(values: readonly (string | number)[]): string {
  return `listOf(${values.map((v) => (typeof v === "string" ? str(v) : String(v))).join(", ")})`;
}


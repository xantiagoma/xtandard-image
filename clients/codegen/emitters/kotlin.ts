/** Kotlin type of a schema (without nullability). */
function schemaType(s: JSONSchema): string {
  if (s.$ref) return s.$ref.replace("#/components/schemas/", "");
  const types = (s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type]).filter((t) => t !== "null");
  const t = types.length === 1 ? types[0] : undefined;
  switch (t) {
    case "string":
      return "String";
    case "integer":
      return "Long";
    case "number":
      return "Double";
    case "boolean":
      return "Boolean";
    case "array":
      return s.items ? `List<${schemaType(s.items)}>` : "JsonArray";
    case "object": {
      if (s.properties) throw new Error("inline object schemas are not supported");
      const ap = s.additionalProperties;
      if (typeof ap === "object") {
        const typed = ap.type !== undefined || ap.$ref !== undefined;
        return `Map<String, ${typed ? schemaType(ap) : "JsonElement"}>`;
      }
      return "JsonObject";
    }
    default:
      return "JsonElement";
  }
}

function emitResponses(spec: Spec): string {
  const out: string[] = [header("The JSON bodies of /info answers and error responses.")];
  out.push("import kotlinx.serialization.SerialName");
  out.push("import kotlinx.serialization.Serializable");
  out.push("import kotlinx.serialization.json.JsonArray");
  out.push("import kotlinx.serialization.json.JsonElement");
  out.push("import kotlinx.serialization.json.JsonObject");
  const entries = Object.entries(spec.response_schemas).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  for (const [name, s] of entries) {
    const props = Object.entries(s.properties ?? {});
    const req = new Set(s.required ?? []);
    const comps = props.map(([p, ps]) => {
      const nullableType = Array.isArray(ps.type) && ps.type.includes("null");
      return { json: p, id: camel(p), type: schemaType(ps), required: req.has(p) && !nullableType, doc: ps.description };
    });
    out.push("");
    const docLines = [kd(s.description ?? `The ${name} object.`)];
    docLines.push("");
    for (const c of comps) {
      docLines.push(`@property ${c.id} \`${kd(c.json)}\`${c.doc ? `: ${kd(c.doc)}` : ""}${c.required ? "" : " (null when absent)"}`);
    }
    out.push(kdoc(docLines, ""));
    out.push("@Serializable");
    out.push(`public data class ${name}(`);
    for (const c of comps) {
      const t = c.required ? c.type : `${c.type}? = null`;
      out.push(`    @SerialName(${str(c.json)}) public val ${c.id}: ${t},`);
    }
    out.push(")");
  }
  out.push("");
  let text = out.join("\n");
  for (const t of ["JsonArray", "JsonElement", "JsonObject"]) {
    const uses = text.split("\n").filter((l) => !l.startsWith("import ") && new RegExp(`\\b${t}\\b`).test(l)).length;
    if (uses === 0) text = text.replace(`import kotlinx.serialization.json.${t}\n`, "");
  }
  return text;
}

export const emitter: Emitter = {
  language: "kotlin",
  emit(spec) {
    const files: Record<string, string> = {};
    for (const kind of ["processing", "info", "video"] as const) {
      files[`${dir}${kindPrefix[kind]}Methods.kt`] = emitMethods(spec, kind);
    }
    files[`${dir}OptionTables.kt`] = emitTables(spec);
    files[`${dir}Constants.kt`] = emitConstants(spec);
    for (const [n, text] of Object.entries(emitEnums(spec))) files[`${dir}${n}.kt`] = text;
    files[`${dir}QueryParams.kt`] = emitParams(
      "QueryParams",
      "Native keys of the query dialect's image endpoint (/q/?url=…&w=300&f=webp).",
      spec.query.image_keys,
    );
    const reservedImaginary = new Set(["url", "sign", "xi_sig"]);
    files[`${dir}ImaginaryParams.kt`] = emitParams(
      "ImaginaryParams",
      "Parameters of the query dialect's imaginary endpoints (/q/resize?url=…&width=300).",
      spec.query.imaginary.params.filter((p) => !reservedImaginary.has(p)).map((p) => ({ name: p, aliases: [], doc: "" })),
    );
    files[`${dir}Responses.kt`] = emitResponses(spec);
    return files;
  },
};

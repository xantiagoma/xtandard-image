// ---- nodes ------------------------------------------------------------------------

const t = (name: string, ...args: TypeRef[]) => N.tref(name, args);
const opt = (x: TypeRef, nullable: boolean) => (nullable && x.k === "tref" ? N.tref(x.name, x.args, { nullable: true }) : x);
const id = N.id;
const pub = ["public"];
/** A KDoc of several lines (each may span lines). */
const kdoc = (text: readonly string[]) => N.comment("doc", text.flatMap((l) => l.split("\n")));
/** A one-line KDoc. */
const kdoc1 = (text: string) => N.comment("doc", [text], { mods: ["inline"] });
const listOf = (values: readonly (string | number)[]) => N.call(id("listOf"), values.map(N.scalar));
/** mapOf(k to v, …), one entry per line. */
const mapOf = (entries: readonly (readonly [Expr, Expr])[]) => N.call(id("mapOf"), entries.map(([k, v]) => N.binary("to", k, v)), { layout: "expanded" });
const strPairs = (pairs: readonly (readonly [string, string])[]) => pairs.map(([k, v]) => [N.str(k), N.str(v)] as const);

/** The file header, the package line, then the items. */
function file(what: string, items: readonly Node[]): Node {
  return N.file([
    N.comment("line", ["Code generated by clients/codegen/emitters/kotlin.ts from clients/spec/spec.json. DO NOT EDIT.", `Run \`task clients:generate\`. ${what}`]),
    N.blank(),
    N.ext("kt.package", { name: pkg }) as Package,
    N.blank(),
    ...items,
  ]);
}

// ---- option methods ---------------------------------------------------------

interface Param {
  /** Kotlin type without nullability. */
  base: string;
  nullable: boolean;
  name: string;
  doc: string;
}

/** Kotlin type of one argument (without "?"). */
function argBase(a: SpecArg): string {
  switch (a.type) {
    case "integer":
    case "number":
      return "Number";
    case "boolean":
      return "Boolean";
    case "direction":
      return "Any";
    default:
      return "String";
  }
}

function argDoc(a: SpecArg): string {
  const parts: string[] = [];
  if (a.doc) parts.push(a.doc);
  if (a.type === "integer") parts.push("an integer");
  if (a.type === "enum" && a.enum) parts.push(`one of ${a.enum.map((v) => `"${v}"`).join(", ")}`);
  if (a.type === "direction") parts.push(`"down", "up", "left", "right" or a number`);
  if (a.type === "color") parts.push("a hex colour");
  if (a.type === "base64") parts.push("URL-safe base64");
  if (a.min !== undefined && a.max !== undefined) parts.push(`${a.min} to ${a.max}`);
  else if (a.min !== undefined) parts.push(`at least ${a.min}`);
  else if (a.max !== undefined) parts.push(`at most ${a.max}`);
  if (a.nullable) parts.push("null writes an empty argument");
  return parts.join("; ") || a.name;
}

interface Sig {
  params: Param[];
  rest?: Param;
}

function shapeSig(s: Shape): Sig {
  const used = new Map<string, number>();
  const name = (n: string) => {
    let ident = camel(n);
    const c = used.get(ident) ?? 0;
    used.set(ident, c + 1);
    if (c > 0) ident = `${ident}${c + 1}`;
    return ident;
  };
  const params = s.fixed.map((a) => ({ base: argBase(a), nullable: a.nullable, name: name(a.name), doc: argDoc(a) }));
  if (!s.rest) return { params };
  const bases = [...new Set(s.rest.map(argBase))];
  const base = bases.length === 1 ? bases[0]! : "Any";
  const nullable = bases.length > 1 || s.rest.some((a) => a.nullable);
  const restDoc = `repeated ${s.rest.map((a) => a.name).join(", ")}: ${s.rest.map(argDoc).join(" / ")}`;
  return {
    params,
    rest: { base, nullable, name: name(s.rest.length === 1 ? `${s.rest[0]!.name}s` : "rest"), doc: restDoc },
  };
}

/** The JVM-level identity of a signature (nullability is not part of it). */
function erasure(s: Sig): string {
  return JSON.stringify([s.params.map((p) => p.base), s.rest?.base ?? null]);
}

/** Shapes with the same erasure become one signature, nullable where any of them is. */
function mergedSigs(o: OptionModel): Sig[] {
  const out = new Map<string, Sig>();
  for (const sh of o.shapes) {
    const sig = shapeSig(sh);
    const key = erasure(sig);
    const prev = out.get(key);
    if (!prev) {
      out.set(key, sig);
      continue;
    }
    prev.params.forEach((p, i) => (p.nullable ||= sig.params[i]!.nullable));
    if (prev.rest && sig.rest) prev.rest.nullable ||= sig.rest.nullable;
  }
  return [...out.values()];
}

const typeOf = (p: Param) => N.tref(p.base, [], { nullable: p.nullable });

function optionDoc(o: OptionModel): string[] {
  return [kd(o.spec.doc), "", kd(`URL names: ${o.names.join(", ")}; arguments ${o.spec.syntax}; default ${o.spec.default}.`), kd(`${o.tags.join("; ")}.`)];
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

function emitMethods(c: CatalogueModel): Node {
  const { kind } = c;
  const S = t("S");
  const members: Node[] = [
    N.func("option", [N.param("name", t("String")), N.param("args", N.tref("Any", [], { nullable: true }), { mods: ["variadic"] })], undefined, {
      returns: S,
      mods: pub,
      doc: kdoc([
        "Appends one option occurrence (what the per-option methods call).",
        "",
        "@param name an option name or alias",
        "@param args the arguments: strings, numbers, booleans or null (an empty argument)",
        "@return this",
      ]),
    }),
  ];
  const used = new Map<string, string>();
  for (const o of c.options) {
    const sigs = mergedSigs(o);
    if (sigs.length === 0) throw new Error(`${kind} option ${o.name} has no argument shapes`);
    for (const n of o.names) {
      const name = camel(n);
      if (reservedMethods.has(name)) throw new Error(`${kind} option ${n} collides with the builder method ${name}`);
      const prev = used.get(name);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Kotlin method ${name}`);
      used.set(name, n);
      for (const sh of sigs) {
        const ps = [...sh.params, ...(sh.rest ? [sh.rest] : [])];
        const params = [
          ...sh.params.map((p) => N.param(p.name, typeOf(p))),
          ...(sh.rest ? [N.param(sh.rest.name, typeOf(sh.rest), { mods: ["variadic"] })] : []),
        ];
        const args: Expr[] = [N.str(n), ...sh.params.map((p) => id(p.name)), ...(sh.rest ? [N.spread(id(sh.rest.name))] : [])];
        members.push(
          N.blank(),
          N.func(name, params, N.call(id("option"), args), {
            returns: S,
            mods: pub,
            doc: kdoc([...optionDoc(o), "", ...ps.map((p) => `@param ${p.name} ${kd(p.doc)}`), "@return this"]),
          }),
        );
      }
    }
  }
  return file(`The typed ${kind} option methods.`, [
    N.type("interface", `${kindPrefix[kind]}Methods`, members, {
      typeParams: [S],
      mods: pub,
      doc: kdoc([
        `One method per ${kind} option name and alias, with one overload per argument shape; each appends`,
        "that option, written with the name as called ([OptionNameStyle.GIVEN]), its short name (the default)",
        "or its canonical name.",
        "",
        "Numbers are written as ECMAScript writes them (`300`, `1.5`), booleans as `1` and `0`, and a null",
        "argument is an empty one.",
        "",
        "@param S the implementing type, returned by every method",
      ]),
    }),
  ]);
}

function emitTables(cats: readonly CatalogueModel[]): Node {
  const strMap = t("Map", t("String"), t("String"));
  const members: Node[] = [];
  for (const c of cats) {
    const K = c.kind.toUpperCase();
    if (members.length) members.push(N.blank());
    members.push(
      N.const(`${K}_NAMES`, mapOf(strPairs(c.names)), { type: strMap, doc: kdoc1(`${c.kind} option name or alias to canonical name.`) }),
      N.blank(),
      N.const(`${K}_SHORT`, mapOf(strPairs(c.options.map((o) => [o.name, o.short]))), {
        type: strMap,
        doc: kdoc1(`Canonical ${c.kind} option name to the name builders write by default (the shortest).`),
      }),
    );
  }
  return file("Option name tables of the processing, /info and /video catalogues.", [
    N.type("object", "OptionTables", members, {
      mods: ["internal"],
      doc: kdoc1("Option name tables: every name and alias to its canonical name, and canonical to short names."),
    }),
  ]);
}

// ---- enums and constants ----------------------------------------------------

interface EnumValue {
  value: string;
  doc?: string;
  /** Extra constructor arguments. */
  extra?: Expr[];
}

/** A constructor property of an enum class with its one-line KDoc. */
const enumProp = (doc: string, name: string, type: TypeRef): KtParam => ({ ...N.param(name, type, { mods: ["public", "val"] }), doc: kdoc1(doc) });

function emitEnum(name: string, doc: string, values: EnumValue[], extraParams: KtParam[] = [], companion: Node[] = []): Node {
  const value = id("value");
  const entries = values.map((v) =>
    N.member(constant(v.value), N.str(v.value), { args: v.extra ?? [], doc: kdoc1(v.doc ? kd(v.doc) : `\`${kd(v.value)}\`.`) }),
  );
  const lookup = N.func("of", [N.param("value", t("String"))], N.call(N.get(id("entries"), "firstOrNull"), [N.lambda([], N.binary("==", N.get(id("it"), "value"), value))]), {
    returns: N.tref(name, [], { nullable: true }),
    mods: pub,
    doc: kdoc(["The constant written [value] in URLs.", "", "@param value the URL value", "@return the constant, or null for an unknown value"]),
  });
  return file(doc, [
    N.type(
      "class",
      name,
      [
        ...entries,
        N.blank(),
        N.func("toString", [], value, { returns: t("String"), mods: ["override"] }),
        N.blank(),
        N.type("object", "", [lookup, ...companion], { mods: ["public", "companion"], doc: kdoc1("Lookup by URL value.") }),
      ],
      { mods: ["public", "enum"], params: [enumProp("The value as written in URLs.", "value", t("String")), ...extraParams], doc: kdoc1(kd(doc)) },
    ),
  ]);
}


// Kotlin Multiplatform emitter (clients/kotlin, package
// io.github.xantiagoma.xtandard.image.kmp): writes src/generated/kotlin/ from
// the spec. That directory is a second commonMain source root, outside what
// ktlint checks.
//
//   ProcessingMethods, InfoMethods, VideoMethods
//                    generic interfaces with one default method per option
//                    name and alias and argument shape (the typed option
//                    values); the options lists and the fluent chains
//                    implement them
//   OptionTables     name or alias to canonical name, canonical to short
//   QueryParams, ImaginaryParams
//                    native query keys and imaginary parameters, one typed
//                    method per key and alias
//   ImageFormat, VideoContainer, StreamProtocol, SegmentFormat,
//   SourceEncoding, SourceScheme, ImaginaryEndpoint, ErrorKind
//                    enums of the spec's value lists
//   Constants        signing, encryption, URL and stream constants
//   Responses        InfoResponse, ErrorResponse and the classes they
//                    reference, as kotlinx.serialization data classes
//
// Numeric arguments are Number (Int, Long, Double, Float all fit), so the
// integer and number forms of an argument share one overload; shapes whose
// JVM signatures would clash are merged, nullable where either is.
//
// This file is the refiner (WP-146): it lowers the neutral model (build.ts)
// into Kotlin nodes (model.ts), which lang/kotlin.ts prints.


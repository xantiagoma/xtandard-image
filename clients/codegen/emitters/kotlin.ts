// ---- query parameters -------------------------------------------------------

function emitParams(name: string, doc: string, keys: { name: string; aliases: string[]; doc: string }[]): Node {
  const self = t(name);
  const members: Node[] = [N.func("self", [], id("this"), { returns: self, mods: ["override"] })];
  const used = new Set<string>();
  for (const k of keys) {
    for (const n of [k.name, ...k.aliases]) {
      const ident = camel(n);
      if (reservedMethods.has(ident)) throw new Error(`${name} key ${n} collides with the method ${ident}`);
      if (used.has(ident)) throw new Error(`${name} keys collide on ${ident}`);
      used.add(ident);
      for (const [type, what] of [
        ["String", "the value"],
        ["Number", "the value"],
        ["Boolean", "the value, written true or false"],
      ] as const) {
        members.push(
          N.blank(),
          N.func(ident, [N.param("value", t(type))], N.call(id("param"), [N.str(n), id("value")]), {
            returns: self,
            mods: pub,
            doc: kdoc([
              kd(k.doc || `The ${k.name} parameter.`),
              "",
              kd(`Key ${n}${k.aliases.length ? ` (names: ${[k.name, ...k.aliases].join(", ")})` : ""}.`),
              "",
              `@param value ${what}`,
              "@return this",
            ]),
          }),
        );
      }
    }
  }
  return file(doc, [
    N.type("class", name, members, {
      mods: pub,
      supers: [N.ext("kt.super-call", { type: t("ParamList", self) }) as SuperCall],
      doc: kdoc([
        kd(doc),
        "",
        "Keys are written in the order they are added, after `url`; booleans are `true` or `false` and numbers",
        "are written as ECMAScript writes them. [param] adds any key.",
      ]),
    }),
  ]);
}

// ---- response classes -------------------------------------------------------

/** Kotlin type of a schema (without nullability). */
function schemaType(s: JSONSchema): TypeRef {
  if (s.$ref) return t(refName(s.$ref));
  const types = schemaTypes(s).filter((x) => x !== "null");
  switch (types.length === 1 ? types[0] : undefined) {
    case "string":
      return t("String");
    case "integer":
      return t("Long");
    case "number":
      return t("Double");
    case "boolean":
      return t("Boolean");
    case "array":
      return s.items ? t("List", schemaType(s.items)) : t("JsonArray");
    case "object": {
      if (s.properties) throw new Error("inline object schemas are not supported");
      const ap = s.additionalProperties;
      if (typeof ap === "object") {
        const typed = ap.type !== undefined || ap.$ref !== undefined;
        return t("Map", t("String"), typed ? schemaType(ap) : t("JsonElement"));
      }
      return t("JsonObject");
    }
    default:
      return t("JsonElement");
  }
}

/** The names of the types a type reference uses. */
function typeNames(x: TypeRef): string[] {
  return x.k === "tref" ? [x.name, ...x.args.flatMap(typeNames)] : [];
}

function emitResponses(spec: Spec): Node {
  const classes: Node[] = [];
  const used = new Set<string>();
  const entries = Object.entries(spec.response_schemas).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  for (const [name, s] of entries) {
    const req = new Set(s.required ?? []);
    const comps = Object.entries(s.properties ?? {}).map(([p, ps]) => {
      const nullableType = Array.isArray(ps.type) && ps.type.includes("null");
      return { json: p, id: camel(p), type: schemaType(ps), required: req.has(p) && !nullableType, doc: ps.description };
    });
    for (const c of comps) for (const n of typeNames(c.type)) used.add(n);
    const docLines = [kd(s.description ?? `The ${name} object.`), ""];
    for (const c of comps) {
      docLines.push(`@property ${c.id} \`${kd(c.json)}\`${c.doc ? `: ${kd(c.doc)}` : ""}${c.required ? "" : " (null when absent)"}`);
    }
    classes.push(
      N.blank(),
      N.type("class", name, [], {
        mods: ["public", "data"],
        annotations: [N.annotation("Serializable")],
        params: comps.map((c) =>
          N.param(c.id, opt(c.type, !c.required), {
            mods: ["public", "val"],
            annotations: [N.annotation("SerialName", [N.str(c.json)])],
            ...(c.required ? {} : { value: N.null() }),
          }),
        ),
        doc: kdoc(docLines),
      }),
    );
  }
  // Only the kotlinx.serialization.json types a class uses are imported.
  const json = ["JsonArray", "JsonElement", "JsonObject"].filter((n) => used.has(n));
  return file("The JSON bodies of /info answers and error responses.", [
    N.imp("kotlinx.serialization.SerialName"),
    N.imp("kotlinx.serialization.Serializable"),
    ...json.map((n) => N.imp(`kotlinx.serialization.json.${n}`)),
    ...classes,
  ]);
}

export const emitter: Emitter = {
  language: "kotlin",
  emit(spec) {
    const cats = catalogues(spec);
    const files: Record<string, Node> = {};
    for (const c of cats) files[`${kindPrefix[c.kind]}Methods`] = emitMethods(c);
    files["OptionTables"] = emitTables(cats);
    files["Constants"] = emitConstants(spec);
    Object.assign(files, emitEnums(spec));
    files["QueryParams"] = emitParams(
      "QueryParams",
      "Native keys of the query dialect's image endpoint (/q/?url=…&w=300&f=webp).",
      spec.query.image_keys,
    );
    files["ImaginaryParams"] = emitParams(
      "ImaginaryParams",
      "Parameters of the query dialect's imaginary endpoints (/q/resize?url=…&width=300).",
      imaginaryParams(spec).map((p) => ({ name: p, aliases: [], doc: "" })),
    );
    files["Responses"] = emitResponses(spec);
    return Object.fromEntries(Object.entries(files).map(([n, f]) => [`${dir}${n}.kt`, printer.print(f)]));
  },
};

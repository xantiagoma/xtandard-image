const refName = (ref: string) => ref.replace("#/components/schemas/", "");

function schemaType(s: JSONSchema): string {
  if (s.$ref) return refName(s.$ref);
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  const t = types.filter((x) => x !== "null");
  if (s.enum) return "String";
  if (t.length !== 1) return "JSONValue";
  switch (t[0]) {
    case "string":
      return "String";
    case "integer":
      return "Int64";
    case "number":
      return "Double";
    case "boolean":
      return "Bool";
    case "array":
      return `[${s.items ? schemaType(s.items) : "JSONValue"}]`;
    case "object":
      if (s.properties) throw new Error("inline object schemas are not supported");
      return `[String: ${typeof s.additionalProperties === "object" && Object.keys(s.additionalProperties).length > 0 ? schemaType(s.additionalProperties) : "JSONValue"}]`;
    default:
      return "JSONValue";
  }
}

/** A property name: lowerCamelCase, with `ID` for an `id` word. */
function property(p: string): string {
  const ws = words(p);
  const id = ws
    .map((w, i) => {
      const l = w.toLowerCase();
      if (i > 0 && l === "id") return "ID";
      return i === 0 ? l : l[0]!.toUpperCase() + l.slice(1);
    })
    .join("");
  return keywords.has(id) ? `\`${id}\`` : id;
}

function emitResponses(spec: Spec): string {
  const out: string[] = [header("Codable types of the JSON response bodies (the OpenAPI components).")];
  for (const name of Object.keys(spec.response_schemas).sort()) {
    const s = spec.response_schemas[name]!;
    out.push("");
    out.push(...doc(s.description ?? name, ""));
    out.push(`public struct ${name}: Codable, Sendable, Equatable {`);
    const req = new Set(s.required ?? []);
    const props = sortedBy(Object.entries(s.properties ?? {}), ([k]) => k);
    const fields: { p: string; id: string; t: string }[] = [];
    for (const [p, ps] of props) {
      const id = property(p);
      let t = schemaType(ps);
      if (!req.has(p)) t = `${t}?`;
      fields.push({ p, id, t });
      out.push(...doc(ps.description ?? `\`${p}\`${ps.$ref ? ` (${refName(ps.$ref)})` : ""}.`, "    "));
      out.push(`    public var ${id}: ${t}`);
    }
    out.push("");
    out.push("    /// A value with every field given (optional fields default to `nil`).");
    const params = fields.map((f) => `${f.id.replaceAll("`", "")}: ${f.t}${f.t.endsWith("?") ? " = nil" : ""}`);
    out.push(`    public init(${params.join(", ")}) {`);
    for (const f of fields) out.push(`        self.${f.id.replaceAll("`", "")} = ${f.id.replaceAll("`", "")}`);
    out.push("    }");
    out.push("");
    out.push("    enum CodingKeys: String, CodingKey {");
    for (const f of fields) out.push(`        case ${f.id} = ${str(f.p)}`);
    out.push("    }");
    out.push("}");
  }
  out.push("");
  return out.join("\n");
}

export const emitter: Emitter = {
  language: "swift",
  emit(spec) {
    return {
      [`${dir}Options.swift`]: emitOptions(spec),
      [`${dir}Methods.swift`]: emitMethods(spec),
      [`${dir}Constants.swift`]: emitConstants(spec),
      [`${dir}Responses.swift`]: emitResponses(spec),
    };
  },
};

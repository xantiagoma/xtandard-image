// ---- Responses.swift -----------------------------------------------------------------

const scalars: Record<string, string> = { string: "String", integer: "Int64", number: "Double", boolean: "Bool" };

function schemaType(s: JSONSchema): TypeRef {
  if (s.$ref) return t(refName(s.$ref));
  const types = schemaTypes(s).filter((x) => x !== "null");
  if (s.enum) return t("String");
  if (types.length !== 1) return t("JSONValue");
  const ty = types[0]!;
  if (scalars[ty]) return t(scalars[ty]);
  if (ty === "array") return array(s.items ? schemaType(s.items) : t("JSONValue"));
  if (ty === "object") {
    if (s.properties) throw new Error("inline object schemas are not supported");
    const ap = s.additionalProperties;
    return dict(t("String"), typeof ap === "object" && Object.keys(ap).length > 0 ? schemaType(ap) : t("JSONValue"));
  }
  return t("JSONValue");
}

function emitResponses(spec: Spec): Node {
  const structs = responseSchemas(spec).map((sm) => {
    const fields = sm.properties.map(([p, ps]) => {
      const name = property(p);
      const type = sm.required.has(p) ? schemaType(ps) : optional(schemaType(ps));
      return { p, ps, name, type, optional: !sm.required.has(p) };
    });
    return N.type(
      "struct",
      sm.name,
      [
        ...fields.map((f) =>
          N.field(escape(f.name), f.type, { mods: pub, doc: doc(f.ps.description ?? `\`${f.p}\`${f.ps.$ref ? ` (${refName(f.ps.$ref)})` : ""}.`) }),
        ),
        N.blank(),
        N.func(
          "init",
          fields.map((f) => N.param(f.name, f.type, f.optional ? { value: N.null() } : {})),
          fields.map((f) => N.stmt(N.binary("=", N.get(id("self"), f.name), id(f.name)))),
          { mods: pub, doc: doc("A value with every field given (optional fields default to `nil`).") },
        ),
        N.blank(),
        N.enum(
          "CodingKeys",
          fields.map((f) => N.member(escape(f.name), N.str(f.p))),
          { supers: [t("String"), t("CodingKey")] },
        ),
      ],
      { mods: pub, supers: ["Codable", "Sendable", "Equatable"].map(t), doc: doc(sm.schema.description ?? sm.name) },
    );
  });
  return N.file([...header("Codable types of the JSON response bodies (the OpenAPI components)."), ...spaced(structs)]);
}

export const emitter: Emitter = {
  language: "swift",
  emit(spec) {
    const files: Record<string, Node> = {
      "Options.swift": emitOptions(spec),
      "Methods.swift": emitMethods(spec),
      "Constants.swift": emitConstants(spec),
      "Responses.swift": emitResponses(spec),
    };
    return Object.fromEntries(Object.entries(files).map(([f, n]) => [`${dir}${f}`, printer.print(n)]));
  },
};

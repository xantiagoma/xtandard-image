// Swift emitter (clients/swift, SwiftPM product XtandardImage): writes
// Sources/XtandardImage/Generated/ from the spec.
//
//   Options.swift    per catalogue (processing, info, video): the option-name
//                    enum (ProcessingOption, InfoOption, VideoOption) with
//                    short names, aliases and the run-time catalogue, and one
//                    nested enum per enum-typed argument (ProcessingOption.ResizeType, …)
//   Methods.swift    protocol extensions with the fluent builders' per-option
//                    methods, one per option name and alias
//   Constants.swift  formats, containers, streams, sources, query keys,
//                    imaginary, signing, encryption and URL constants, error kinds
//   Responses.swift  Codable structs of the JSON bodies (InfoResponse, ErrorResponse)
//
// The runtime (Sources/XtandardImage/*.swift) defines the protocols the
// generated code extends (OptionChain, ArgConvertible, ParsableEnum) and the
// Catalogue type. The generated directory is excluded from swift-format.
//
// This file is the refiner (WP-146): it lowers the neutral model (build.ts)
// into Swift nodes (model.ts plus lang/swift.ts's own), which
// lang/swift.ts prints.


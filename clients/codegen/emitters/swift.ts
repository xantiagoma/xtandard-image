/** lowerCamelCase of a name ("min-width" → "minWidth", "c_obj" → "cObj"). */
function camel(name: string): string {
  const p = pascal(name);
  if (p === "") throw new Error(`${JSON.stringify(name)} has no identifier characters`);
  const id = p[0]!.toLowerCase() + p.slice(1);
  return /^[0-9]/.test(id) ? `v${id}` : id;
}

/** An identifier, backticked when it is a keyword. */
function ident(name: string): string {
  const id = camel(name);
  return keywords.has(id) ? `\`${id}\`` : id;
}

/** A Swift string literal. */
function str(s: string): string {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0)!;
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\t") out += "\\t";
    else if (ch === "\r") out += "\\r";
    else if (c < 0x20 || c === 0x7f) out += `\\u{${c.toString(16)}}`;
    else out += ch;
  }
  return out + '"';
}

/** `///` lines of a doc text (Markdown); blank lines kept, indentation dropped. */
function doc(text: string, indent: string): string[] {
  return text
    .trim()
    .split("\n")
    .map((l) => l.trim())
    .map((l) => (l === "" ? `${indent}///` : `${indent}/// ${l}`));
}

/** Inline code of spec text, or the text when it has backticks itself. */
function code(text: string): string {
  return text.includes("`") ? text : `\`${text}\``;
}

function sortedBy<T>(xs: readonly T[], key: (x: T) => string): T[] {
  return [...xs].sort((a, b) => {
    const ka = key(a);
    const kb = key(b);
    return ka < kb ? -1 : ka > kb ? 1 : 0;
  });
}

/** Error codes of URLBuildError.Code, by the Rust-style variant used in the emitters. */
type ErrorCode = "invalidArgument" | "invalidExtension" | "invalidRequest" | "invalidName" | "invalidEndpoint";

/** A String-backed enum: cases, `ParsableEnum` (init(parsing:) with aliases) and `ArgConvertible`. */
function strEnum(
  name: string,
  error: ErrorCode,
  docText: string,
  values: readonly { value: string; aliases?: readonly string[]; doc?: string }[],
  indent = "",
): string[] {
  const out: string[] = [];
  out.push(...doc(docText, indent));
  out.push(`${indent}public enum ${name}: String, CaseIterable, Sendable, Hashable, ParsableEnum, ArgConvertible {`);
  const seen = new Set<string>();
  for (const v of values) {
    const id = ident(v.value);
    if (seen.has(id)) throw new Error(`${name}: two values are the case ${id}`);
    seen.add(id);
    out.push(...doc(v.doc ?? `\`${v.value}\`.`, `${indent}    `));
    out.push(`${indent}    case ${id} = ${str(v.value)}`);
  }
  out.push("");
  out.push(`${indent}    /// The error code of a value this enum does not know.`);
  out.push(`${indent}    public static let parseError: URLBuildError.Code = .${error}`);
  const aliased = values.filter((v) => v.aliases && v.aliases.length > 0);
  out.push("");
  out.push(`${indent}    /// Other spellings \`init(parsing:)\` accepts.`);
  if (aliased.length === 0) {
    out.push(`${indent}    public static let aliases: [String: Self] = [:]`);
  } else {
    out.push(`${indent}    public static let aliases: [String: Self] = [`);
    for (const v of aliased) for (const a of v.aliases!) out.push(`${indent}        ${str(a)}: .${ident(v.value)},`);
    out.push(`${indent}    ]`);
  }
  out.push(`${indent}}`);
  return out;
}

const kindDoc: Record<CatalogueKind, string> = {
  processing: "A processing option (imgproxy dialect `/{signature}/{options}/{source}`, query dialect `o=`)",
  info: "An `/info` option",
  video: "A `/video` option (also a key of `/q/video`)",
};
const catalogueKind: Record<CatalogueKind, string> = { processing: "imgproxy", info: "info", video: "video" };
const typeName: Record<CatalogueKind, string> = {
  processing: "ProcessingOption",
  info: "InfoOption",
  video: "VideoOption",
};

/** The enum type name of an enum argument of an option. */
function argEnumName(o: SpecOption, a: SpecArg): string {
  return `${pascal(o.name)}${pascal(a.name)}`;
}

/** One enum per (option, enum argument name), the values of every form merged in order. */
function argEnums(opts: readonly SpecOption[]): Map<string, { option: SpecOption; arg: SpecArg; values: string[] }> {
  const out = new Map<string, { option: SpecOption; arg: SpecArg; values: string[] }>();
  for (const o of opts) {
    for (const a of allArgs(o)) {
      if (a.type !== "enum") continue;
      const name = argEnumName(o, a);
      const prev = out.get(name);
      if (prev && prev.option !== o) throw new Error(`argument enums of ${prev.option.name} and ${o.name} are both ${name}`);
      const entry = prev ?? { option: o, arg: a, values: [] };
      for (const v of a.enum ?? []) if (!entry.values.includes(v)) entry.values.push(v);
      out.set(name, entry);
    }
  }
  return out;
}

/** How one argument reads in the docs. */
function argDoc(kind: CatalogueKind, o: SpecOption, a: SpecArg): string {
  const parts: string[] = [];
  switch (a.type) {
    case "enum":
      parts.push(`\`${typeName[kind]}.${argEnumName(o, a)}\` (${(a.enum ?? []).map((v) => `\`${v}\``).join(", ")})`);
      break;
    case "direction":
      parts.push("`down`, `up`, `left`, `right` or a number");
      break;
    default:
      parts.push(a.type);
  }
  if (a.min !== undefined) parts.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) parts.push(`≤ ${a.max}`);
  if (a.multiple_of !== undefined) parts.push(`multiple of ${a.multiple_of}`);
  if (a.pattern !== undefined) parts.push(`pattern \`${a.pattern}\``);
  if (a.nullable) parts.push("may be empty (`nil`)");
  return `\`${a.name}\`: ${parts.join(", ")}${a.doc ? `. ${a.doc}` : ""}`;
}

function shapeDoc(s: Shape): string {
  const names = s.fixed.map((a) => a.name);
  if (s.rest) names.push(`${s.rest.map((a) => a.name).join(", ")}…`);
  return `\`(${names.join(", ")})\``;
}

function optionDoc(kind: CatalogueKind, o: SpecOption): string {
  const lines = [o.doc, ""];
  lines.push(
    `URL names: ${[o.name, ...o.aliases].map((n) => `\`${n}\``).join(", ")}; arguments ${code(o.syntax)}; default ${code(o.default)}.`,
  );
  const tags: string[] = [];
  if (o.milestone) tags.push(`milestone ${o.milestone}`);
  tags.push(`scope ${o.scope}`);
  if (o.pro) tags.push("imgproxy Pro option (free here)");
  if (o.security) tags.push("security option (needs `XI_SECURITY_ALLOW_SECURITY_OPTIONS`)");
  if (o.removed) tags.push("removed: accepted and ignored");
  lines.push(`${tags.join("; ")}.`);
  lines.push("");
  lines.push(`Argument shapes: ${shapes(o).map(shapeDoc).join(", ")}.`);
  lines.push("");
  const seen = new Set<string>();
  for (const a of allArgs(o)) {
    const d = argDoc(kind, o, a);
    if (seen.has(d)) continue;
    seen.add(d);
    lines.push(`- ${d}`);
  }
  return lines.join("\n");
}

function emitOptions(spec: Spec): string {
  const out: string[] = [header("Typed option tables of the processing, `/info` and `/video` catalogues.")];
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    const T = typeName[kind];
    out.push("");
    out.push(...doc(`${kindDoc[kind]}, by canonical name: short name, aliases and argument enums.`, ""));
    out.push(`public enum ${T}: String, CaseIterable, Sendable, Hashable {`);
    const seen = new Set<string>();
    for (const o of opts) {
      const id = ident(o.name);
      if (seen.has(id)) throw new Error(`${kind}: options ${o.name} and another are both the case ${id}`);
      seen.add(id);
      out.push(...doc(o.doc, "    "));
      out.push(`    case ${id} = ${str(o.name)}`);
    }
    out.push("");
    out.push("    /// The name builders write by default.");
    out.push("    public var short: String {");
    out.push("        switch self {");
    for (const o of opts) out.push(`        case .${ident(o.name)}: ${str(o.short)}`);
    out.push("        }");
    out.push("    }");
    out.push("");
    out.push("    /// The other names of the option.");
    out.push("    public var aliases: [String] {");
    out.push("        switch self {");
    for (const o of opts) out.push(`        case .${ident(o.name)}: [${o.aliases.map(str).join(", ")}]`);
    out.push("        }");
    out.push("    }");
    out.push("");
    out.push("    /// The option of a canonical name or an alias.");
    out.push("    public init?(name: String) {");
    out.push(`        guard let canonical = Self.catalogue.canonical(name) else { return nil }`);
    out.push("        self.init(rawValue: canonical)");
    out.push("    }");
    out.push("");
    out.push(`    /// Every ${kind} option name and alias to its canonical name.`);
    out.push("    public static let names: [String: String] = [");
    for (const [n, c] of nameTable(opts)) out.push(`        ${str(n)}: ${str(c)},`);
    out.push("    ]");
    out.push("");
    out.push(`    /// Canonical ${kind} option name to the name builders write by default.`);
    out.push("    public static let shortNames: [String: String] = [");
    for (const o of sortedBy(opts, (x) => x.name)) out.push(`        ${str(o.name)}: ${str(o.short)},`);
    out.push("    ]");
    out.push("");
    out.push(`    static let catalogue = Catalogue(kind: ${str(catalogueKind[kind])}, names: names, shortNames: shortNames)`);
    for (const [name, e] of argEnums(opts)) {
      out.push("");
      out.push(
        ...strEnum(
          name,
          "invalidArgument",
          `Values of argument \`${e.arg.name}\` of ${kind} option \`${e.option.name}\`${e.arg.doc ? `: ${e.arg.doc}` : ""}.`,
          e.values.map((value) => ({ value })),
          "    ",
        ),
      );
    }
    out.push("}");
  }
  out.push("");
  return out.join("\n");
}

const methodsProtocol: Record<CatalogueKind, string> = {
  processing: "ProcessingOptionMethods",
  info: "InfoOptionMethods",
  video: "VideoOptionMethods",
};

function emitMethods(spec: Spec): string {
  const out: string[] = [header("Per-option methods of the fluent URL builders.")];
  for (const kind of ["processing", "info", "video"] as const) {
    const P = methodsProtocol[kind];
    out.push("");
    out.push(`/// A fluent chain with one method per ${kind} option name and alias.`);
    out.push(`public protocol ${P}: OptionChain {}`);
    out.push("");
    out.push(`extension ${P} {`);
    const used = new Map<string, string>();
    for (const o of spec.options[kind]) {
      const full = doc(optionDoc(kind, o), "    ");
      for (const n of [o.name, ...o.aliases]) {
        const id = camel(n);
        if (reservedMethods.has(id)) throw new Error(`${kind} option ${n} collides with the builder method ${id}`);
        const prev = used.get(id);
        if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Swift method ${id}`);
        used.set(id, n);
        if (n === o.name) out.push(...full);
        else out.push(`    /// \`${n}\`: alias of \`${camel(o.name)}\`, written as \`${n}\` with the \`given\` name style.`);
        out.push(`    public func ${ident(n)}(_ args: (any ArgConvertible)?...) -> Self {`);
        out.push(`        option(${str(n)}, arguments: Arg.list(args))`);
        out.push("    }");
        out.push("");
      }
    }
    if (out.at(-1) === "") out.pop();
    out.push("}");
  }
  out.push("");
  return out.join("\n");
}

function swiftStrs(xs: readonly string[]): string {
  return `[${xs.map(str).join(", ")}]`;
}


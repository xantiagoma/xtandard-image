/** Chain methods the per-option methods must not shadow. */
export const reservedMethods = new Set(["option", "options", "pipeline", "extension", "encoding", "withPDFPassword", "build", "param", "init"]);

// ---- helpers -------------------------------------------------------------------------

const t = (name: string) => N.tref(name);
const id = N.id;
const doc = (text: string): Comment => N.doc(text);
const pub = ["public"];
const pubStatic = ["public", "static"];

/** The file comment: what the file holds and the generated-code notice, then two empty lines. */
const header = (what: string): Node[] => [
  N.comment("line", [what, "", "Code generated by clients/codegen/emitters/swift.ts from clients/spec/spec.json.", "DO NOT EDIT. Run `task clients:generate`."]),
  N.blank(),
  N.blank(),
];

/** Inline code of spec text, or the text when it has backticks itself. */
const code = (text: string) => (text.includes("`") ? text : `\`${text}\``);

/** `switch self { case .a: x … }` as the body of a computed property. */
const switchSelf = (arms: readonly (readonly [string, Expr])[]): Stmt[] => [
  N.switch(
    id("self"),
    arms.map(([c, v]) => N.case([dot(c)], [N.stmt(v)])),
  ),
];

const strList = (xs: readonly string[]) => N.list(xs.map(N.str));

/** Items with an empty line between each two. */
const spaced = (items: readonly Node[]): Node[] => items.flatMap((n, i) => (i ? [N.blank(), n] : [n]));

/** Error codes of URLBuildError.Code. */
type ErrorCode = "invalidArgument" | "invalidExtension" | "invalidRequest" | "invalidName" | "invalidEndpoint";

/** A String-backed enum: cases, `ParsableEnum` (init(parsing:) with aliases) and `ArgConvertible`. */
function strEnum(name: string, error: ErrorCode, docText: string, values: readonly { value: string; aliases?: readonly string[]; doc?: string }[]): Node {
  const seen = new Set<string>();
  const members = values.map((v) => {
    const c = ident(v.value);
    if (seen.has(c)) throw new Error(`${name}: two values are the case ${c}`);
    seen.add(c);
    return N.member(c, N.str(v.value), { doc: doc(v.doc ?? `\`${v.value}\`.`) });
  });
  const aliases = values.flatMap((v) => (v.aliases ?? []).map((a) => N.entry(N.str(a), dot(ident(v.value)))));
  return N.enum(name, members, {
    mods: pub,
    supers: ["String", "CaseIterable", "Sendable", "Hashable", "ParsableEnum", "ArgConvertible"].map(t),
    doc: doc(docText),
    body: [
      N.blank(),
      N.const("parseError", dot(error), { mods: pubStatic, type: t("URLBuildError.Code"), doc: doc("The error code of a value this enum does not know.") }),
      N.blank(),
      N.const("aliases", N.map(aliases, { layout: "expanded" }), {
        mods: pubStatic,
        type: dict(t("String"), t("Self")),
        doc: doc("Other spellings `init(parsing:)` accepts."),
      }),
    ],
  });
}

// ---- Options.swift -------------------------------------------------------------------

const kindDoc: Record<CatalogueKind, string> = {
  processing: "A processing option (imgproxy dialect `/{signature}/{options}/{source}`, query dialect `o=`)",
  info: "An `/info` option",
  video: "A `/video` option (also a key of `/q/video`)",
};
const catalogueKind: Record<CatalogueKind, string> = { processing: "imgproxy", info: "info", video: "video" };
const typeName: Record<CatalogueKind, string> = { processing: "ProcessingOption", info: "InfoOption", video: "VideoOption" };

/** The enum type name of an enum argument of an option. */
const argEnumName = (o: OptionModel, a: SpecArg) => `${pascal(o.name)}${pascal(a.name)}`;

/** One enum per (option, enum argument name), the values of every form merged in order. */
function argEnums(opts: readonly OptionModel[]): Map<string, { option: OptionModel; arg: SpecArg; values: string[] }> {
  const out = new Map<string, { option: OptionModel; arg: SpecArg; values: string[] }>();
  for (const o of opts) {
    for (const a of o.args) {
      if (a.type !== "enum") continue;
      const name = argEnumName(o, a);
      const prev = out.get(name);
      if (prev && prev.option !== o) throw new Error(`argument enums of ${prev.option.name} and ${o.name} are both ${name}`);
      const entry = prev ?? { option: o, arg: a, values: [] };
      for (const v of a.enum ?? []) if (!entry.values.includes(v)) entry.values.push(v);
      out.set(name, entry);
    }
  }
  return out;
}

/** How one argument reads in the docs. */
function argDoc(o: OptionModel, a: SpecArg): string {
  const parts: string[] = [];
  switch (a.type) {
    case "enum":
      parts.push(`\`${typeName[o.kind]}.${argEnumName(o, a)}\` (${(a.enum ?? []).map((v) => `\`${v}\``).join(", ")})`);
      break;
    case "direction":
      parts.push("`down`, `up`, `left`, `right` or a number");
      break;
    default:
      parts.push(a.type);
  }
  if (a.min !== undefined) parts.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) parts.push(`≤ ${a.max}`);
  if (a.multiple_of !== undefined) parts.push(`multiple of ${a.multiple_of}`);
  if (a.pattern !== undefined) parts.push(`pattern \`${a.pattern}\``);
  if (a.nullable) parts.push("may be empty (`nil`)");
  return `\`${a.name}\`: ${parts.join(", ")}${a.doc ? `. ${a.doc}` : ""}`;
}

function shapeDoc(s: Shape): string {
  const names = s.fixed.map((a) => a.name);
  if (s.rest) names.push(`${s.rest.map((a) => a.name).join(", ")}…`);
  return `\`(${names.join(", ")})\``;
}

function optionDoc(o: OptionModel): string {
  // Swift's docs mark the environment variable as code.
  const tags = o.tags.map((x) =>
    x === "security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS)" ? "security option (needs `XI_SECURITY_ALLOW_SECURITY_OPTIONS`)" : x,
  );
  const lines = [
    o.spec.doc,
    "",
    `URL names: ${o.names.map((n) => `\`${n}\``).join(", ")}; arguments ${code(o.spec.syntax)}; default ${code(o.spec.default)}.`,
    `${tags.join("; ")}.`,
    "",
    `Argument shapes: ${o.shapes.map(shapeDoc).join(", ")}.`,
    "",
  ];
  const seen = new Set<string>();
  for (const a of o.args) {
    const d = argDoc(o, a);
    if (seen.has(d)) continue;
    seen.add(d);
    lines.push(`- ${d}`);
  }
  return lines.join("\n");
}

function optionEnum(c: CatalogueModel): Node {
  const { kind } = c;
  const seen = new Set<string>();
  const members = c.options.map((o) => {
    const name = ident(o.name);
    if (seen.has(name)) throw new Error(`${kind}: options ${o.name} and another are both the case ${name}`);
    seen.add(name);
    return N.member(name, N.str(o.name), { doc: doc(o.spec.doc) });
  });
  const stringTable = dict(t("String"), t("String"));
  const body: Node[] = [
    N.blank(),
    computed("short", t("String"), switchSelf(c.options.map((o) => [ident(o.name), N.str(o.short)])), {
      mods: pub,
      doc: doc("The name builders write by default."),
    }),
    N.blank(),
    computed("aliases", array(t("String")), switchSelf(c.options.map((o) => [ident(o.name), strList(o.aliases)])), {
      mods: pub,
      doc: doc("The other names of the option."),
    }),
    N.blank(),
    N.func(
      "init",
      [N.param("name", t("String"))],
      [
        guardLet("canonical", N.invoke(N.get(id("Self"), "catalogue"), "canonical", [id("name")]), [N.ret(N.null())]),
        N.stmt(N.invoke(id("self"), "init", [N.named("rawValue", id("canonical"))])),
      ],
      { mods: ["public", "failable"], doc: doc("The option of a canonical name or an alias.") },
    ),
    N.blank(),
    N.const("names", N.map(c.names.map(([n, canonical]) => N.entry(N.str(n), N.str(canonical))), { layout: "expanded" }), {
      mods: pubStatic,
      type: stringTable,
      doc: doc(`Every ${kind} option name and alias to its canonical name.`),
    }),
    N.blank(),
    N.const(
      "shortNames",
      N.map(
        [...c.options].sort((a, b) => byCode(a.name, b.name)).map((o) => N.entry(N.str(o.name), N.str(o.short))),
        { layout: "expanded" },
      ),
      { mods: pubStatic, type: stringTable, doc: doc(`Canonical ${kind} option name to the name builders write by default.`) },
    ),
    N.blank(),
    N.const(
      "catalogue",
      N.call(id("Catalogue"), [N.named("kind", N.str(catalogueKind[kind])), N.named("names", id("names")), N.named("shortNames", id("shortNames"))]),
      { mods: ["static"] },
    ),
  ];
  for (const [name, e] of argEnums(c.options)) {
    body.push(
      N.blank(),
      strEnum(
        name,
        "invalidArgument",
        `Values of argument \`${e.arg.name}\` of ${kind} option \`${e.option.name}\`${e.arg.doc ? `: ${e.arg.doc}` : ""}.`,
        e.values.map((value) => ({ value })),
      ),
    );
  }
  return N.enum(typeName[kind], members, {
    mods: pub,
    supers: ["String", "CaseIterable", "Sendable", "Hashable"].map(t),
    doc: doc(`${kindDoc[kind]}, by canonical name: short name, aliases and argument enums.`),
    body,
  });
}

function emitOptions(spec: Spec): Node {
  return N.file([...header("Typed option tables of the processing, `/info` and `/video` catalogues."), ...spaced(catalogues(spec).map(optionEnum))]);
}

// ---- Methods.swift -------------------------------------------------------------------

const methodsProtocol: Record<CatalogueKind, string> = {
  processing: "ProcessingOptionMethods",
  info: "InfoOptionMethods",
  video: "VideoOptionMethods",
};

function methods(c: CatalogueModel): Node[] {
  const { kind } = c;
  const P = methodsProtocol[kind];
  const used = new Map<string, string>();
  const funcs: Node[] = [];
  for (const o of c.options) {
    for (const n of o.names) {
      const name = camel(n);
      if (reservedMethods.has(name)) throw new Error(`${kind} option ${n} collides with the builder method ${name}`);
      const prev = used.get(name);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Swift method ${name}`);
      used.set(name, n);
      const text = n === o.name ? optionDoc(o) : `\`${n}\`: alias of \`${camel(o.name)}\`, written as \`${n}\` with the \`given\` name style.`;
      funcs.push(
        N.func(
          ident(n),
          [N.param("args", optional(any(t("ArgConvertible"))), { mods: ["unlabeled", "variadic"] })],
          [N.stmt(N.call(id("option"), [N.str(n), N.named("arguments", N.invoke(id("Arg"), "list", [id("args")]))]))],
          { mods: pub, returns: t("Self"), doc: doc(text) },
        ),
      );
    }
  }
  return [
    N.type("protocol", P, [], { mods: pub, supers: [t("OptionChain")], doc: doc(`A fluent chain with one method per ${kind} option name and alias.`) }),
    N.blank(),
    N.type("extension", P, spaced(funcs)),
  ];
}

function emitMethods(spec: Spec): Node {
  const groups = catalogues(spec).map(methods);
  return N.file([...header("Per-option methods of the fluent URL builders."), ...groups.flatMap((g, i) => (i ? [N.blank(), ...g] : g))]);
}


/** Builder methods the per-option methods must not shadow. */
export const reservedMethods = new Set([
  "option",
  "options",
  "pipeline",
  "extension",
  "encoding",
  "with_pdf_password",
  "build",
  "param",
  "to_s",
  "to_str",
  "inspect",
  "initialize",
]);

const notice = ["Code generated by clients/codegen/emitters/ruby.ts from clients/spec/spec.json.", "DO NOT EDIT. Run `task clients:generate`."];

/** The comment block every RBS file starts with, then an empty line. */
const rbsHeader = (what: string): Node[] => [N.comment("line", [what, "", ...notice]), N.blank()];

/** A Ruby file: the frozen string literal magic comment, the header, the module. */
const rubyFile = (what: string, items: readonly Node[]): Node =>
  N.file([N.comment("line", ["frozen_string_literal: true"]), N.blank(), ...rbsHeader(what), N.namespace("XtandardImage", items)]);

const rbsFile = (what: string, items: readonly Node[]): Node => N.file([...rbsHeader(what), N.namespace("XtandardImage", items)]);

/** A one-line # comment. */
const note = (text: string): Comment => N.comment("line", [text]);

/** A # comment of a text that may span lines (trimmed). */
const comment = (text: string): Comment => N.comment("line", text.trim().split("\n"));

/** Drops the last item (the empty line after the last group). */
const trimLast = (items: Node[]): Node[] => items.slice(0, -1);

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

function optionDoc(o: OptionModel): string {
  return [o.spec.doc, "", `URL names: ${o.names.join(", ")}; arguments ${o.spec.syntax}; default ${o.spec.default}.`, `${o.tags.join("; ")}.`].join(
    "\n",
  );
}

/** Checks the per-option method names of a catalogue and returns [method, name, option] triples. */
function methodNames(c: CatalogueModel): [string, string, OptionModel][] {
  const used = new Map<string, string>();
  const out: [string, string, OptionModel][] = [];
  for (const o of c.options) {
    for (const n of o.names) {
      const id = ident(n);
      if (reservedMethods.has(id)) throw new Error(`${c.kind} option ${n} collides with the builder method ${id}`);
      const prev = used.get(id);
      if (prev !== undefined) throw new Error(`${c.kind} option names ${prev} and ${n} are both the Ruby method ${id}`);
      used.set(id, n);
      out.push([id, n, o]);
    }
  }
  return out;
}

// ---- RBS types --------------------------------------------------------------------------

const t = (name: string, ...args: TypeRef[]) => N.tref(name, args);
const untyped = t("untyped");
const self = t("self");
const str = t("String");
const int = t("Integer");
const number = N.tunion([int, t("Float")]);

/** A union of the distinct types; no type at all is untyped. */
const anyOf = (parts: readonly TypeRef[]): TypeRef => (parts.length === 0 ? untyped : union(parts));

/** "a" | "b" | :"a" | :"b". */
const enumType = (values: readonly string[]) => anyOf([...values.map((v) => N.tlit(N.str(v))), ...values.map((v) => N.tlit(N.sym(v)))]);

/** The RBS type of one argument. */
function argType(a: SpecArg): TypeRef {
  let x: TypeRef;
  switch (a.type) {
    case "integer":
      x = int;
      break;
    case "number":
      x = number;
      break;
    case "boolean":
      x = t("bool");
      break;
    case "enum":
      x = enumType(a.enum ?? []);
      break;
    case "direction":
      x = N.tunion([enumType(["down", "up", "left", "right"]), int, t("Float")]);
      break;
    default:
      x = str;
  }
  return a.nullable ? R.optional(x) : x;
}

/** The RBS tuple (or array, with a repeated tail) of one shape. */
function shapeType(s: Shape): TypeRef {
  if (s.rest) return t("Array", anyOf([...s.fixed, ...s.rest].map(argType)));
  return N.ttuple(s.fixed.map(argType));
}

const positional = (type: TypeRef) => N.param("", type);
const rest = (type: TypeRef) => N.param("", type, { mods: ["variadic"] });

/** One RBS method overload of a shape. */
function shapeOverload(s: Shape): RbsOverload {
  const params = s.fixed.map((a) => positional(argType(a)));
  if (s.rest) params.push(rest(anyOf(s.rest.map(argType))));
  return R.overload(params, self);
}

const valueAlias = (o: OptionModel) => `${o.kind}_${ident(o.name)}_value`;
const argsAlias = (o: OptionModel) => `${o.kind}_${ident(o.name)}_args`;

/** The RBS type of the bare (single, non-nil) first argument an option accepts, if any. */
function bareFirst(o: OptionModel): TypeRef | undefined {
  return o.bare.length ? anyOf(o.bare.map((a) => argType({ ...a, nullable: false }))) : undefined;
}

/** An RBS record of optional keys typed query_value?. */
const queryRecord = (keys: readonly string[]) =>
  R.record(keys.map((name): RbsField => ({ name, key: "symbol", optional: true, type: R.optional(t("query_value")) })));

// ---- lib/xtandard_image/generated/*.rb ----------------------------------------------------

/** A frozen value: x.freeze. */
const frozen = (x: Expr) => N.invoke(x, "freeze");

/** A frozen hash, one entry per line. */
const hash = (entries: readonly (readonly [Expr, Expr])[]) =>
  frozen(N.map(entries.map(([k, v]) => N.entry(k, v)), { layout: "expanded" }));

const strings = (pairs: readonly (readonly [string, string])[]) => hash(pairs.map(([k, v]) => [N.str(k), N.str(v)] as const));

/** A frozen array on one line. */
const list = (values: readonly (string | number)[]) => frozen(N.list(values.map(N.scalar)));

/** A documented constant. */
const constant = (doc: string, name: string, value: Expr) => N.const(name, value, { doc: note(doc) });

function emitCataloguesRb(spec: Spec): Node {
  const items: Node[] = [];
  for (const c of catalogues(spec)) {
    const K = c.kind.toUpperCase();
    items.push(
      constant(`${c.kind} option name or alias to canonical name.`, `${K}_NAMES`, strings(c.names)),
      N.blank(),
      constant(
        `Canonical ${c.kind} option name to the name builders write by default (the shortest).`,
        `${K}_SHORT`,
        strings(c.options.map((o) => [o.name, o.short])),
      ),
      N.blank(),
    );
  }
  return rubyFile("Name tables of the processing, /info and /video option catalogues.", trimLast(items));
}

function emitMethodsRb(spec: Spec): Node {
  const items: Node[] = [];
  for (const c of catalogues(spec)) {
    const methods: Node[] = [];
    for (const [id, n, o] of methodNames(c)) {
      methods.push(
        N.func(id, [N.param("args", undefined, { mods: ["variadic"] })], N.call(N.id("option"), [N.str(n), N.spread(N.id("args"))]), {
          doc: comment(optionDoc(o)),
        }),
        N.blank(),
      );
    }
    items.push(
      N.namespace(`${kindPrefix[c.kind]}Methods`, trimLast(methods), {
        doc: N.comment("line", [
          `One method per ${c.kind} option name and alias; each appends that option,`,
          "written with the name as called. Included by the fluent chains, which",
          "define +option+.",
        ]),
      }),
      N.blank(),
    );
  }
  return rubyFile("Per-option methods of the fluent URL builders.", trimLast(items));
}


// Ruby emitter (clients/ruby, gem xtandard-image, module XtandardImage):
// writes lib/xtandard_image/generated/ and sig/generated/ from the spec.
//
//   lib/…/generated/catalogues.rb  the name tables (name or alias to
//                                  canonical, canonical to short)
//   lib/…/generated/methods.rb     the fluent builders' per-option methods
//                                  (ProcessingMethods, InfoMethods, VideoMethods)
//   lib/…/generated/constants.rb   formats, containers, streams, query keys,
//                                  imaginary, sources, signing, encryption,
//                                  URL rules, error kinds
//   sig/generated/catalogues.rbs   one argument-tuple type per option, the
//                                  options records, the name tables
//   sig/generated/methods.rbs      typed overloads of every per-option method
//   sig/generated/constants.rbs    the constants and their literal types
//   sig/generated/responses.rbs    records of the JSON bodies (info_response,
//                                  error_response; string keys, as JSON.parse
//                                  returns them)
//
// Ruby >= 3.2. Every Ruby file starts with the frozen string literal magic
// comment. RuboCop skips the generated files; Steep checks them, except
// the bodies of the per-option methods (their overloads still check callers).


// ---- sig/generated/*.rbs ------------------------------------------------------

function emitCataloguesRbs(spec: Spec): string {
  const out: string[] = [rbsHeader("Option argument types, options records and name tables of the three catalogues.")];
  out.push("module XtandardImage");
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    out.push(`  # ---- ${kind} ${"-".repeat(66 - kind.length)}`);
    out.push("");
    for (const o of opts) {
      out.push(`  # Argument lists of ${kind} option \`${o.name}\`.`);
      out.push(`  type ${argsAlias(kind, o)} = ${union(shapes(o).map(shapeType))}`);
      const bare = bareFirst(o);
      out.push(`  type ${valueAlias(kind, o)} = ${bare ? `${argsAlias(kind, o)} | ${bare}` : argsAlias(kind, o)}`);
    }
    out.push("");
    const byName = new Map(opts.map((o) => [o.name, o]));
    out.push(`  # ${kind} options of one pipeline, keyed by name or alias (symbols), in URL order.`);
    out.push("  # A value is the argument list, or the first argument alone when the rest are");
    out.push("  # optional: { rs: [\"fill\", 300, 400], q: 80 }. nil inside a list is an empty");
    out.push("  # argument; a nil value skips the option. String keys work at run time too.");
    out.push(`  type ${kind}_options = {`);
    const names = nameTable(opts);
    names.forEach(([n, canonical], i) => {
      const t = `${valueAlias(kind, byName.get(canonical)!)}?`;
      out.push(`    ?${recordKey(n)} ${t}${i < names.length - 1 ? "," : ""}`);
    });
    out.push("  }");
    out.push("");
    out.push(`  # Every ${kind} option name and alias.`);
    out.push(`  type ${kind}_option_name = ${union(names.map(([n]) => rbsStr(n)))}`);
    out.push("");
    out.push(`  ${kind.toUpperCase()}_NAMES: Hash[String, String]`);
    out.push(`  ${kind.toUpperCase()}_SHORT: Hash[String, String]`);
    out.push("");
  }
  out.pop();
  out.push("end");
  out.push("");
  return out.join("\n");
}

/** The RBS type of the bare (single, non-nil) first argument an option accepts, if any. */
function bareFirst(o: SpecOption): string | undefined {
  const parts: string[] = [];
  for (const f of o.forms) {
    if (Math.max(f.min_items, 1) > 1) continue;
    const first = f.args[0] ?? f.rest?.[0];
    if (first) parts.push(argType({ ...first, nullable: false }));
  }
  return parts.length ? union(parts) : undefined;
}

function emitMethodsRbs(spec: Spec): string {
  const out: string[] = [rbsHeader("Typed per-option methods of the fluent URL builders.")];
  out.push("module XtandardImage");
  out.push("  # What the per-option method modules need from the class that includes them.");
  out.push("  interface _OptionChain");
  out.push("    def option: (String | Symbol name, *arg args) -> self");
  out.push("  end");
  out.push("");
  for (const kind of ["processing", "info", "video"] as const) {
    const K = kindPrefix[kind];
    out.push(`  # One method per ${kind} option name and alias.`);
    out.push(`  module ${K}Methods : _OptionChain`);
    for (const [id, , o] of methodNames(spec, kind)) {
      const overloads = shapes(o).map(shapeOverload);
      const all = union(allArgs(o).map(argType));
      // The untyped tail form keeps every runtime-valid call typable (the
      // server is the judge of argument ranges).
      if (!overloads.includes(`(*${group(all)}) -> self`)) overloads.push(`(*${group(all)}) -> self`);
      out.push(`    def ${id}: ${overloads[0]}`);
      for (const ov of overloads.slice(1)) out.push(`         ${" ".repeat(id.length)}| ${ov}`);
    }
    out.push("  end");
    out.push("");
  }
  out.pop();
  out.push("end");
  out.push("");
  return out.join("\n");
}


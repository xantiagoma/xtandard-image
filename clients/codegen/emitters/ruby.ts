const typeName = (schema: string) => schema.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2").toLowerCase();

function schemaType(s: JSONSchema): string {
  if (s.$ref) return typeName(s.$ref.replace("#/components/schemas/", ""));
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  if (s.enum) {
    const t = union(s.enum.filter((v) => v !== null).map((v) => JSON.stringify(v)));
    return s.enum.includes(null) || types.includes("null") ? `${group(t)}?` : t;
  }
  const parts: string[] = [];
  let nullable = false;
  for (const t of types) {
    switch (t) {
      case "string":
        parts.push("String");
        break;
      case "integer":
        parts.push("Integer");
        break;
      case "number":
        parts.push("Integer | Float");
        break;
      case "boolean":
        parts.push("bool");
        break;
      case "null":
        nullable = true;
        break;
      case "array":
        parts.push(`Array[${s.items ? schemaType(s.items) : "untyped"}]`);
        break;
      case "object":
        if (s.properties) throw new Error("inline object schemas are not supported");
        parts.push(
          `Hash[String, ${typeof s.additionalProperties === "object" && Object.keys(s.additionalProperties).length > 0 ? schemaType(s.additionalProperties) : "untyped"}]`,
        );
        break;
      default:
        parts.push("untyped");
    }
  }
  const t = parts.length === 0 ? "untyped" : union(parts);
  return nullable && t !== "untyped" ? `${group(t)}?` : t;
}

function emitResponsesRbs(spec: Spec): string {
  const out: string[] = [rbsHeader("Records of the JSON response bodies (the OpenAPI components), with string keys as JSON.parse returns them.")];
  out.push("module XtandardImage");
  const names = Object.keys(spec.response_schemas).sort();
  for (const name of names) {
    const s = spec.response_schemas[name]!;
    out.push(...comment((s.description ?? name).split("\n")[0]!, "  "));
    out.push(`  type ${typeName(name)} = {`);
    const req = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {}).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    props.forEach(([p, ps], i) => {
      out.push(`    ${req.has(p) ? "" : "?"}${rbsStr(p)} => ${schemaType(ps)}${i < props.length - 1 ? "," : ""}`);
    });
    out.push("  }");
  }
  out.push("end");
  out.push("");
  return out.join("\n");
}

export const emitter: Emitter = {
  language: "ruby",
  emit(spec) {
    return {
      [`${lib}catalogues.rb`]: emitCataloguesRb(spec),
      [`${lib}methods.rb`]: emitMethodsRb(spec),
      [`${lib}constants.rb`]: emitConstantsRb(spec),
      [`${sig}catalogues.rbs`]: emitCataloguesRbs(spec),
      [`${sig}methods.rbs`]: emitMethodsRbs(spec),
      [`${sig}constants.rbs`]: emitConstantsRbs(spec),
      [`${sig}responses.rbs`]: emitResponsesRbs(spec),
    };
  },
};

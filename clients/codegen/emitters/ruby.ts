/** Builder methods the per-option methods must not shadow. */
export const reservedMethods = new Set([
  "option",
  "options",
  "pipeline",
  "extension",
  "encoding",
  "with_pdf_password",
  "build",
  "param",
  "to_s",
  "to_str",
  "inspect",
  "initialize",
]);

/** A Ruby double-quoted string literal (no interpolation). */
const rb = (s: string) => JSON.stringify(s).replaceAll("#", "\\#");

/** A Ruby symbol literal. */
const sym = (s: string) => (/^[a-z_][a-z0-9_]*$/.test(s) ? `:${s}` : `:${rb(s)}`);

/** An RBS string literal type. */
const rbsStr = (s: string) => JSON.stringify(s);

/** An RBS symbol literal type (always quoted, so keywords and dashes are fine). */
const rbsSym = (s: string) => `:${JSON.stringify(s)}`;

/** An RBS record key: `name:` when it is a plain symbol, otherwise `:"min-width" =>`. */
const recordKey = (s: string) => (/^[a-z_][a-z0-9_]*$/.test(s) ? `${s}:` : `${rbsSym(s)} =>`);

/** A Ruby method name for an option name or alias ("min-width" → "min_width"). */
function ident(name: string): string {
  let id = name.replace(/[^A-Za-z0-9_]/g, "_");
  if (/^[0-9]/.test(id)) id = `_${id}`;
  return id;
}

/** A JS/Go regular expression as a Ruby Regexp literal anchored on the whole string. */
function regexp(pattern: string): string {
  let p = pattern;
  if (p.startsWith("^")) p = `\\A${p.slice(1)}`;
  if (p.endsWith("$") && !p.endsWith("\\$")) p = `${p.slice(0, -1)}\\z`;
  return `/${p.replaceAll("/", "\\/")}/`;
}

function comment(text: string, indent: string): string[] {
  return text
    .trim()
    .split("\n")
    .map((l) => (l === "" ? `${indent}#` : `${indent}# ${l}`));
}

function union(parts: string[]): string {
  const uniq = [...new Set(parts)];
  return uniq.length === 0 ? "untyped" : uniq.join(" | ");
}

/** Wraps a union in parentheses so a `?` or `*` applies to all of it. */
const group = (t: string) => (t.includes(" | ") ? `(${t})` : t);

const enumType = (values: readonly string[]) => union([...values.map(rbsStr), ...values.map(rbsSym)]);

/** The RBS type of one argument. */
function argType(a: SpecArg): string {
  let t: string;
  switch (a.type) {
    case "integer":
      t = "Integer";
      break;
    case "number":
      t = "Integer | Float";
      break;
    case "boolean":
      t = "bool";
      break;
    case "enum":
      t = enumType(a.enum ?? []);
      break;
    case "direction":
      t = `${enumType(["down", "up", "left", "right"])} | Integer | Float`;
      break;
    default:
      t = "String";
  }
  return a.nullable ? `${group(t)}?` : t;
}

/** The RBS tuple (or array, with a repeated tail) of one shape. */
function shapeType(s: Shape): string {
  if (s.rest) return `Array[${union([...s.fixed, ...s.rest].map(argType))}]`;
  return `[${s.fixed.map(argType).join(", ")}]`;
}

/** One RBS method overload of a shape. */
function shapeOverload(s: Shape): string {
  const params = s.fixed.map(argType);
  if (s.rest) params.push(`*${group(union(s.rest.map(argType)))}`);
  return `(${params.join(", ")}) -> self`;
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

const valueAlias = (kind: CatalogueKind, o: SpecOption) => `${kind}_${ident(o.name)}_value`;
const argsAlias = (kind: CatalogueKind, o: SpecOption) => `${kind}_${ident(o.name)}_args`;

function optionDoc(o: SpecOption): string {
  const lines = [o.doc, "", `URL names: ${[o.name, ...o.aliases].join(", ")}; arguments ${o.syntax}; default ${o.default}.`];
  const tags: string[] = [];
  if (o.milestone) tags.push(`milestone ${o.milestone}`);
  tags.push(`scope ${o.scope}`);
  if (o.pro) tags.push("imgproxy Pro option (free here)");
  if (o.security) tags.push("security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS)");
  if (o.removed) tags.push("removed: accepted and ignored");
  lines.push(`${tags.join("; ")}.`);
  return lines.join("\n");
}

/** Checks the per-option method names of a catalogue and returns [method, name, option] triples. */
function methodNames(spec: Spec, kind: CatalogueKind): [string, string, SpecOption][] {
  const used = new Map<string, string>();
  const out: [string, string, SpecOption][] = [];
  for (const o of spec.options[kind]) {
    for (const n of [o.name, ...o.aliases]) {
      const id = ident(n);
      if (reservedMethods.has(id)) throw new Error(`${kind} option ${n} collides with the builder method ${id}`);
      const prev = used.get(id);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Ruby method ${id}`);
      used.set(id, n);
      out.push([id, n, o]);
    }
  }
  return out;
}


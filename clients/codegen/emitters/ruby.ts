// ---- sig/generated/*.rbs ----------------------------------------------------------------

function emitCataloguesRbs(spec: Spec): Node {
  const items: Node[] = [];
  for (const c of catalogues(spec)) {
    const { kind } = c;
    items.push(N.comment("line", [`---- ${kind} ${"-".repeat(66 - kind.length)}`]), N.blank());
    for (const o of c.options) {
      const args = t(argsAlias(o));
      const bare = bareFirst(o);
      items.push(
        N.typeAlias(argsAlias(o), anyOf(o.shapes.map(shapeType)), { doc: note(`Argument lists of ${kind} option \`${o.name}\`.`) }),
        N.typeAlias(valueAlias(o), bare ? N.tunion([args, bare]) : args),
      );
    }
    items.push(
      N.blank(),
      N.typeAlias(
        `${kind}_options`,
        R.record(
          c.names.map(([n, canonical]): RbsField => ({ name: n, key: "symbol", optional: true, type: R.optional(t(valueAlias(c.byName.get(canonical)!))) })),
        ),
        {
          doc: N.comment("line", [
            `${kind} options of one pipeline, keyed by name or alias (symbols), in URL order.`,
            "A value is the argument list, or the first argument alone when the rest are",
            'optional: { rs: ["fill", 300, 400], q: 80 }. nil inside a list is an empty',
            "argument; a nil value skips the option. String keys work at run time too.",
          ]),
        },
      ),
      N.blank(),
      N.typeAlias(`${kind}_option_name`, anyOf(c.names.map(([n]) => N.tlit(N.str(n)))), { doc: note(`Every ${kind} option name and alias.`) }),
      N.blank(),
      N.const(`${kind.toUpperCase()}_NAMES`, undefined, { type: t("Hash", str, str) }),
      N.const(`${kind.toUpperCase()}_SHORT`, undefined, { type: t("Hash", str, str) }),
      N.blank(),
    );
  }
  return rbsFile("Option argument types, options records and name tables of the three catalogues.", trimLast(items));
}

function emitMethodsRbs(spec: Spec): Node {
  const items: Node[] = [
    N.type("interface", "_OptionChain", [R.method("option", [R.overload([N.param("name", N.tunion([str, t("Symbol")])), N.param("args", t("arg"), { mods: ["variadic"] })], self)])], {
      doc: note("What the per-option method modules need from the class that includes them."),
    }),
    N.blank(),
  ];
  for (const c of catalogues(spec)) {
    const methods: Node[] = [];
    for (const [id, , o] of methodNames(c)) {
      const overloads = o.shapes.map(shapeOverload);
      // The untyped tail form keeps every runtime-valid call typable (the
      // server is the judge of argument ranges).
      const tail = R.overload([rest(anyOf(o.args.map(argType)))], self);
      if (!overloads.some((ov) => rbs.print(ov) === rbs.print(tail))) overloads.push(tail);
      methods.push(R.method(id, overloads));
    }
    items.push(
      N.type("mixin", `${kindPrefix[c.kind]}Methods`, methods, {
        supers: [t("_OptionChain")],
        doc: note(`One method per ${c.kind} option name and alias.`),
      }),
      N.blank(),
    );
  }
  return rbsFile("Typed per-option methods of the fluent URL builders.", trimLast(items));
}


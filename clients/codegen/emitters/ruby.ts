function schemaType(s: JSONSchema): TypeRef {
  if (s.$ref) return t(typeName(refName(s.$ref)));
  const types = schemaTypes(s);
  if (s.enum) {
    const x = anyOf(s.enum.filter((v) => v !== null).map((v) => N.tlit(N.scalar(v as string | number))));
    return s.enum.includes(null) || types.includes("null") ? R.optional(x) : x;
  }
  const parts: TypeRef[] = [];
  let nullable = false;
  for (const ty of types) {
    switch (ty) {
      case "string":
        parts.push(str);
        break;
      case "integer":
        parts.push(int);
        break;
      case "number":
        parts.push(number);
        break;
      case "boolean":
        parts.push(t("bool"));
        break;
      case "null":
        nullable = true;
        break;
      case "array":
        parts.push(t("Array", s.items ? schemaType(s.items) : untyped));
        break;
      case "object": {
        if (s.properties) throw new Error("inline object schemas are not supported");
        const ap = s.additionalProperties;
        parts.push(t("Hash", str, typeof ap === "object" && Object.keys(ap).length > 0 ? schemaType(ap) : untyped));
        break;
      }
      default:
        parts.push(untyped);
    }
  }
  const x = anyOf(parts);
  return nullable && x !== untyped ? R.optional(x) : x;
}

function emitResponsesRbs(spec: Spec): Node {
  const items: Node[] = responseSchemas(spec).map((sm) =>
    N.typeAlias(
      typeName(sm.name),
      R.record(sm.properties.map(([p, ps]): RbsField => ({ name: p, key: "string", optional: !sm.required.has(p), type: schemaType(ps) }))),
      { doc: comment((sm.schema.description ?? sm.name).split("\n")[0]!) },
    ),
  );
  return rbsFile("Records of the JSON response bodies (the OpenAPI components), with string keys as JSON.parse returns them.", items);
}

export const emitter: Emitter = {
  language: "ruby",
  emit(spec) {
    return {
      [`${lib}catalogues.rb`]: ruby.print(emitCataloguesRb(spec)),
      [`${lib}methods.rb`]: ruby.print(emitMethodsRb(spec)),
      [`${lib}constants.rb`]: ruby.print(emitConstantsRb(spec)),
      [`${sig}catalogues.rbs`]: rbs.print(emitCataloguesRbs(spec)),
      [`${sig}methods.rbs`]: rbs.print(emitMethodsRbs(spec)),
      [`${sig}constants.rbs`]: rbs.print(emitConstantsRbs(spec)),
      [`${sig}responses.rbs`]: rbs.print(emitResponsesRbs(spec)),
    };
  },
};

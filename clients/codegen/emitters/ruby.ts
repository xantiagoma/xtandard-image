function hash(entries: [string, string][], indent: string): string[] {
  return [`{`, ...entries.map(([k, v]) => `${indent}  ${rb(k)} => ${rb(v)},`), `${indent}}.freeze`];
}

function emitCataloguesRb(spec: Spec): string {
  const out: string[] = [rubyHeader("Name tables of the processing, /info and /video option catalogues.")];
  out.push("module XtandardImage");
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    const K = kind.toUpperCase();
    out.push(`  # ${kind} option name or alias to canonical name.`);
    const names = hash(nameTable(opts), "  ");
    out.push(`  ${K}_NAMES = ${names[0]}`, ...names.slice(1));
    out.push("");
    out.push(`  # Canonical ${kind} option name to the name builders write by default (the shortest).`);
    const short = hash(opts.map((o) => [o.name, o.short]), "  ");
    out.push(`  ${K}_SHORT = ${short[0]}`, ...short.slice(1));
    out.push("");
  }
  out.pop();
  out.push("end");
  out.push("");
  return out.join("\n");
}

function emitMethodsRb(spec: Spec): string {
  const out: string[] = [rubyHeader("Per-option methods of the fluent URL builders.")];
  out.push("module XtandardImage");
  for (const kind of ["processing", "info", "video"] as const) {
    const K = kindPrefix[kind];
    out.push(`  # One method per ${kind} option name and alias; each appends that option,`);
    out.push("  # written with the name as called. Included by the fluent chains, which");
    out.push("  # define +option+.");
    out.push(`  module ${K}Methods`);
    for (const [id, n, o] of methodNames(spec, kind)) {
      out.push(...comment(optionDoc(o), "    "));
      out.push(`    def ${id}(*args) = option(${rb(n)}, *args)`);
      out.push("");
    }
    out.pop();
    out.push("  end");
    out.push("");
  }
  out.pop();
  out.push("end");
  out.push("");
  return out.join("\n");
}

function list(values: readonly (string | number)[]): string {
  return `[${values.map((v) => (typeof v === "string" ? rb(v) : String(v))).join(", ")}].freeze`;
}


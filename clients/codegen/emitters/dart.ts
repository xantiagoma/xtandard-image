interface DartType {
  /** The Dart type without `?`. */
  readonly type: TypeRef;
  readonly nullable: boolean;
  /** The decoding expression of a JSON value v (nullability checked by the caller), w naming it in errors. */
  decode(v: Expr, w: Expr): Expr;
}

const anyType: DartType = { type: t("Object"), nullable: true, decode: (v) => v };
/** The type with `?`. */
const orNull = (x: TypeRef): TypeRef => (x.k === "tref" ? { ...x, nullable: true } : x);
const elemType = (it: DartType) => (it.nullable ? orNull(it.type) : it.type);
const decoder = (fn: string) => (v: Expr, w: Expr) => N.call(id(fn), [v, w]);

function schemaType(s: JSONSchema): DartType {
  if (s.$ref) {
    const n = refName(s.$ref);
    return { type: t(n), nullable: false, decode: (v, w) => N.invoke(id(n), "fromJson", [N.call(id("jsonObject"), [v, w])]) };
  }
  const types = schemaTypes(s);
  const nullable = types.includes("null") || (s.enum?.includes(null) ?? false);
  const ts = types.filter((x) => x !== "null");
  if (ts.length !== 1) return anyType;
  switch (ts[0]) {
    case "string":
      return { type: str, nullable, decode: decoder("jsonString") };
    case "integer":
      return { type: int, nullable, decode: decoder("jsonInt") };
    case "number":
      return { type: t("double"), nullable, decode: decoder("jsonDouble") };
    case "boolean":
      return { type: t("bool"), nullable, decode: decoder("jsonBool") };
    case "array": {
      const it = s.items ? schemaType(s.items) : anyType;
      const type = listOf(elemType(it));
      const one = (x: Expr, w: Expr) => (it.nullable ? ternary(N.binary("==", x, N.null()), N.null(), it.decode(x, w)) : it.decode(x, w));
      return {
        type,
        nullable,
        decode: (v, w) =>
          N.invoke(N.typeExpr(type), "unmodifiable", [N.invoke(N.call(id("jsonList"), [v, w]), "map", [N.lambda([N.param("e")], one(id("e"), w))])]),
      };
    }
    case "object": {
      if (s.properties) throw new Error("inline object schemas are not supported");
      const ap = s.additionalProperties;
      const it = typeof ap === "object" && (ap.type !== undefined || ap.$ref !== undefined) ? schemaType(ap) : anyType;
      const type = mapOf(elemType(it));
      const isObject = it.type.k === "tref" && it.type.name === "Object";
      const one = (x: Expr, w: Expr) =>
        it.nullable && !isObject ? ternary(N.binary("==", x, N.null()), N.null(), it.decode(x, w)) : it.decode(x, w);
      return {
        type,
        nullable,
        decode: (v, w) =>
          N.invoke(N.typeExpr(type), "unmodifiable", [
            N.invoke(N.call(id("jsonObject"), [v, w]), "map", [
              N.lambda([N.param("k"), N.param("e")], N.call(id("MapEntry"), [id("k"), one(id("e"), w)])),
            ]),
          ]),
      };
    }
    default:
      return anyType;
  }
}

function emitResponses(spec: Spec): Node {
  const items: Node[] = [
    ...header("The JSON response bodies (the OpenAPI components), with fromJson."),
    N.imp("../json.dart"),
    N.blank(),
  ];
  const json = id("json");
  for (const sm of responseSchemas(spec)) {
    const { name } = sm;
    const desc = (sm.schema.description ?? `The ${name} object of the server's JSON responses.`).split("\n\n")[0]!;
    const fields = sm.properties.map(([p, ps]) => {
      const ty = schemaType(ps);
      const fid = ident(p);
      if (fid === "json") throw new Error(`${name}.${p} collides with the json field`);
      return { p, ps, t: ty, id: fid, required: sm.required.has(p) && !ty.nullable };
    });
    const members: Node[] = [
      N.func(
        name,
        [
          ...fields.map((f) => N.param(f.id, undefined, { mods: ["named", "this", ...(f.required ? ["required"] : [])] })),
          N.param("json", undefined, { mods: ["named", "this"], value: constOf(N.map([])) }),
        ],
        undefined,
        { mods: ["const"], doc: N.doc(`Creates a ${name}.`) },
      ),
      N.blank(),
      N.func(
        `${name}.fromJson`,
        [N.param("json", mapOf(opt("Object")))],
        N.call(
          id(name),
          [
            ...fields.map((f) => {
              const w = N.str(`${name}.${f.p}`);
              const v = N.index(json, N.str(f.p));
              return N.named(f.id, f.required ? f.t.decode(v, w) : ternary(N.binary("==", v, N.null()), N.null(), f.t.decode(v, w)));
            }),
            N.named("json", json),
          ],
          { layout: "expanded" },
        ),
        { mods: ["factory"], doc: N.doc(`Decodes a ${name} from a decoded JSON object; throws [FormatException] on a wrong type.`) },
      ),
      N.blank(),
    ];
    for (const f of fields) {
      const type = f.required ? f.t.type : orNull(f.t.type);
      members.push(N.field(f.id, type, { mods: ["final"], doc: mdDoc(f.ps.description ?? `\`${f.p}\`.`) }), N.blank());
    }
    members.push(
      N.field("json", mapOf(opt("Object")), { mods: ["final"], doc: N.doc("The decoded JSON object, including fields newer than this client.") }),
    );
    items.push(N.type("class", name, members, { mods: ["final"], doc: mdDoc(desc) }), N.blank());
  }
  return file(items);
}

export const emitter: Emitter = {
  language: "dart",
  emit(spec) {
    const files: Record<string, Node> = {
      "catalogue.g.dart": emitCatalogue(spec),
      "options.g.dart": emitOptions(spec),
      "methods.g.dart": emitMethods(spec),
      "constants.g.dart": emitConstants(spec),
      "responses.g.dart": emitResponses(spec),
    };
    return Object.fromEntries(Object.entries(files).map(([f, n]) => [`${dir}${f}`, printer.print(n)]));
  },
};

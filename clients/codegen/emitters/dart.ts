    "",
    "  const SegmentFormat(this.value, this.aliases, this.protocols);",
    "",
    "  /// The name as written in URLs.",
    "  final String value;",
    "",
    "  /// Other names the server accepts.",
    "  final List<String> aliases;",
    "",
    "  /// The protocols that accept this format.",
    "  final List<StreamProtocol> protocols;",
    "",

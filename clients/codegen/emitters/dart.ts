  c("Pattern of an `xi://` source name.", `const String xiNamePattern = ${str(spec.sources.xi_name_pattern)};`);
  c("Default mount of the query dialect.", `const String queryMount = ${str(spec.query.mount)};`);
  out.push("/// Video option names written as native `/q/video` keys (`crop` → `c`).");

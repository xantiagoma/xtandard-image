/** A file of items; a trailing blank() is dropped (the file ends with one newline). */
const file = (items: Node[]) => N.file(items.at(-1)?.k === "blank" ? items.slice(0, -1) : items);

/** A string-keyed table, one entry per line. */
const table = (entries: readonly (readonly [string, string])[]) =>
  N.map(entries.map(([k, v]) => N.entry(N.str(k), N.str(v))), { layout: "expanded" });

/** A top-level `const T name = value;`. */
const constant = (name: string, type: TypeRef, value: Expr, doc?: Comment) =>
  N.const(name, value, { type, mods: ["const"], ...(doc ? { doc } : {}) });

/** The Dart type of one argument (non-nullable form). */
function baseType(a: SpecArg): string {
  switch (a.type) {
    case "integer":
      return "int";
    case "number":
      return "num";
    case "boolean":
      return "bool";
    case "direction":
      return "Object";
    default:
      return "String";
  }
}

function argDoc(a: SpecArg): string {
  const parts: string[] = [];
  parts.push(a.doc ? a.doc.replace(/\.?$/, ".") : `${a.name.replaceAll("_", " ")} (${a.type}).`);
  if (a.enum?.length) parts.push(`One of ${a.enum.map((v) => `\`${v}\``).join(", ")}.`);
  if (a.type === "direction") parts.push("A direction (`down`, `up`, `left`, `right`) or an angle in degrees.");
  if (a.type === "base64") parts.push("URL-safe base64, written as given.");
  if (a.type === "color") parts.push("A hex colour (`ff0000`, `f00`, with optional alpha).");
  const range: string[] = [];
  if (a.min !== undefined) range.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) range.push(`≤ ${a.max}`);
  if (range.length) parts.push(`Range ${range.join(", ")}.`);
  if (a.nullable) parts.push("Null writes an empty argument.");
  return parts.join(" ");
}

// ---- signatures --------------------------------------------------------------

interface Param {
  readonly name: string;
  /** Dart type name without `?`. */
  readonly type: string;
  readonly nullable: boolean;
  readonly docs: string[];
}

/** The repeated tail of a signature. */
interface Rest {
  readonly name: string;
  /** The element type: a type, or a named record of fields. */
  readonly elem: TypeRef;
  /** Record fields (empty for a single repeated argument). */
  readonly fields: readonly { readonly name: string; readonly type: TypeRef }[];
  readonly required: boolean;
  readonly doc: string;
}

/** The one Dart signature of an option: `required` leading positional parameters, the rest optional. */
interface Signature {
  readonly params: Param[];
  readonly required: number;
  readonly rest?: Rest;
}

function plural(name: string): string {
  const c = camel(name);
  const pl = /(s|x|ch|sh)$/.test(c) ? `${c}es` : /[^aeiou]y$/.test(c) ? `${c.slice(0, -1)}ies` : `${c}s`;
  return reserved.has(pl) ? `${pl}_` : pl;
}

function uniqueName(name: string, used: Set<string>): string {
  let n = name;
  for (let i = 2; used.has(n); i++) n = `${name}${i}`;
  used.add(n);
  return n;
}

/** How many leading arguments a form requires. */
function formRequired(f: SpecForm): number {
  const min = Math.max(f.min_items, 1);
  return Math.min(min, f.args.length);
}

/** The type of position i in a form: a fixed argument, a repeated one, or undefined past its end. */
function typeAt(f: SpecForm, i: number): SpecArg | undefined {
  if (i < f.args.length) return f.args[i];
  if (f.rest && f.rest.length > 0) return f.rest[(i - f.args.length) % f.rest.length];
  return undefined;
}

function signature(o: SpecOption): Signature {
  const used = new Set<string>();
  if (o.forms.length === 1) {
    const f = o.forms[0]!;
    const required = formRequired(f);
    const params = f.args.map((a, i) => ({
      name: uniqueName(ident(a.name), used),
      type: baseType(a),
      nullable: a.nullable || i >= required,
      docs: [argDoc(a)],
    }));
    if (!f.rest || f.rest.length === 0) return { params, required };
    const restRequired = Math.max(f.min_items, 1) > f.args.length;
    // A required repeated tail makes every fixed argument required too.
    const req = restRequired ? params.length : required;
    const r = f.rest;
    const restDoc = `Repeated ${r.length === 1 ? "argument" : "groups"}: ${r.map((a) => `\`${a.name}\`: ${argDoc(a)}`).join(" ")}`;
    if (r.length === 1) {
      const a = r[0]!;
      return {
        params,
        required: req,
        rest: { name: uniqueName(plural(a.name), used), elem: t(baseType(a)), fields: [], required: restRequired, doc: restDoc },
      };
    }
    const fieldsUsed = new Set<string>();
    const fields = r.map((a) => ({ name: uniqueName(ident(a.name), fieldsUsed), type: t(baseType(a)) }));
    return {
      params,
      required: req,
      rest: { name: uniqueName("groups", used), elem: N.ext("dart.record", { fields }), fields, required: restRequired, doc: restDoc },
    };
  }
  // Several forms: merge them position by position.
  const length = Math.max(...o.forms.map((f) => f.args.length));
  const required = Math.min(...o.forms.map(formRequired));
  const params: Param[] = [];
  for (let i = 0; i < length; i++) {
    const at = o.forms.map((f) => typeAt(f, i)).filter((a): a is SpecArg => a !== undefined);
    const types = new Set(at.map(baseType));
    const fixed = o.forms.map((f) => f.args[i]).filter((a): a is SpecArg => a !== undefined);
    const docs = [...new Set(at.map(argDoc))];
    params.push({
      name: uniqueName(ident(fixed[0]!.name), used),
      type: types.size === 1 ? [...types][0]! : "Object",
      nullable: i >= required || at.some((a) => a.nullable),
      docs,
    });
  }
  const restForms = o.forms.filter((f) => f.rest && f.rest.length > 0);
  if (restForms.length === 0) return { params, required };
  const restDoc = `More arguments of the forms that repeat: ${restForms
    .map((f) => `${f.args.map((a) => a.name).join(", ")}, then (${f.rest!.map((a) => a.name).join(", ")})…`)
    .join("; ")}.`;
  return { params, required, rest: { name: uniqueName("more", used), elem: opt("Object"), fields: [], required: false, doc: restDoc } };
}

/** The parameter nodes of a signature: required positional, then optional positional. */
function paramNodes(s: Signature): PNode[] {
  const out = s.params.map((p, i) =>
    N.param(p.name, N.tref(p.type, [], { nullable: p.nullable }), i < s.required ? {} : { mods: ["optional"] }),
  );
  if (s.rest) {
    const type = listOf(s.rest.elem);
    out.push(s.rest.required ? N.param(s.rest.name, type) : N.param(s.rest.name, type, { value: constOf(N.list([])), mods: ["optional"] }));
  }
  return out;
}

/** The expression building the argument list of a signature. */
function argsExpr(s: Signature): Expr {
  const items: Expr[] = s.params.map((p) => id(p.name));
  if (s.rest) {
    const r = s.rest;
    if (r.fields.length === 0) items.push(N.spread(id(r.name)));
    else items.push(forElement("g", id(r.name), N.spread(N.list(r.fields.map((f) => N.get(id("g"), f.name))))));
  }
  const list = N.list(items);
  return s.params.slice(s.required).length > 0 ? N.call(id("trimArgs"), [list, N.int(s.required)]) : list;
}

function optionSummary(o: SpecOption): string {
  return o.doc.trim().replace(/\.?$/, ".");
}

function optionDetails(o: SpecOption): string {
  const tags: string[] = [];
  tags.push(`URL names: ${[o.name, ...o.aliases].map((n) => `\`${n}\``).join(", ")}; arguments \`${o.syntax}\`; default ${o.default}.`);
  tags.push(o.milestone ? `Milestone ${o.milestone}; scope ${o.scope}.` : `Scope ${o.scope}.`);
  if (o.pro) tags.push("imgproxy Pro option (free here).");
  if (o.security) tags.push("Security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS).");
  if (o.removed) tags.push("Removed: accepted and ignored.");
  return tags.join(" ");
}

/** The doc comment of an option's constructor or method: summary, details, one line per parameter. */
function signatureDoc(o: SpecOption, s: Signature): Comment {
  const paras = [optionSummary(o), optionDetails(o)];
  const params: string[] = [];
  for (const p of s.params) params.push(`- \`${p.name}\`: ${p.docs.join(" Or: ")}`);
  if (s.rest) params.push(`- \`${s.rest.name}\`: ${s.rest.doc}`);
  if (params.length) paras.push(params.join("\n"));
  return N.comment(
    "doc",
    paras.flatMap((p, i) => [...(i ? [""] : []), ...md(p.trim()).split("\n")]),
  );
}


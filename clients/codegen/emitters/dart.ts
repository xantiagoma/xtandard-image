/** Members of OptionValue that the named constructors must not shadow. */
const reservedConstructors = new Set(["name", "args", "toString", "hashCode", "runtimeType", "noSuchMethod"]);

const str = (s: string) => `'${s.replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("$", "\\$").replaceAll("\n", "\\n")}'`;

/** lowerCamelCase of a name ("min-width" → "minWidth", "c_obj" → "cObj", "R" → "r"). */
function camel(name: string): string {
  const p = pascal(name);
  return p.length === 0 ? "value" : p[0]!.toLowerCase() + p.slice(1);
}

/** A Dart identifier for a method, parameter or field: lowerCamelCase, reserved words get a trailing `_`. */
function ident(name: string): string {
  const id = camel(name);
  return reserved.has(id) ? `${id}_` : id;
}

/** Escapes Markdown that dartdoc would read as references or HTML, outside `code` spans. */
function md(text: string): string {
  return text
    .split("`")
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/([[\]<>])/g, (c) => ({ "[": "\\[", "]": "\\]", "<": "&lt;", ">": "&gt;" })[c]!)))
    .join("`");
}

/** A `///` comment from paragraphs, each line prefixed by indent. */
function doc(indent: string, text: string): string[] {
  return md(text.trim())
    .split("\n")
    .map((l) => `${indent}///${l === "" ? "" : ` ${l}`}`);
}

/** The Dart type of one argument (non-nullable form). */
function baseType(a: SpecArg): string {
  switch (a.type) {
    case "integer":
      return "int";
    case "number":
      return "num";
    case "boolean":
      return "bool";
    case "direction":
      return "Object";
    default:
      return "String";
  }
}

function argDoc(a: SpecArg): string {
  const parts: string[] = [];
  parts.push(a.doc ? a.doc.replace(/\.?$/, ".") : `${a.name.replaceAll("_", " ")} (${a.type}).`);
  if (a.enum?.length) parts.push(`One of ${a.enum.map((v) => `\`${v}\``).join(", ")}.`);
  if (a.type === "direction") parts.push("A direction (`down`, `up`, `left`, `right`) or an angle in degrees.");
  if (a.type === "base64") parts.push("URL-safe base64, written as given.");
  if (a.type === "color") parts.push("A hex colour (`ff0000`, `f00`, with optional alpha).");
  const range: string[] = [];
  if (a.min !== undefined) range.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) range.push(`≤ ${a.max}`);
  if (range.length) parts.push(`Range ${range.join(", ")}.`);
  if (a.nullable) parts.push("Null writes an empty argument.");
  return parts.join(" ");
}

// ---- signatures --------------------------------------------------------------

interface Param {
  readonly name: string;
  /** Dart type without `?`. */
  readonly type: string;
  readonly nullable: boolean;
  readonly docs: string[];
}

/** The repeated tail of a signature. */
interface Rest {
  readonly name: string;
  /** The element type: a type, or a named record of fields. */
  readonly elem: string;
  /** Record fields (empty for a single repeated argument). */
  readonly fields: readonly { readonly name: string; readonly type: string }[];
  readonly required: boolean;
  readonly doc: string;
}

/** The one Dart signature of an option: `required` leading positional parameters, the rest optional. */
interface Signature {
  readonly params: Param[];
  readonly required: number;
  readonly rest?: Rest;
}

function plural(name: string): string {
  const id = camel(name);
  const pl = /(s|x|ch|sh)$/.test(id) ? `${id}es` : /[^aeiou]y$/.test(id) ? `${id.slice(0, -1)}ies` : `${id}s`;
  return reserved.has(pl) ? `${pl}_` : pl;
}

function uniqueName(name: string, used: Set<string>): string {
  let n = name;
  for (let i = 2; used.has(n); i++) n = `${name}${i}`;
  used.add(n);
  return n;
}

/** How many leading arguments a form requires. */
function formRequired(f: SpecForm): number {
  const min = Math.max(f.min_items, 1);
  return Math.min(min, f.args.length);
}

/** The type of position i in a form: a fixed argument, a repeated one, or undefined past its end. */
function typeAt(f: SpecForm, i: number): SpecArg | undefined {
  if (i < f.args.length) return f.args[i];
  if (f.rest && f.rest.length > 0) return f.rest[(i - f.args.length) % f.rest.length];
  return undefined;
}

function signature(o: SpecOption): Signature {
  const used = new Set<string>();
  if (o.forms.length === 1) {
    const f = o.forms[0]!;
    const required = formRequired(f);
    const params = f.args.map((a, i) => ({
      name: uniqueName(ident(a.name), used),
      type: baseType(a),
      nullable: a.nullable || i >= required,
      docs: [argDoc(a)],
    }));
    if (!f.rest || f.rest.length === 0) return { params, required };
    const restRequired = Math.max(f.min_items, 1) > f.args.length;
    // A required repeated tail makes every fixed argument required too.
    const req = restRequired ? params.length : required;
    const r = f.rest;
    const restDoc = `Repeated ${r.length === 1 ? "argument" : "groups"}: ${r.map((a) => `\`${a.name}\`: ${argDoc(a)}`).join(" ")}`;
    if (r.length === 1) {
      const a = r[0]!;
      return {
        params,
        required: req,
        rest: { name: uniqueName(plural(a.name), used), elem: baseType(a), fields: [], required: restRequired, doc: restDoc },
      };
    }
    const fieldsUsed = new Set<string>();
    const fields = r.map((a) => ({ name: uniqueName(ident(a.name), fieldsUsed), type: baseType(a) }));
    return {
      params,
      required: req,
      rest: {
        name: uniqueName("groups", used),
        elem: `({${fields.map((x) => `${x.type} ${x.name}`).join(", ")}})`,
        fields,
        required: restRequired,
        doc: restDoc,
      },
    };
  }
  // Several forms: merge them position by position.
  const length = Math.max(...o.forms.map((f) => f.args.length));
  const required = Math.min(...o.forms.map(formRequired));
  const params: Param[] = [];
  for (let i = 0; i < length; i++) {
    const at = o.forms.map((f) => typeAt(f, i)).filter((a): a is SpecArg => a !== undefined);
    const types = new Set(at.map(baseType));
    const fixed = o.forms.map((f) => f.args[i]).filter((a): a is SpecArg => a !== undefined);
    const docs = [...new Set(at.map(argDoc))];
    params.push({
      name: uniqueName(ident(fixed[0]!.name), used),
      type: types.size === 1 ? [...types][0]! : "Object",
      nullable: i >= required || at.some((a) => a.nullable),
      docs,
    });
  }
  const restForms = o.forms.filter((f) => f.rest && f.rest.length > 0);
  if (restForms.length === 0) return { params, required };
  const restDoc = `More arguments of the forms that repeat: ${restForms
    .map((f) => `${f.args.map((a) => a.name).join(", ")}, then (${f.rest!.map((a) => a.name).join(", ")})…`)
    .join("; ")}.`;
  return { params, required, rest: { name: uniqueName("more", used), elem: "Object?", fields: [], required: false, doc: restDoc } };
}

function paramList(s: Signature): string {
  const decl = (p: Param) => `${p.type}${p.nullable ? "?" : ""} ${p.name}`;
  const req = s.params.slice(0, s.required).map(decl);
  const opt = s.params.slice(s.required).map(decl);
  if (s.rest) {
    const t = `List<${s.rest.elem}>`;
    if (s.rest.required) req.push(`${t} ${s.rest.name}`);
    else opt.push(`${t} ${s.rest.name} = const []`);
  }
  return opt.length ? [...req, `[${opt.join(", ")}]`].join(", ") : req.join(", ");
}

/** The expression building the argument list of a signature. */
function argsExpr(s: Signature): string {
  const items = s.params.map((p) => p.name);
  if (s.rest) {
    const r = s.rest;
    if (r.fields.length === 0) items.push(`...${r.name}`);
    else items.push(`for (final g in ${r.name}) ...[${r.fields.map((f) => `g.${f.name}`).join(", ")}]`);
  }
  const list = `[${items.join(", ")}]`;
  return s.params.slice(s.required).length > 0 ? `trimArgs(${list}, ${s.required})` : list;
}

function optionSummary(o: SpecOption): string {
  return o.doc.trim().replace(/\.?$/, ".");
}

function optionDetails(o: SpecOption): string {
  const tags: string[] = [];
  tags.push(`URL names: ${[o.name, ...o.aliases].map((n) => `\`${n}\``).join(", ")}; arguments \`${o.syntax}\`; default ${o.default}.`);
  tags.push(o.milestone ? `Milestone ${o.milestone}; scope ${o.scope}.` : `Scope ${o.scope}.`);
  if (o.pro) tags.push("imgproxy Pro option (free here).");
  if (o.security) tags.push("Security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS).");
  if (o.removed) tags.push("Removed: accepted and ignored.");
  return tags.join(" ");
}

function signatureDocs(o: SpecOption, s: Signature, indent: string): string[] {
  const out = [...doc(indent, optionSummary(o)), `${indent}///`, ...doc(indent, optionDetails(o))];
  const lines: string[] = [];
  for (const p of s.params) lines.push(`- \`${p.name}\`: ${p.docs.join(" Or: ")}`);
  if (s.rest) lines.push(`- \`${s.rest.name}\`: ${s.rest.doc}`);
  if (lines.length) out.push(`${indent}///`, ...doc(indent, lines.join("\n")));
  return out;
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

// ---- catalogue ---------------------------------------------------------------

function mapLiteral(entries: [string, string][], indent: string): string[] {
  return entries.map(([k, v]) => `${indent}${str(k)}: ${str(v)},`);
}

function emitCatalogue(spec: Spec): string {
  const out: string[] = [header("Name tables of the processing, /info and /video option catalogues.")];
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    const names: [string, string][] = [];
    for (const o of opts) {
      names.push([o.name, o.name]);
      for (const a of o.aliases) names.push([a, o.name]);
    }
    names.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    out.push(`/// Every ${kind} option name and alias to its canonical name.`);
    out.push(`const Map<String, String> ${kind}Names = {`, ...mapLiteral(names, "  "), "};", "");
    out.push(`/// Canonical ${kind} option name to the name builders write by default (the shortest).`);
    out.push(`const Map<String, String> ${kind}ShortNames = {`, ...mapLiteral(opts.map((o) => [o.name, o.short]), "  "), "};", "");
  }
  return out.join("\n");
}

// ---- typed option values -----------------------------------------------------

function emitOptions(spec: Spec): string {
  const out: string[] = [header("Typed option values of the processing, /info and /video catalogues.")];
  out.push("import '../args.dart';", "");
  out.push(
    "/// A typed option: its canonical name and its arguments, built by the",
    "/// named constructors of [ProcessingOption], [InfoOption] and [VideoOption].",
    "///",
    "/// The three catalogues are the subclasses, so a `switch` over an",
    "/// [OptionValue] is exhaustive. Add one to a fluent chain with `add`.",
    "sealed class OptionValue {",
    "  const OptionValue._(this.name, this.args);",
    "",
    "  /// The canonical option name.",
    "  final String name;",
    "",
    "  /// The positional arguments: `String`, `int`, `double`, `bool` or null (an empty argument).",
    "  final List<Object?> args;",
    "",
    "  @override",
    "  bool operator ==(Object other) =>",
    "      other is OptionValue && other.runtimeType == runtimeType && other.name == name && argsEqual(other.args, args);",
    "",
    "  @override",
    "  int get hashCode => Object.hash(runtimeType, name, Object.hashAll(args));",
    "",
    "  /// The option as written with canonical names and `:`: `resize:fill:300:400`.",
    "  @override",
    "  String toString() => [name, for (final a in args) describeArg(a)].join(':');",
    "}",
    "",
  );
  for (const kind of ["processing", "info", "video"] as const) {
    const K = `${kindPrefix[kind]}Option`;
    const what = kind === "processing" ? "processing" : `\`/${kind}\``;
    out.push(`/// A typed ${what} option: one named constructor per option of the catalogue.`);
    out.push("///");
    out.push(
      kind === "processing"
        ? "/// `ProcessingOption.resize('fill', 300, 400)`, `ProcessingOption.quality(80)`."
        : kind === "info"
          ? "/// `InfoOption.size(true)`, `InfoOption.blurhash(4, 3)`."
          : "/// `VideoOption.start(12)`, `VideoOption.duration(8)`.",
    );
    out.push(`final class ${K} extends OptionValue {`);
    out.push(`  const ${K}._(super.name, super.args) : super._();`);
    const used = new Set<string>();
    for (const o of spec.options[kind]) {
      const id = ident(o.name);
      if (reservedConstructors.has(id) || used.has(id)) throw new Error(`${kind} option ${o.name} cannot be the constructor ${K}.${id}`);
      used.add(id);
      const s = signature(o);
      out.push("");
      out.push(...signatureDocs(o, s, "  "));
      out.push(`  ${K}.${id}(${paramList(s)}) : this._(${str(o.name)}, ${argsExpr(s)});`);
    }
    out.push("}", "");
  }
  return out.join("\n");
}

// ---- fluent methods ----------------------------------------------------------

function emitMethods(spec: Spec): string {
  const out: string[] = [header("Per-option methods of the fluent URL builders.")];
  out.push("import '../args.dart';", "");
  for (const kind of ["processing", "info", "video"] as const) {
    const K = kindPrefix[kind];
    out.push(
      `/// The ${kind} option methods of a fluent URL builder: one per option name`,
      "/// and alias, each appending that option written with the name as called.",
      "///",
      "/// `T` is the concrete builder, which every method returns.",
      `mixin ${K}Methods<T> {`,
      "  /// Appends one option occurrence by name or alias.",
      "  T option(String name, List<Object?> args);",
    );
    const used = new Map<string, string>();
    for (const o of spec.options[kind]) {
      const s = signature(o);
      for (const n of [o.name, ...o.aliases]) {
        const id = ident(n);
        if (reservedMethods.has(id)) throw new Error(`${kind} option ${n} collides with the builder member ${id}`);
        const prev = used.get(id);
        if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Dart method ${id}`);
        used.set(id, n);
        out.push("");
        out.push(...signatureDocs(o, s, "  "));
        out.push(`  T ${id}(${paramList(s)}) => option(${str(n)}, ${argsExpr(s)});`);
      }
    }
    out.push("}", "");
  }
  return out.join("\n");
}


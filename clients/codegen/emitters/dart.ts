/** The sealed base class of the typed options. */
function optionValueClass(): Node {
  const objectT = opt("Object");
  const get = (o: string, name: string) => N.get(id(o), name);
  const eq = (l: Expr, r: Expr) => N.binary("==", l, r);
  const and = (...xs: Expr[]) => xs.reduce((l, r) => N.binary("&&", l, r));
  return N.type(
    "class",
    "OptionValue",
    [
      N.func("OptionValue._", [self("name"), self("args")], undefined, { mods: ["const"] }),
      N.blank(),
      N.field("name", str, { mods: ["final"], doc: N.doc("The canonical option name.") }),
      N.blank(),
      N.field("args", listOf(objectT), {
        mods: ["final"],
        doc: N.doc("The positional arguments: `String`, `int`, `double`, `bool` or null (an empty argument)."),
      }),
      N.blank(),
      N.func(
        "==",
        [N.param("other", t("Object"))],
        and(
          N.binary("is", id("other"), id("OptionValue")),
          eq(get("other", "runtimeType"), id("runtimeType")),
          eq(get("other", "name"), id("name")),
          N.call(id("argsEqual"), [get("other", "args"), id("args")]),
        ),
        { returns: t("bool"), mods: ["operator", "wrap"], annotations: [override] },
      ),
      N.blank(),
      N.func("hashCode", [], N.invoke(id("Object"), "hash", [id("runtimeType"), id("name"), N.invoke(id("Object"), "hashAll", [id("args")])]), {
        returns: int,
        mods: ["get"],
        annotations: [override],
      }),
      N.blank(),
      N.func(
        "toString",
        [],
        N.invoke(N.list([id("name"), forElement("a", id("args"), N.call(id("describeArg"), [id("a")]))]), "join", [N.str(":")]),
        { returns: str, annotations: [override], doc: N.doc("The option as written with canonical names and `:`: `resize:fill:300:400`.") },
      ),
    ],
    {
      mods: ["sealed"],
      doc: N.doc(
        [
          "A typed option: its canonical name and its arguments, built by the",
          "named constructors of [ProcessingOption], [InfoOption] and [VideoOption].",
          "",
          "The three catalogues are the subclasses, so a `switch` over an",
          "[OptionValue] is exhaustive. Add one to a fluent chain with `add`.",
        ].join("\n"),
      ),
    },
  );
}

const optionExample: Record<CatalogueKind, string> = {
  processing: "`ProcessingOption.resize('fill', 300, 400)`, `ProcessingOption.quality(80)`.",
  info: "`InfoOption.size(true)`, `InfoOption.blurhash(4, 3)`.",
  video: "`VideoOption.start(12)`, `VideoOption.duration(8)`.",
};

function optionClass(c: CatalogueModel): Node {
  const { kind } = c;
  const K = `${kindPrefix[kind]}Option`;
  const what = kind === "processing" ? "processing" : `\`/${kind}\``;
  const superP = (name: string) => N.param(name, undefined, { mods: ["super"] });
  const members: Node[] = [N.func(`${K}._`, [superP("name"), superP("args")], initializers(N.call(N.get(id("super"), "_"))), { mods: ["const"] })];
  const used = new Set<string>();
  for (const o of c.options) {
    const name = ident(o.name);
    if (reservedConstructors.has(name) || used.has(name)) throw new Error(`${kind} option ${o.name} cannot be the constructor ${K}.${name}`);
    used.add(name);
    const s = signature(o.spec);
    members.push(
      N.blank(),
      N.func(`${K}.${name}`, paramNodes(s), initializers(N.call(N.get(id("this"), "_"), [N.str(o.name), argsExpr(s)])), {
        doc: signatureDoc(o.spec, s),
      }),
    );
  }
  return N.type("class", K, members, {
    mods: ["final"],
    supers: [t("OptionValue")],
    doc: N.doc([`A typed ${what} option: one named constructor per option of the catalogue.`, "", optionExample[kind]].join("\n")),
  });
}

function emitOptions(spec: Spec): Node {
  const items: Node[] = [
    ...header("Typed option values of the processing, /info and /video catalogues."),
    N.imp("../args.dart"),
    N.blank(),
    optionValueClass(),
    N.blank(),
  ];
  for (const c of catalogues(spec)) items.push(optionClass(c), N.blank());
  return file(items);
}

// ---- fluent methods ----------------------------------------------------------

function methodsMixin(c: CatalogueModel): Node {
  const { kind } = c;
  const T = t("T");
  const members: Node[] = [
    N.func("option", [N.param("name", str), N.param("args", listOf(opt("Object")))], undefined, {
      returns: T,
      doc: N.doc("Appends one option occurrence by name or alias."),
    }),
  ];
  const used = new Map<string, string>();
  for (const o of c.options) {
    const s = signature(o.spec);
    for (const n of o.names) {
      const name = ident(n);
      if (reservedMethods.has(name)) throw new Error(`${kind} option ${n} collides with the builder member ${name}`);
      const prev = used.get(name);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Dart method ${name}`);
      used.set(name, n);
      members.push(N.blank(), N.func(name, paramNodes(s), N.call(id("option"), [N.str(n), argsExpr(s)]), { returns: T, doc: signatureDoc(o.spec, s) }));
    }
  }
  return N.type("mixin", `${kindPrefix[kind]}Methods`, members, {
    typeParams: [T],
    doc: N.doc(
      [
        `The ${kind} option methods of a fluent URL builder: one per option name`,
        "and alias, each appending that option written with the name as called.",
        "",
        "`T` is the concrete builder, which every method returns.",
      ].join("\n"),
    ),
  });
}

function emitMethods(spec: Spec): Node {
  const items: Node[] = [...header("Per-option methods of the fluent URL builders."), N.imp("../args.dart"), N.blank()];
  for (const c of catalogues(spec)) items.push(methodsMixin(c), N.blank());
  return file(items);
}


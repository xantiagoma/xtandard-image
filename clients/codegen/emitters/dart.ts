const refName = (ref: string) => ref.replace("#/components/schemas/", "");

interface DartType {
  /** The Dart type without `?`. */
  readonly type: string;
  readonly nullable: boolean;
  /** The decoding expression of a JSON value `v` (nullability checked by the caller). */
  decode(v: string, where: string): string;
}

function schemaType(s: JSONSchema): DartType {
  if (s.$ref) {
    const n = refName(s.$ref);
    return { type: n, nullable: false, decode: (v, w) => `${n}.fromJson(jsonObject(${v}, ${w}))` };
  }
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  const nullable = types.includes("null") || (s.enum?.includes(null) ?? false);
  const t = types.filter((x) => x !== "null");
  if (t.length !== 1) return { type: "Object", nullable: true, decode: (v) => v };
  switch (t[0]) {
    case "string":
      return { type: "String", nullable, decode: (v, w) => `jsonString(${v}, ${w})` };
    case "integer":
      return { type: "int", nullable, decode: (v, w) => `jsonInt(${v}, ${w})` };
    case "number":
      return { type: "double", nullable, decode: (v, w) => `jsonDouble(${v}, ${w})` };
    case "boolean":
      return { type: "bool", nullable, decode: (v, w) => `jsonBool(${v}, ${w})` };
    case "array": {
      const it = s.items ? schemaType(s.items) : { type: "Object", nullable: true, decode: (v: string) => v };
      const elem = `${it.type}${it.nullable ? "?" : ""}`;
      const one = (x: string, w: string) => (it.nullable ? `${x} == null ? null : ${it.decode(x, w)}` : it.decode(x, w));
      return {
        type: `List<${elem}>`,
        nullable,
        decode: (v, w) => `List<${elem}>.unmodifiable(jsonList(${v}, ${w}).map((e) => ${one("e", w)}))`,
      };
    }
    case "object": {
      if (s.properties) throw new Error("inline object schemas are not supported");
      const ap = s.additionalProperties;
      const it =
        typeof ap === "object" && (ap.type !== undefined || ap.$ref !== undefined)
          ? schemaType(ap)
          : { type: "Object", nullable: true, decode: (v: string) => v };
      const elem = `${it.type}${it.nullable ? "?" : ""}`;
      const one = (x: string, w: string) => (it.nullable && it.type !== "Object" ? `${x} == null ? null : ${it.decode(x, w)}` : it.decode(x, w));
      return {
        type: `Map<String, ${elem}>`,
        nullable,
        decode: (v, w) => `Map<String, ${elem}>.unmodifiable(jsonObject(${v}, ${w}).map((k, e) => MapEntry(k, ${one("e", w)})))`,
      };
    }
    default:
      return { type: "Object", nullable: true, decode: (v) => v };
  }
}

function emitResponses(spec: Spec): string {
  const out: string[] = [header("The JSON response bodies (the OpenAPI components), with fromJson.")];
  out.push("import '../json.dart';", "");
  const names = Object.keys(spec.response_schemas).sort();
  for (const name of names) {
    const s = spec.response_schemas[name]!;
    const desc = (s.description ?? `The ${name} object of the server's JSON responses.`).split("\n\n")[0]!;
    const req = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {}).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    const fields = props.map(([p, ps]) => {
      const t = schemaType(ps);
      const id = ident(p);
      if (id === "json") throw new Error(`${name}.${p} collides with the json field`);
      const required = req.has(p) && !t.nullable;
      return { p, ps, t, id, required };
    });
    out.push(...doc("", desc));
    out.push(`final class ${name} {`);
    out.push(`  /// Creates a ${name}.`);
    const ctorParams = fields.map((f) => `${f.required ? "required " : ""}this.${f.id}`);
    out.push(`  const ${name}({${[...ctorParams, "this.json = const {}"].join(", ")}});`, "");
    out.push(`  /// Decodes a ${name} from a decoded JSON object; throws [FormatException] on a wrong type.`);
    out.push(`  factory ${name}.fromJson(Map<String, Object?> json) => ${name}(`);
    for (const f of fields) {
      const w = str(`${name}.${f.p}`);
      const v = `json[${str(f.p)}]`;
      out.push(f.required ? `    ${f.id}: ${f.t.decode(v, w)},` : `    ${f.id}: ${v} == null ? null : ${f.t.decode(v, w)},`);
    }
    out.push("    json: json,", "  );", "");
    for (const f of fields) {
      out.push(...doc("  ", f.ps.description ?? `\`${f.p}\`.`));
      out.push(`  final ${f.t.type}${f.required ? "" : "?"} ${f.id};`, "");
    }
    out.push("  /// The decoded JSON object, including fields newer than this client.", "  final Map<String, Object?> json;", "}", "");
  }
  return out.join("\n");
}


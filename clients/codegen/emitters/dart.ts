    "",
    "  /// The format named [value] (or one of its aliases), or null.",
    "  static SegmentFormat? fromValue(String value) {",
    "    for (final f in values) {",
    "      if (f.value == value || f.aliases.contains(value)) return f;",
    "    }",
    "    return null;",
    "  }",
    "}",
    "",

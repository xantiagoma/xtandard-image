const strList = (values: readonly string[]) => N.list(values.map(N.str));

/** One field of an enum: `/// doc` then `final T name;`. */
const enumField = (name: string, type: TypeRef, doc: string) => N.field(name, type, { mods: ["final"], doc: N.doc(doc) });

/**
 * An enum with a value field and a lookup: members (each with its
 * constructor arguments and doc), the constructor, the fields, extra
 * members, then `static E? fromValue(String value)` matching `match`.
 */
function valueEnum(o: {
  name: string;
  doc: string;
  members: { name: string; args: Expr[]; doc: string }[];
  fields: [string, TypeRef, string][];
  extra?: Node[];
  lookupDoc: string;
  loopVar: string;
  match: (v: Expr) => Expr;
}): Node {
  const v = id(o.loopVar);
  const body: Node[] = [N.blank(), N.func(o.name, o.fields.map(([f]) => self(f)), undefined, { mods: ["const"] })];
  for (const [f, type, d] of o.fields) body.push(N.blank(), enumField(f, type, d));
  body.push(N.blank(), ...(o.extra ?? []));
  body.push(
    N.func(
      "fromValue",
      [N.param("value", str)],
      [N.forEach(o.loopVar, id("values"), [N.if(o.match(v), [N.ret(v)])]), N.ret(N.null())],
      { returns: opt(o.name), mods: ["static"], doc: N.doc(o.lookupDoc) },
    ),
  );
  return N.enum(
    o.name,
    o.members.map((m) => N.member(m.name, undefined, { args: m.args, doc: mdDoc(m.doc) })),
    { body, doc: N.doc(o.doc) },
  );
}

const valueIs = (v: Expr) => N.binary("==", N.get(v, "value"), id("value"));


  c("Most renditions in one stream request.", `const int maxRenditions = ${s.max_renditions};`);
  c("Smallest rendition (short side of the frame).", `const int renditionMin = ${s.rendition_min};`);
  c("Largest rendition (short side of the frame).", `const int renditionMax = ${s.rendition_max};`);

// Dart emitter (clients/dart, pub.dev xtandard_image): writes
// lib/src/generated/ from the spec.
//
//   catalogue.g.dart  the name tables (name or alias to canonical,
//                     canonical to short) of the three catalogues
//   options.g.dart    the sealed OptionValue hierarchy: ProcessingOption,
//                     InfoOption and VideoOption, with one named
//                     constructor per option (ProcessingOption.resize(…))
//   methods.g.dart    the fluent builders' per-option methods: one mixin per
//                     catalogue, one method per option name and alias
//   constants.g.dart  formats, containers, the StreamProtocol,
//                     SegmentFormat, SourceEncoding, SourceScheme and
//                     ErrorKind enums, query keys, imaginary, signing,
//                     encryption and URL constants
//   responses.g.dart  the JSON bodies (InfoResponse, ErrorResponse, …) as
//                     immutable classes with hand-rolled fromJson (no
//                     build_runner for consumers)
//
// Argument types: integer → int, number → num, boolean → bool,
// direction → Object (a name or an angle), everything else → String.
// Dart has no overloads, so an option with several argument forms gets one
// signature whose positions are typed where every form agrees (Object
// otherwise), plus a trailing `List<Object?> more` when a form repeats.
// The generated files are not run through `dart format` (the Taskfile
// formats only the hand-written sources) and silence the style lints that
// would fight the generator.


// PHP emitter (clients/php, Packagist xtandard/image, namespace Xtandard\Image):
// writes clients/php/generated/ from the spec. composer.json maps the
// namespace to both src/ (hand-written) and generated/ (this emitter).
//
//   OptionTypes.php      PHPStan/Psalm type aliases: one argument-list type and
//                        one value type per option, the options array shapes
//                        (every name and alias a key), query parameter shapes
//   OptionNames.php      the name tables (name or alias to canonical,
//                        canonical to short)
//   *Methods.php         traits with the fluent builders' per-option methods
//   Constants.php        signing, encryption, URL, stream and query constants
//   <Enum>.php           backed enums: ImageFormat, VideoContainer,
//                        StreamProtocol, SegmentFormat, SourceScheme,
//                        SourceEncoding, ErrorKind
//   ResponseTypes.php    array shapes of the JSON bodies (InfoResponse, ErrorResponse)

import { allArgs, bareArgs, nameTable, pascal, type Shape, shapes, words } from "../lib.ts";
import type { CatalogueKind, Emitter, JSONSchema, Spec, SpecArg, SpecOption } from "../spec.ts";

const dir = "clients/php/generated/";

const header = (what: string) =>
  [
    "<?php",
    "",
    "// Code generated by clients/codegen/emitters/php.ts from clients/spec/spec.json.",
    "// DO NOT EDIT. Run `task clients:generate`.",
    "",
    "declare(strict_types=1);",
    "",
    "namespace Xtandard\\Image;",
    "",
    `// ${what}`,
    "",
  ].join("\n");

/** Builder methods the per-option methods must not shadow (PHP method names are case-insensitive). */
export const reservedMethods = new Set(
  ["option", "options", "pipeline", "extension", "encoding", "withPdfPassword", "build", "param", "__toString"].map((m) =>
    m.toLowerCase(),
  ),
);

/** camelCase of an option name ("min-width" → "minWidth", "crop_ar" → "cropAr"). */
function camel(name: string): string {
  const w = words(name);
  return w.map((x, i) => (i === 0 ? x.toLowerCase() : x[0]!.toUpperCase() + x.slice(1).toLowerCase())).join("");
}

/** A PHP single-quoted string literal. */
const q = (s: string) => `'${s.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;

/** Text safe inside a /** … *\/ block. */
const docText = (s: string) => s.replaceAll("*/", "*\\/");

function docBlock(lines: string[], indent: string): string[] {
  const out = [`${indent}/**`];
  for (const l of lines) for (const x of docText(l).split("\n")) out.push(x === "" ? `${indent} *` : `${indent} * ${x}`);
  out.push(`${indent} */`);
  return out;
}

const uniq = (parts: string[]) => [...new Set(parts)];

/** The PHPDoc type of one argument. */
function argType(a: SpecArg): string {
  let t: string;
  switch (a.type) {
    case "integer":
      t = "int";
      break;
    case "number":
      t = "int|float";
      break;
    case "boolean":
      t = "bool";
      break;
    case "enum":
      t = (a.enum ?? []).map(q).join("|");
      break;
    case "direction":
      t = "'down'|'up'|'left'|'right'|int|float";
      break;
    default:
      t = "string";
  }
  return a.nullable ? `${t}|null` : t;
}

/** The native PHP type of one argument (for the variadic per-option methods). */
function nativeParts(a: SpecArg): string[] {
  switch (a.type) {
    case "integer":
      return ["int"];
    case "number":
      return ["int", "float"];
    case "boolean":
      return ["bool"];
    case "direction":
      return ["string", "int", "float"];
    default:
      return ["string"];
  }
}

const nativeOrder = ["string", "int", "float", "bool"];

function union(parts: string[]): string {
  // Split already-joined unions so duplicates disappear.
  return uniq(parts.flatMap((p) => p.split("|"))).join("|");
}

function shapeType(s: Shape): string {
  if (s.rest) return `non-empty-list<${union([...s.fixed.map(argType), ...s.rest.map(argType)])}>`;
  return `array{${s.fixed.map(argType).join(", ")}}`;
}

const kindPrefix: Record<CatalogueKind, string> = { processing: "Processing", info: "Info", video: "Video" };

const argsAlias = (kind: CatalogueKind, o: SpecOption) => `${kindPrefix[kind]}${pascal(o.name)}Args`;
const valueAlias = (kind: CatalogueKind, o: SpecOption) => `${kindPrefix[kind]}${pascal(o.name)}Value`;

function optionDoc(o: SpecOption): string[] {
  const tags: string[] = [];
  if (o.milestone) tags.push(`milestone ${o.milestone}`);
  tags.push(`scope ${o.scope}`);
  if (o.pro) tags.push("imgproxy Pro option (free here)");
  if (o.security) tags.push("security option (needs XI_SECURITY_ALLOW_SECURITY_OPTIONS)");
  if (o.removed) tags.push("removed: accepted and ignored");
  return [
    o.doc,
    "",
    `URL names: ${[o.name, ...o.aliases].join(", ")}; arguments ${o.syntax}; default ${o.default}.`,
    `${tags.join("; ")}.`,
  ];
}

function emitOptionTypes(spec: Spec): string {
  const out: string[] = [header("Type aliases of the option catalogues and the query parameters.")];
  const doc: string[] = [
    "Type aliases (PHPStan and Psalm) of the processing, /info and /video option catalogues.",
    "",
    "Import them where you build URLs (phpstan-import-type ProcessingOptions from \\Xtandard\\Image\\OptionTypes).",
    "",
    "An options array maps option names or aliases, in URL order, to the argument list",
    "or, when the rest are optional, the first argument alone:",
    "['rs' => ['fill', 300, 400], 'q' => 80]. null inside a list is an empty argument;",
    "a null value skips the option.",
    "",
  ];
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    for (const o of opts) {
      doc.push(`@phpstan-type ${argsAlias(kind, o)} ${uniq(shapes(o).map(shapeType)).join("|")}`);
      const bare = bareArgs(o).map((a) => argType({ ...a, nullable: false }));
      doc.push(`@phpstan-type ${valueAlias(kind, o)} ${argsAlias(kind, o)}${bare.length ? `|${union(bare)}` : ""}`);
    }
    const byName = new Map(opts.map((o) => [o.name, o]));
    const keys = nameTable(opts).map(([n, c]) => `${q(n)}?: ${valueAlias(kind, byName.get(c)!)}|null`);
    doc.push(`@phpstan-type ${kindPrefix[kind]}Options array{${keys.join(", ")}}`);
    doc.push(`@phpstan-type ${kindPrefix[kind]}OptionName ${nameTable(opts).map(([n]) => q(n)).join("|")}`);
  }
  doc.push("@phpstan-type QueryValue string|int|float|bool");
  const imageKeys = spec.query.image_keys.flatMap((k) => [k.name, ...k.aliases]).map((n) => `${q(n)}?: QueryValue|null`);
  doc.push(`@phpstan-type QueryImageParams array{${imageKeys.join(", ")}}`);
  const reservedImaginary = new Set(["url", "sign", "xi_sig"]);
  const imaginary = spec.query.imaginary.params.filter((p) => !reservedImaginary.has(p)).map((p) => `${q(p)}?: QueryValue|null`);
  doc.push(`@phpstan-type ImaginaryParams array{${imaginary.join(", ")}}`);
  doc.push(`@phpstan-type ImaginaryEndpoint ${spec.query.imaginary.endpoints.map(q).join("|")}`);
  out.push(...docBlock(doc, ""));
  out.push("final class OptionTypes");
  out.push("{");
  out.push("    private function __construct()");
  out.push("    {");
  out.push("    }");
  out.push("}");
  out.push("");
  return out.join("\n");
}

function phpArray(entries: [string, string][], indent: string): string[] {
  return [`[`, ...entries.map(([k, v]) => `${indent}    ${q(k)} => ${q(v)},`), `${indent}]`];
}

function emitOptionNames(spec: Spec): string {
  const out: string[] = [header("Name tables of the option catalogues.")];
  out.push(...docBlock(["Option name tables: every name and alias to its canonical name, and canonical names to the name builders write by default."], ""));
  out.push("final class OptionNames");
  out.push("{");
  for (const kind of ["processing", "info", "video"] as const) {
    const K = kind.toUpperCase();
    const names = phpArray(nameTable(spec.options[kind]), "    ");
    out.push(...docBlock([`${kind} option name or alias to canonical name.`, "", "@var array<string, string>"], "    "));
    out.push(`    public const ${K}_NAMES = ${names[0]}`, ...names.slice(1, -1), `${names.at(-1)};`);
    out.push("");
    const short = phpArray(
      spec.options[kind].map((o) => [o.name, o.short]),
      "    ",
    );
    out.push(...docBlock([`Canonical ${kind} option name to the name builders write by default (the shortest).`, "", "@var array<string, string>"], "    "));
    out.push(`    public const ${K}_SHORT = ${short[0]}`, ...short.slice(1, -1), `${short.at(-1)};`);
    out.push("");
  }
  out.push("    private function __construct()");
  out.push("    {");
  out.push("    }");
  out.push("}");
  out.push("");
  return out.join("\n");
}

function emitMethods(spec: Spec, kind: CatalogueKind): string {
  const K = kindPrefix[kind];
  const out: string[] = [header(`Per-option methods of the fluent ${kind} URL builders.`)];
  out.push(
    ...docBlock(
      [
        `One method per ${kind} option name and alias; each appends that option, written with the name as called.`,
        "Names that differ only in punctuation (min-width, min_width) share one method.",
        "",
        "@internal used by the fluent URL chains",
      ],
      "",
    ),
  );
  out.push(`trait ${K}Methods`);
  out.push("{");
  out.push(...docBlock(["Appends one option occurrence."], "    "));
  out.push("    abstract public function option(string $name, string|int|float|bool|null ...$args): static;");
  const used = new Map<string, { name: string; canonical: string }>();
  for (const o of spec.options[kind]) {
    const args = allArgs(o);
    const doc = union(args.map(argType)) || "string|int|float|bool|null";
    const native = nativeOrder.filter((t) => args.some((a) => nativeParts(a).includes(t)));
    const nullable = args.some((a) => a.nullable);
    const nativeType = [...native, ...(nullable ? ["null"] : [])].join("|");
    for (const n of [o.name, ...o.aliases]) {
      const id = camel(n);
      if (!/^[a-z][A-Za-z0-9]*$/.test(id)) throw new Error(`${kind} option ${n} is not a PHP method name (${id})`);
      const key = id.toLowerCase();
      if (reservedMethods.has(key)) throw new Error(`${kind} option ${n} collides with the builder method ${id}`);
      const prev = used.get(key);
      if (prev !== undefined) {
        if (prev.canonical === o.name) continue;
        throw new Error(`${kind} option names ${prev.name} and ${n} are both the PHP method ${id}`);
      }
      used.set(key, { name: n, canonical: o.name });
      out.push("");
      out.push(...docBlock([...optionDoc(o), "", `@param ${doc} ...$args`], "    "));
      out.push(`    public function ${id}(${nativeType} ...$args): static`);
      out.push("    {");
      out.push(`        return $this->option(${q(n)}, ...$args);`);
      out.push("    }");
    }
  }
  out.push("}");
  out.push("");
  return out.join("\n");
}

/** An enum case name for a value ("fill-down" → "FillDown", "h265" → "H265"). */
function caseName(v: string): string {
  const c = pascal(v);
  return /^[0-9]/.test(c) ? `V${c}` : c;
}

function emitEnum(name: string, values: readonly string[], doc: string[], extra: string[] = []): string {
  const out: string[] = [header(doc[0]!)];
  out.push(...docBlock(doc, ""));
  out.push(`enum ${name}: string`);
  out.push("{");
  const seen = new Set<string>();
  for (const v of values) {
    const c = caseName(v);
    if (seen.has(c.toLowerCase())) throw new Error(`enum ${name}: two cases named ${c}`);
    seen.add(c.toLowerCase());
    out.push(`    case ${c} = ${q(v)};`);
  }
  if (extra.length) out.push("", ...extra);
  out.push("}");
  out.push("");
  return out.join("\n");
}

function constList(values: readonly (string | number)[]): string {
  return `[${values.map((v) => (typeof v === "string" ? q(v) : String(v))).join(", ")}]`;
}

function emitConstants(spec: Spec): string {
  const s = spec.media.streams;
  const sg = spec.signing;
  const en = spec.encryption;
  const u = spec.url;
  const out: string[] = [header("Constants of the client specification.")];
  out.push(...docBlock(["Constants of the client specification: signing, encryption, URL rules, streams, query keys."], ""));
  out.push("final class Constants");
  out.push("{");
  // PHP 8.2 has no typed class constants: the type goes in @var.
  const c = (doc: string, type: string, name: string, value: string) => {
    const t = type === "array" ? (value.startsWith("['") ? "list<string>" : "list<int>") : type;
    out.push(...docBlock([doc, "", `@var ${t}`], "    "));
    out.push(`    public const ${name} = ${value};`);
  };
  c("Version of clients/spec/spec.json this client was generated from.", "int", "SPEC_VERSION", String(spec.spec_version));
  c("Output formats of the processing `format` option.", "array", "IMAGE_FORMATS", constList(spec.media.image_formats));
  c("Output containers of /video URLs.", "array", "VIDEO_CONTAINERS", constList(spec.media.video_containers));
  out.push(...docBlock(["Stream protocol to its manifest container and media type.", "", "@var array<string, array{string, string}>"], "    "));
  out.push("    public const STREAM_MANIFESTS = [");
  for (const p of s.protocols) out.push(`        ${q(p.name)} => [${q(p.container)}, ${q(p.content_type)}],`);
  out.push("    ];");
  out.push(...docBlock(["Segment format (and alias) to the protocols that accept it.", "", "@var array<string, list<string>>"], "    "));
  out.push("    public const SEGMENT_FORMAT_PROTOCOLS = [");
  for (const f of s.segment_formats) out.push(`        ${q(f.name)} => ${constList(f.protocols)},`);
  out.push("    ];");
  c("The segment format the server uses when none is given.", "string", "DEFAULT_SEGMENT_FORMAT", q(s.segment_formats.find((f) => f.default)!.name));
  c("Most renditions of one stream.", "int", "MAX_RENDITIONS", String(s.max_renditions));
  c("Smallest rendition (short side, pixels).", "int", "RENDITION_MIN", String(s.rendition_min));
  c("Largest rendition (short side, pixels).", "int", "RENDITION_MAX", String(s.rendition_max));
  c("Shortest segment duration (seconds).", "int", "SEGMENT_DURATION_MIN", String(s.segment_duration_min));
  c("Longest segment duration (seconds).", "int", "SEGMENT_DURATION_MAX", String(s.segment_duration_max));
  c("Pattern of an xi:// source name.", "string", "XI_NAME_PATTERN", q(spec.sources.xi_name_pattern));
  c("Mount prefix of the query dialect.", "string", "QUERY_MOUNT", q(spec.query.mount));
  out.push(...docBlock(["/q/video keys written under a native name.", "", "@var array<string, string>"], "    "));
  out.push("    public const NATIVE_VIDEO_KEYS = [");
  for (const [k, v] of Object.entries(spec.query.native_video_keys).sort()) out.push(`        ${q(k)} => ${q(v)},`);
  out.push("    ];");
  c("Smallest signature size in bytes.", "int", "MIN_SIGNATURE_SIZE", String(sg.min_size));
  c("Largest signature size in bytes.", "int", "MAX_SIGNATURE_SIZE", String(sg.max_size));
  c("Default signature size in bytes.", "int", "DEFAULT_SIGNATURE_SIZE", String(sg.default_size));
  c("Signature segments of unsigned URLs.", "array", "UNSIGNED_PLACEHOLDERS", constList(sg.unsigned_placeholders));
  c("Default signature segment of unsigned URLs.", "string", "DEFAULT_UNSIGNED", q(sg.default_unsigned));
  c("Query parameter of the xi_sig signature.", "string", "XI_SIG_PARAM", q(sg.query_param));
  c("AES key sizes in bytes.", "array", "ENCRYPTION_KEY_SIZES", constList(en.key_sizes));
  c("AES-CBC IV size in bytes.", "int", "IV_SIZE", String(en.iv_size));
  c("Source segment prefix of encrypted sources.", "string", "ENCRYPTED_SOURCE_PREFIX", q(en.source_prefix));
  c("Longest PDF password in UTF-8 bytes.", "int", "MAX_PDF_PASSWORD_BYTES", String(en.max_pdf_password_bytes));
  c("Canonical name of the PDF password option.", "string", "PDF_PASSWORD_NAME", q(en.pdf_password_names[0]!));
  c("Short name of the PDF password option.", "string", "PDF_PASSWORD_SHORT", q(en.pdf_password_short_name));
  c("Default argument separator.", "string", "DEFAULT_SEPARATOR", q(u.default_separator));
  c("Separators the imgproxy grammar refuses.", "array", "FORBIDDEN_SEPARATORS", constList(u.forbidden_separators));
  c("Separators the query dialect refuses.", "array", "FORBIDDEN_QUERY_SEPARATORS", constList(u.forbidden_query_separators));
  c("Separator segment between chained pipelines.", "string", "PIPELINE_SEPARATOR", q(u.pipeline_separator));
  c("Characters a plain source keeps verbatim besides ASCII letters and digits.", "string", "PLAIN_SAFE", q(u.plain_safe));
  c("Characters a query key or value keeps verbatim besides ASCII letters and digits.", "string", "QUERY_SAFE", q(u.query_safe));
  c("Pattern of an output extension.", "string", "EXTENSION_PATTERN", q(u.extension_pattern));
  out.push(...docBlock(["HTTP status of each error kind.", "", "@var array<string, int>"], "    "));
  out.push("    public const ERROR_STATUS = [");
  for (const e of spec.error_kinds) out.push(`        ${q(e.kind)} => ${e.status},`);
  out.push("    ];");
  out.push("");
  out.push("    private function __construct()");
  out.push("    {");
  out.push("    }");
  out.push("}");
  out.push("");
  return out.join("\n");
}

function schemaType(s: JSONSchema): string {
  if (s.$ref) return s.$ref.replace("#/components/schemas/", "");
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  if (s.enum) {
    const vals = s.enum.filter((v) => v !== null).map((v) => (typeof v === "string" ? q(v) : JSON.stringify(v)));
    return [...vals, ...(s.enum.includes(null) || types.includes("null") ? ["null"] : [])].join("|");
  }
  const parts: string[] = [];
  for (const t of types) {
    switch (t) {
      case "string":
        parts.push("string");
        break;
      case "integer":
        parts.push("int");
        break;
      case "number":
        parts.push("int|float");
        break;
      case "boolean":
        parts.push("bool");
        break;
      case "null":
        parts.push("null");
        break;
      case "array":
        parts.push(`list<${s.items ? schemaType(s.items) : "mixed"}>`);
        break;
      case "object":
        if (s.properties) throw new Error("inline object schemas are not supported");
        parts.push(`array<string, ${typeof s.additionalProperties === "object" ? schemaType(s.additionalProperties) : "mixed"}>`);
        break;
      default:
        parts.push("mixed");
    }
  }
  if (parts.length === 0) return "mixed";
  return union([...parts.filter((p) => p !== "null"), ...parts.filter((p) => p === "null")]);
}

function emitResponseTypes(spec: Spec): string {
  const out: string[] = [header("Array shapes of the JSON response bodies.")];
  const doc: string[] = [
    "Array shapes (PHPStan and Psalm) of the JSON response bodies, from the OpenAPI components.",
    "Client::info() returns an InfoResponse; HttpException::$body is an ErrorResponse",
    "(phpstan-import-type InfoResponse from \\Xtandard\\Image\\ResponseTypes).",
    "",
  ];
  for (const name of Object.keys(spec.response_schemas).sort()) {
    const s = spec.response_schemas[name]!;
    const req = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {})
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([p, ps]) => `${q(p)}${req.has(p) ? "" : "?"}: ${schemaType(ps)}`);
    doc.push(`@phpstan-type ${name} array{${props.join(", ")}}`);
  }
  out.push(...docBlock(doc, ""));
  out.push("final class ResponseTypes");
  out.push("{");
  out.push("    private function __construct()");
  out.push("    {");
  out.push("    }");
  out.push("}");
  out.push("");
  return out.join("\n");
}

export const emitter: Emitter = {
  language: "php",
  emit(spec) {
    const s = spec.media.streams;
    const segAliases: string[] = [];
    for (const f of s.segment_formats) for (const a of f.aliases) segAliases.push(a);
    return {
      [`${dir}OptionTypes.php`]: emitOptionTypes(spec),
      [`${dir}OptionNames.php`]: emitOptionNames(spec),
      [`${dir}ProcessingMethods.php`]: emitMethods(spec, "processing"),
      [`${dir}InfoMethods.php`]: emitMethods(spec, "info"),
      [`${dir}VideoMethods.php`]: emitMethods(spec, "video"),
      [`${dir}Constants.php`]: emitConstants(spec),
      [`${dir}ResponseTypes.php`]: emitResponseTypes(spec),
      [`${dir}ImageFormat.php`]: emitEnum("ImageFormat", spec.media.image_formats, ["Output formats of the processing format option (the URL extension)."]),
      [`${dir}VideoContainer.php`]: emitEnum("VideoContainer", spec.media.video_containers, ["Output containers of /video URLs (the URL extension)."]),
      [`${dir}StreamProtocol.php`]: emitEnum("StreamProtocol", s.protocols.map((p) => p.name), [
        "Adaptive streaming protocols: HLS or DASH.",
      ], [
        "    /** The manifest container, also the URL extension (m3u8, mpd). */",
        "    public function container(): string",
        "    {",
        "        return Constants::STREAM_MANIFESTS[$this->value][0];",
        "    }",
        "",
        "    /** The manifest's media type. */",
        "    public function contentType(): string",
        "    {",
        "        return Constants::STREAM_MANIFESTS[$this->value][1];",
        "    }",
      ]),
      [`${dir}SegmentFormat.php`]: emitEnum("SegmentFormat", s.segment_formats.map((f) => f.name), [
        `Stream segment containers: fmp4 (CMAF) or ts (MPEG-TS, HLS only). The server also accepts ${segAliases.join(", ")}.`,
      ]),
      [`${dir}SourceScheme.php`]: emitEnum("SourceScheme", spec.sources.schemes.map((x) => x.scheme), ["Source schemes the server resolves."]),
      [`${dir}SourceEncoding.php`]: emitEnum("SourceEncoding", spec.sources.encodings, ["How a source is written in an imgproxy URL."]),
      [`${dir}ErrorKind.php`]: emitEnum("ErrorKind", spec.error_kinds.map((e) => e.kind), [
        "Error kinds of the server's JSON error envelope.",
      ], [
        "    /** The HTTP status the server answers with. */",
        "    public function status(): int",
        "    {",
        "        return Constants::ERROR_STATUS[$this->value];",
        "    }",
      ]),
    };
  },
};

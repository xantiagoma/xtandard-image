const header = (what: string) =>
  [
    `//! ${what}`,
    "//!",
    "//! Code generated by clients/codegen/emitters/rust.ts from clients/spec/spec.json.",
    "//! DO NOT EDIT. Run `task clients:generate`.",
    "",
  ].join("\n");

/** Strict and reserved keywords of Rust 2024. */
const keywords = new Set(
  (
    "as async await break const continue crate dyn else enum extern false fn for gen if impl in let loop match mod " +
    "move mut pub ref return self Self static struct super trait true type unsafe use where while abstract become box " +
    "do final macro override priv try typeof unsized virtual yield"
  ).split(" "),
);

/** Chain methods the per-option methods must not shadow. */
export const reservedMethods = new Set([
  "option",
  "options",
  "pipeline",
  "extension",
  "encoding",
  "with_pdf_password",
  "build",
  "param",
  "new",
]);

/** A Rust method identifier for an option name or alias. */
function ident(name: string): string {
  let id = name.replace(/[^A-Za-z0-9_]/g, "_").toLowerCase();
  if (/^[0-9]/.test(id)) id = `_${id}`;
  return keywords.has(id) ? `${id}_` : id;
}

/** A Rust enum variant for a value ("fill-down" → FillDown, "h265" → H265). */
function variant(value: string): string {
  const v = pascal(value);
  if (v === "") throw new Error(`enum value ${JSON.stringify(value)} has no identifier characters`);
  return /^[0-9]/.test(v) ? `V${v}` : v;
}

const str = (s: string) => JSON.stringify(s);

/** Escapes Markdown that rustdoc would read as links or HTML, outside code spans. */
function md(text: string): string {
  return text
    .split("`")
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/([[\]<>])/g, "\\$1")))
    .join("`");
}

/** Inline code of spec text, or the escaped text when it has backticks itself. */
function code(text: string): string {
  return text.includes("`") ? md(text) : `\`${text}\``;
}

/** `///` (or `//!`) lines of a doc text (Markdown; escape spec text with md()); leading indentation is dropped so nothing becomes a doc test. */
function doc(text: string, indent: string, marker = "///"): string[] {
  return text
    .trim()
    .split("\n")
    .map((l) => l.trim())
    .map((l) => (l === "" ? `${indent}${marker}` : `${indent}${marker} ${l}`));
}

function sortedBy<T>(xs: readonly T[], key: (x: T) => string): T[] {
  return [...xs].sort((a, b) => {
    const ka = key(a);
    const kb = key(b);
    return ka < kb ? -1 : ka > kb ? 1 : 0;
  });
}

/** A str_enum! invocation (the runtime macro: enum, ALL, as_str, Display, FromStr, AsRef, Arg conversions). */
function strEnum(
  name: string,
  errorVariant: string,
  docText: string,
  values: readonly { value: string; aliases?: readonly string[]; doc?: string }[],
  indent = "",
): string[] {
  const out: string[] = [];
  out.push(`${indent}crate::str_enum! {`);
  out.push(...doc(docText, `${indent}    `));
  out.push(`${indent}    pub enum ${name} (${errorVariant}) {`);
  const seen = new Set<string>();
  for (const v of values) {
    const id = variant(v.value);
    if (seen.has(id)) throw new Error(`${name}: two values are the variant ${id}`);
    seen.add(id);
    out.push(...doc(v.doc ?? `\`${v.value}\`.`, `${indent}        `));
    out.push(`${indent}        ${id} = ${[v.value, ...(v.aliases ?? [])].map(str).join(" | ")},`);
  }
  out.push(`${indent}    }`);
  out.push(`${indent}}`);
  return out;
}

const kindDoc: Record<CatalogueKind, string> = {
  processing: "Processing options (imgproxy dialect `/{signature}/{options}/{source}`, query dialect `o=`)",
  info: "`/info` options",
  video: "`/video` options (also the keys of `/q/video`)",
};
const catalogueKind: Record<CatalogueKind, string> = { processing: "imgproxy", info: "info", video: "video" };

/** The enum type name of an enum argument of an option. */
function argEnumName(o: SpecOption, a: SpecArg): string {
  return `${pascal(o.name)}${pascal(a.name)}`;
}

/** One enum per (option, enum argument name), the values of every form merged in order. */
function argEnums(opts: readonly SpecOption[]): Map<string, { option: SpecOption; arg: SpecArg; values: string[] }> {
  const out = new Map<string, { option: SpecOption; arg: SpecArg; values: string[] }>();
  for (const o of opts) {
    for (const a of allArgs(o)) {
      if (a.type !== "enum") continue;
      const name = argEnumName(o, a);
      const prev = out.get(name);
      if (prev && prev.option !== o) throw new Error(`argument enums of ${prev.option.name} and ${o.name} are both ${name}`);
      const entry = prev ?? { option: o, arg: a, values: [] };
      for (const v of a.enum ?? []) if (!entry.values.includes(v)) entry.values.push(v);
      out.set(name, entry);
    }
  }
  return out;
}

/** How one argument reads in the docs. */
function argDoc(kind: CatalogueKind, o: SpecOption, a: SpecArg): string {
  const parts: string[] = [];
  switch (a.type) {
    case "enum":
      parts.push(`[\`${argEnumName(o, a)}\`](crate::${kind}::${argEnumName(o, a)}) (${(a.enum ?? []).map((v) => `\`${v}\``).join(", ")})`);
      break;
    case "direction":
      parts.push("`down`, `up`, `left`, `right` or a number");
      break;
    default:
      parts.push(a.type);
  }
  if (a.min !== undefined) parts.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) parts.push(`≤ ${a.max}`);
  if (a.multiple_of !== undefined) parts.push(`multiple of ${a.multiple_of}`);
  if (a.pattern !== undefined) parts.push(`pattern \`${a.pattern}\``);
  if (a.nullable) parts.push("may be empty (`None`)");
  return `\`${a.name}\`: ${parts.join(", ")}${a.doc ? `. ${md(a.doc)}` : ""}`;
}

function shapeDoc(s: Shape): string {
  const names = s.fixed.map((a) => a.name);
  if (s.rest) names.push(`${s.rest.map((a) => a.name).join(", ")}…`);
  return `\`(${names.join(", ")})\``;
}

function optionDoc(kind: CatalogueKind, o: SpecOption): string {
  const lines = [md(o.doc), ""];
  lines.push(`URL names: ${[o.name, ...o.aliases].map((n) => `\`${n}\``).join(", ")}; arguments ${code(o.syntax)}; default ${code(o.default)}.`);
  const tags: string[] = [];
  if (o.milestone) tags.push(`milestone ${md(o.milestone)}`);
  tags.push(`scope ${o.scope}`);
  if (o.pro) tags.push("imgproxy Pro option (free here)");
  if (o.security) tags.push("security option (needs `XI_SECURITY_ALLOW_SECURITY_OPTIONS`)");
  if (o.removed) tags.push("removed: accepted and ignored");
  lines.push(`${tags.join("; ")}.`);
  lines.push("");
  lines.push(`Argument shapes: ${shapes(o).map(shapeDoc).join(", ")}; a single argument may be passed bare.`);
  lines.push("");
  const seen = new Set<string>();
  for (const a of allArgs(o)) {
    const d = argDoc(kind, o, a);
    if (seen.has(d)) continue;
    seen.add(d);
    lines.push(`- ${d}`);
  }
  return lines.join("\n");
}

function emitOptions(spec: Spec): string {
  const out: string[] = [header("Typed option tables of the processing, `/info` and `/video` catalogues.")];
  for (const kind of ["processing", "info", "video"] as const) {
    const opts = spec.options[kind];
    out.push("");
    out.push(`pub mod ${kind} {`);
    out.push(...doc(`${kindDoc[kind]}: names, aliases, short names and argument enums.`, "    ", "//!"));
    out.push("");
    out.push("    use crate::options::Catalogue;");
    out.push("");
    // OptionName
    out.push("    crate::option_names! {");
    out.push(...doc(`A ${kind} option, by canonical name. \`FromStr\` also accepts every alias.`, "        "));
    out.push("        pub enum OptionName {");
    const seenVariants = new Set<string>();
    for (const o of opts) {
      const v = variant(o.name);
      if (seenVariants.has(v)) throw new Error(`${kind}: options ${o.name} and another are both the variant ${v}`);
      seenVariants.add(v);
      out.push(...doc(md(o.doc), "            "));
      out.push(`            ${v} = ${str(o.name)}, short ${str(o.short)}, aliases [${o.aliases.map(str).join(", ")}],`);
    }
    out.push("        }");
    out.push("    }");
    out.push("");
    const names = nameTable(opts);
    out.push(...doc(`Every ${kind} option name and alias to its canonical name, sorted by name.`, "    "));
    out.push("    pub const NAMES: &[(&str, &str)] = &[");
    for (const [n, c] of names) out.push(`        (${str(n)}, ${str(c)}),`);
    out.push("    ];");
    out.push("");
    out.push(...doc(`Canonical ${kind} option name to the name builders write by default, sorted by canonical name.`, "    "));
    out.push("    pub const SHORT: &[(&str, &str)] = &[");
    for (const o of sortedBy(opts, (x) => x.name)) out.push(`        (${str(o.name)}, ${str(o.short)}),`);
    out.push("    ];");
    out.push("");
    out.push(`    pub(crate) const CATALOGUE: Catalogue = Catalogue { kind: ${str(catalogueKind[kind])}, names: NAMES, short: SHORT };`);
    for (const [name, e] of argEnums(opts)) {
      out.push("");
      out.push(
        ...strEnum(
          name,
          "InvalidArgument",
          `Values of argument \`${e.arg.name}\` of ${kind} option \`${e.option.name}\`${e.arg.doc ? `: ${md(e.arg.doc)}` : ""}.`,
          e.values.map((value) => ({ value })),
          "    ",
        ),
      );
    }
    out.push("}");
  }
  out.push("");
  return out.join("\n");
}

function methodsMacro(spec: Spec, kind: CatalogueKind): string[] {
  const out: string[] = [];
  out.push(`/// One method per ${kind} option name and alias; each appends that option, written with the name as called.`);
  out.push("#[doc(hidden)]");
  out.push(`macro_rules! ${kind}_methods {`);
  out.push("    () => {");
  const used = new Map<string, string>();
  for (const o of spec.options[kind]) {
    const full = doc(optionDoc(kind, o), "        ");
    for (const n of [o.name, ...o.aliases]) {
      const id = ident(n);
      if (reservedMethods.has(id)) throw new Error(`${kind} option ${n} collides with the builder method ${id}`);
      const prev = used.get(id);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Rust method ${id}`);
      used.set(id, n);
      if (n === o.name) out.push(...full);
      else out.push(`        /// \`${n}\`: alias of [\`${ident(o.name)}\`](Self::${ident(o.name)}), written as \`${n}\` with the \`given\` name style.`);
      out.push(`        pub fn ${id}(self, args: impl $crate::IntoArgs) -> Self {`);
      out.push(`            self.option(${str(n)}, args)`);
      out.push("        }");
      out.push("");
    }
  }
  if (out.at(-1) === "") out.pop();
  out.push("    };");
  out.push("}");
  out.push(`pub(crate) use ${kind}_methods;`);
  return out;
}

function emitMethods(spec: Spec): string {
  const out: string[] = [header("Per-option methods of the fluent URL builders, as macros the chain types expand.")];
  for (const kind of ["processing", "info", "video"] as const) {
    out.push("");
    out.push(...methodsMacro(spec, kind));
  }
  out.push("");
  return out.join("\n");
}

function rustStr(xs: readonly string[]): string {
  return `&[${xs.map(str).join(", ")}]`;
}


// ---- names, types and values ----------------------------------------------------------

const t = (name: string, ...args: TypeRef[]) => N.tref(name, args);
const id = N.id;
const pub = ["pub"];
const strRef = R.ref(t("str"));
const staticStr = R.ref(t("str"), "static");
/** &[T]. */
const sliceOf = (x: TypeRef) => R.ref(R.slice(x));
/** &[a, b, …]. */
const slice = (items: readonly Expr[], layout: "auto" | "expanded" = "auto") => N.unary("&", N.list(items, { layout }));
const strs = (xs: readonly string[]) => slice(xs.map(N.str));
/** Self::Variant (or Type::Variant). */
const path = (type: string, name: string) => N.get(id(type), name, { mods: ["static"] });

/** A doc comment (Markdown; escape spec text with md()). */
const doc = (text: string): Comment => N.doc(text);
const header = (what: string): Comment =>
  N.doc([what, "", "Code generated by clients/codegen/emitters/rust.ts from clients/spec/spec.json.", "DO NOT EDIT. Run `task clients:generate`."].join("\n"), {
    mods: ["inner"],
  });
const attr = (name: string, ...args: Expr[]): Annotation => N.annotation(name, args);
const derive = (...traits: string[]) => attr("derive", ...traits.map(id));

/** A str_enum! invocation (the runtime macro: enum, ALL, as_str, Display, FromStr, AsRef, Arg conversions). */
function strEnum(name: string, errorVariant: string, docText: string, values: readonly { value: string; aliases?: readonly string[]; doc?: string }[]): Node {
  const seen = new Set<string>();
  const members = values.map((v) => {
    const vid = variant(v.value);
    if (seen.has(vid)) throw new Error(`${name}: two values are the variant ${vid}`);
    seen.add(vid);
    return N.member(vid, R.alternatives([v.value, ...(v.aliases ?? [])].map(N.str)), { doc: doc(v.doc ?? `\`${v.value}\`.`) });
  });
  return R.strEnum(N.enum(name, members, { mods: pub, doc: doc(docText) }), errorVariant);
}

/** A `pub const fn name(self) -> T { match self { Self::V => value, … } }`. */
function matchFn(name: string, returns: TypeRef, docText: string, arms: readonly (readonly [string, Expr])[], qualifiers = ["pub", "const"]): Node {
  return N.func(
    name,
    [N.param("self")],
    [N.switch(id("self"), arms.map(([v, value]) => N.case([path("Self", v)], [N.stmt(value)])))],
    { mods: qualifiers, returns, doc: doc(docText) },
  );
}

const kindDoc: Record<CatalogueKind, string> = {
  processing: "Processing options (imgproxy dialect `/{signature}/{options}/{source}`, query dialect `o=`)",
  info: "`/info` options",
  video: "`/video` options (also the keys of `/q/video`)",
};
const catalogueKind: Record<CatalogueKind, string> = { processing: "imgproxy", info: "info", video: "video" };

/** The enum type name of an enum argument of an option. */
const argEnumName = (o: OptionModel, a: SpecArg) => `${pascal(o.name)}${pascal(a.name)}`;

/** One enum per (option, enum argument name), the values of every form merged in order. */
function argEnums(opts: readonly OptionModel[]): Map<string, { option: OptionModel; arg: SpecArg; values: string[] }> {
  const out = new Map<string, { option: OptionModel; arg: SpecArg; values: string[] }>();
  for (const o of opts) {
    for (const a of o.args) {
      if (a.type !== "enum") continue;
      const name = argEnumName(o, a);
      const prev = out.get(name);
      if (prev && prev.option !== o) throw new Error(`argument enums of ${prev.option.name} and ${o.name} are both ${name}`);
      const entry = prev ?? { option: o, arg: a, values: [] };
      for (const v of a.enum ?? []) if (!entry.values.includes(v)) entry.values.push(v);
      out.set(name, entry);
    }
  }
  return out;
}

// ---- documentation prose ---------------------------------------------------------------

/** How one argument reads in the docs. */
function argDoc(o: OptionModel, a: SpecArg): string {
  const parts: string[] = [];
  switch (a.type) {
    case "enum":
      parts.push(`[\`${argEnumName(o, a)}\`](crate::${o.kind}::${argEnumName(o, a)}) (${(a.enum ?? []).map((v) => `\`${v}\``).join(", ")})`);
      break;
    case "direction":
      parts.push("`down`, `up`, `left`, `right` or a number");
      break;
    default:
      parts.push(a.type);
  }
  if (a.min !== undefined) parts.push(`${a.exclusive_min ? ">" : "≥"} ${a.min}`);
  if (a.max !== undefined) parts.push(`≤ ${a.max}`);
  if (a.multiple_of !== undefined) parts.push(`multiple of ${a.multiple_of}`);
  if (a.pattern !== undefined) parts.push(`pattern \`${a.pattern}\``);
  if (a.nullable) parts.push("may be empty (`None`)");
  return `\`${a.name}\`: ${parts.join(", ")}${a.doc ? `. ${md(a.doc)}` : ""}`;
}

function shapeDoc(s: Shape): string {
  const names = s.fixed.map((a) => a.name);
  if (s.rest) names.push(`${s.rest.map((a) => a.name).join(", ")}…`);
  return `\`(${names.join(", ")})\``;
}

function optionDoc(o: OptionModel): string {
  const lines = [md(o.spec.doc), ""];
  lines.push(`URL names: ${o.names.map((n) => `\`${n}\``).join(", ")}; arguments ${code(o.spec.syntax)}; default ${code(o.spec.default)}.`);
  // The flags as the other clients write them, with Markdown escaped and the variable as code.
  const tags: string[] = [];
  if (o.spec.milestone) tags.push(`milestone ${md(o.spec.milestone)}`);
  tags.push(`scope ${o.spec.scope}`);
  if (o.spec.pro) tags.push("imgproxy Pro option (free here)");
  if (o.spec.security) tags.push("security option (needs `XI_SECURITY_ALLOW_SECURITY_OPTIONS`)");
  if (o.spec.removed) tags.push("removed: accepted and ignored");
  lines.push(`${tags.join("; ")}.`);
  lines.push("");
  lines.push(`Argument shapes: ${o.shapes.map(shapeDoc).join(", ")}; a single argument may be passed bare.`);
  lines.push("");
  const seen = new Set<string>();
  for (const a of o.args) {
    const d = argDoc(o, a);
    if (seen.has(d)) continue;
    seen.add(d);
    lines.push(`- ${d}`);
  }
  return lines.join("\n");
}

// ---- options.rs ------------------------------------------------------------------------

function catalogueModule(c: CatalogueModel): Node {
  const { kind } = c;
  const seenVariants = new Set<string>();
  const members = c.options.map((o) => {
    const v = variant(o.name);
    if (seenVariants.has(v)) throw new Error(`${kind}: options ${o.name} and another are both the variant ${v}`);
    seenVariants.add(v);
    return N.member(v, N.str(o.name), { args: [N.str(o.short), N.list(o.aliases.map(N.str))], doc: doc(md(o.spec.doc)) });
  });
  const pair = sliceOf(N.ttuple([strRef, strRef]));
  const items: Node[] = [
    N.blank(),
    N.imp("crate::options::Catalogue"),
    N.blank(),
    R.optionNames(N.enum("OptionName", members, { mods: pub, doc: doc(`A ${kind} option, by canonical name. \`FromStr\` also accepts every alias.`) })),
    N.blank(),
    N.const(
      "NAMES",
      slice(c.names.map(([n, canonical]) => N.tuple([N.str(n), N.str(canonical)])), "expanded"),
      { type: pair, mods: pub, doc: doc(`Every ${kind} option name and alias to its canonical name, sorted by name.`) },
    ),
    N.blank(),
    N.const(
      "SHORT",
      slice([...c.options].sort((a, b) => byCode(a.name, b.name)).map((o) => N.tuple([N.str(o.name), N.str(o.short)])), "expanded"),
      { type: pair, mods: pub, doc: doc(`Canonical ${kind} option name to the name builders write by default, sorted by canonical name.`) },
    ),
    N.blank(),
    N.const(
      "CATALOGUE",
      N.new(t("Catalogue"), [N.named("kind", N.str(catalogueKind[kind])), N.named("names", id("NAMES")), N.named("short", id("SHORT"))]),
      { type: t("Catalogue"), mods: ["pub(crate)"] },
    ),
  ];
  for (const [name, e] of argEnums(c.options)) {
    items.push(
      N.blank(),
      strEnum(
        name,
        "InvalidArgument",
        `Values of argument \`${e.arg.name}\` of ${kind} option \`${e.option.name}\`${e.arg.doc ? `: ${md(e.arg.doc)}` : ""}.`,
        e.values.map((value) => ({ value })),
      ),
    );
  }
  return N.namespace(kind, items, { mods: pub, doc: N.doc(`${kindDoc[kind]}: names, aliases, short names and argument enums.`, { mods: ["inner"] }) });
}

function emitOptions(spec: Spec): Node {
  return N.file([
    header("Typed option tables of the processing, `/info` and `/video` catalogues."),
    N.blank(),
    ...catalogues(spec).flatMap((c) => [N.blank(), catalogueModule(c)]),
  ]);
}

// ---- methods.rs ------------------------------------------------------------------------

function methodsMacro(c: CatalogueModel): Node[] {
  const { kind } = c;
  const items: Node[] = [];
  const used = new Map<string, string>();
  for (const o of c.options) {
    for (const n of o.names) {
      const name = ident(n);
      if (reservedMethods.has(name)) throw new Error(`${kind} option ${n} collides with the builder method ${name}`);
      const prev = used.get(name);
      if (prev !== undefined) throw new Error(`${kind} option names ${prev} and ${n} are both the Rust method ${name}`);
      used.set(name, n);
      const canonical = ident(o.name);
      const text = n === o.name ? optionDoc(o) : `\`${n}\`: alias of [\`${canonical}\`](Self::${canonical}), written as \`${n}\` with the \`given\` name style.`;
      if (items.length) items.push(N.blank());
      items.push(
        N.func(name, [N.param("self"), N.param("args", R.impl(t("$crate::IntoArgs")))], N.invoke(id("self"), "option", [N.str(n), id("args")]), {
          mods: pub,
          returns: t("Self"),
          doc: doc(text),
        }),
      );
    }
  }
  return [
    R.macroRules(`${kind}_methods`, items, {
      doc: doc(`One method per ${kind} option name and alias; each appends that option, written with the name as called.`),
      annotations: [attr("doc", id("hidden"))],
    }),
    N.imp(`${kind}_methods`, [], { mods: ["pub(crate)"] }),
  ];
}

function emitMethods(spec: Spec): Node {
  return N.file([
    header("Per-option methods of the fluent URL builders, as macros the chain types expand."),
    N.blank(),
    ...catalogues(spec).flatMap((c) => [N.blank(), ...methodsMacro(c)]),
  ]);
}


// ---- responses.rs ----------------------------------------------------------------------

const scalars: Record<string, string> = { string: "String", integer: "i64", number: "f64", boolean: "bool" };
const json = t("serde_json::Value");

function schemaType(s: JSONSchema): TypeRef {
  if (s.$ref) return t(refName(s.$ref));
  const types = schemaTypes(s);
  const nullable = types.includes("null") || (s.enum?.includes(null) ?? false);
  const ts = types.filter((x) => x !== "null");
  let base: TypeRef;
  if (s.enum) base = t("String");
  else if (ts.length !== 1) base = json;
  else if (scalars[ts[0]!]) base = t(scalars[ts[0]!]!);
  else if (ts[0] === "array") base = t("Vec", s.items ? schemaType(s.items) : json);
  else if (ts[0] === "object") {
    if (s.properties) throw new Error("inline object schemas are not supported");
    const ap = s.additionalProperties;
    base = t("BTreeMap", t("String"), typeof ap === "object" && Object.keys(ap).length > 0 ? schemaType(ap) : json);
  } else base = json;
  return nullable ? t("Option", base) : base;
}

const isOption = (x: TypeRef) => x.k === "tref" && x.name === "Option";

function emitResponses(spec: Spec): Node {
  const items: Node[] = [
    header("serde types of the JSON response bodies (the OpenAPI components)."),
    N.blank(),
    N.imp("std::collections::BTreeMap"),
    N.blank(),
    N.imp("serde", ["Deserialize", "Serialize"]),
  ];
  for (const sm of responseSchemas(spec)) {
    const fields = sm.properties.map(([p, ps]) => {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(p)) throw new Error(`${sm.name}.${p} is not a Rust identifier`);
      let x = schemaType(ps);
      const serde: Expr[] = [];
      if (p.toLowerCase() !== p) serde.push(N.binary("=", id("rename"), N.str(p)));
      if (!sm.required.has(p)) {
        if (!isOption(x)) x = t("Option", x);
        serde.push(id("default"), N.binary("=", id("skip_serializing_if"), N.str("Option::is_none")));
      }
      return N.field(field(p), x, {
        mods: pub,
        doc: doc(ps.description ? md(ps.description) : `\`${p}\`${ps.$ref ? ` (${refName(ps.$ref)})` : ""}.`),
        annotations: serde.length ? [attr("serde", ...serde)] : [],
      });
    });
    items.push(
      N.blank(),
      N.type("struct", sm.name, fields, {
        mods: pub,
        doc: doc(md(sm.schema.description ?? sm.name)),
        annotations: [derive("Debug", "Clone", "PartialEq", "Default", "Serialize", "Deserialize"), attr("non_exhaustive")],
      }),
    );
  }
  return N.file(items);
}

export const emitter: Emitter = {
  language: "rust",
  emit(spec) {
    const files: Record<string, Node> = {
      "mod.rs": N.file([
        header("Generated tables; use the re-exports at the crate root instead."),
        N.blank(),
        R.mod("constants", pub),
        R.mod("methods", ["pub(crate)"]),
        R.mod("options", pub),
        R.mod("responses", pub, [attr("cfg", N.binary("=", id("feature"), N.str("serde")))]),
      ]),
      "options.rs": emitOptions(spec),
      "methods.rs": emitMethods(spec),
      "constants.rs": emitConstants(spec),
      "responses.rs": emitResponses(spec),
    };
    return Object.fromEntries(Object.entries(files).map(([f, n]) => [`${dir}${f}`, printer.print(n)]));
  },
};

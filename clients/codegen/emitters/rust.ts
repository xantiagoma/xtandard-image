const refName = (ref: string) => ref.replace("#/components/schemas/", "");

function schemaType(s: JSONSchema): string {
  if (s.$ref) return refName(s.$ref);
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  const nullable = types.includes("null") || (s.enum?.includes(null) ?? false);
  const t = types.filter((x) => x !== "null");
  let base: string;
  if (s.enum) base = "String";
  else if (t.length !== 1) base = "serde_json::Value";
  else {
    switch (t[0]) {
      case "string":
        base = "String";
        break;
      case "integer":
        base = "i64";
        break;
      case "number":
        base = "f64";
        break;
      case "boolean":
        base = "bool";
        break;
      case "array":
        base = `Vec<${s.items ? schemaType(s.items) : "serde_json::Value"}>`;
        break;
      case "object":
        if (s.properties) throw new Error("inline object schemas are not supported");
        base = `BTreeMap<String, ${typeof s.additionalProperties === "object" && Object.keys(s.additionalProperties).length > 0 ? schemaType(s.additionalProperties) : "serde_json::Value"}>`;
        break;
      default:
        base = "serde_json::Value";
    }
  }
  return nullable ? `Option<${base}>` : base;
}

function emitResponses(spec: Spec): string {
  const out: string[] = [header("serde types of the JSON response bodies (the OpenAPI components).")];
  out.push("use std::collections::BTreeMap;");
  out.push("");
  out.push("use serde::{Deserialize, Serialize};");
  for (const name of Object.keys(spec.response_schemas).sort()) {
    const s = spec.response_schemas[name]!;
    out.push("");
    out.push(...doc(md(s.description ?? name), ""));
    out.push("#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]");
    out.push("#[non_exhaustive]");
    out.push(`pub struct ${name} {`);
    const req = new Set(s.required ?? []);
    for (const [p, ps] of sortedBy(Object.entries(s.properties ?? {}), ([k]) => k)) {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(p)) throw new Error(`${name}.${p} is not a Rust identifier`);
      const lower = p.toLowerCase();
      const field = keywords.has(lower) ? `r#${lower}` : lower;
      let t = schemaType(ps);
      const optional = !req.has(p);
      out.push(...doc(ps.description ? md(ps.description) : `\`${p}\`${ps.$ref ? ` (${refName(ps.$ref)})` : ""}.`, "    "));
      const attrs: string[] = [];
      if (lower !== p) attrs.push(`rename = ${str(p)}`);
      if (optional) {
        if (!t.startsWith("Option<")) t = `Option<${t}>`;
        attrs.push("default", 'skip_serializing_if = "Option::is_none"');
      }
      if (attrs.length) out.push(`    #[serde(${attrs.join(", ")})]`);
      out.push(`    pub ${field}: ${t},`);
    }
    out.push("}");
  }
  out.push("");
  return out.join("\n");
}

export const emitter: Emitter = {
  language: "rust",
  emit(spec) {
    return {
      [`${dir}mod.rs`]: [
        header("Generated tables; use the re-exports at the crate root instead."),
        "pub mod constants;",
        "pub(crate) mod methods;",
        "pub mod options;",
        '#[cfg(feature = "serde")]',
        "pub mod responses;",
        "",
      ].join("\n"),
      [`${dir}options.rs`]: emitOptions(spec),
      [`${dir}methods.rs`]: emitMethods(spec),
      [`${dir}constants.rs`]: emitConstants(spec),
      [`${dir}responses.rs`]: emitResponses(spec),
    };
  },
};

// Rust emitter (clients/rust, crate xtandard-image): writes src/generated/
// from the spec.
//
//   mod.rs        the module list
//   options.rs    per catalogue (processing, info, video): the OptionName
//                 enum, the name and short-name tables, and one enum per
//                 enum-typed argument (ResizeType, GravityType, …)
//   methods.rs    macros with the fluent builders' per-option methods,
//                 expanded into the chain types by the runtime
//   constants.rs  formats, containers, streams, sources, query keys,
//                 imaginary, signing, encryption and URL constants, error kinds
//   responses.rs  serde structs of the JSON bodies (InfoResponse, ErrorResponse)
//
// The runtime (src/*.rs) defines the `str_enum!` macro the enums use and the
// `Arg`/`IntoArgs` types the methods take. lib.rs marks the generated module
// #[rustfmt::skip] and allows the pedantic lints the generator would fight.
//
// This file is the refiner (WP-146): it lowers the neutral model (build.ts)
// into Rust nodes (model.ts, and lang/rust.ts's own: str_enum!,
// option_names!, macro_rules!, references and slices), which lang/rust.ts
// prints.


// ADR 0006: the runtime dependency closure of every target (what an app that depends on this library pulls in)
// must be MIT, BSD, Apache-2.0 or ISC. Licences come from each module's POM, following <parent> POMs. There are no
// exceptions; add one here, with its reason, only together with the README.
val licenseConfigurations =
    listOf("jvmRuntimeClasspath", "iosArm64CompileKlibraries", "iosSimulatorArm64CompileKlibraries", "macosArm64CompileKlibraries")
val licenseExceptions = emptyMap<String, String>()

tasks.register("checkLicenses") {
    group = "verification"
    description = "Checks the runtime dependency closure of every target against the ADR 0006 licence allowlist"
    val configs = configurations
    val deps = dependencies
    val report = layout.buildDirectory.file("reports/licenses.txt")
    outputs.file(report)
    outputs.upToDateWhen { false }
    doLast {
        val modules = sortedSetOf<String>()
        for (name in licenseConfigurations) {
            configs
                .getByName(name)
                .incoming.resolutionResult.allComponents
                .mapNotNull { it.id as? org.gradle.api.artifacts.component.ModuleComponentIdentifier }
                .forEach { modules += "${it.group}:${it.module}:${it.version}" }
        }
        val licenseName = Regex("<license>\\s*(?:<!--.*?-->\\s*)*<name>([^<]+)</name>", RegexOption.DOT_MATCHES_ALL)
        val parent =
            Regex(
                "<parent>.*?<groupId>([^<]+)</groupId>.*?<artifactId>([^<]+)</artifactId>.*?<version>([^<]+)</version>.*?</parent>",
                RegexOption.DOT_MATCHES_ALL,
            )

        fun pom(coordinates: String): String {
            val (g, m, v) = coordinates.split(':')
            val result =
                deps
                    .createArtifactResolutionQuery()
                    .forModule(g, m, v)
                    .withArtifacts(MavenModule::class.java, MavenPomArtifact::class.java)
                    .execute()
            val artifact =
                result.resolvedComponents
                    .single()
                    .getArtifacts(MavenPomArtifact::class.java)
                    .single() as ResolvedArtifactResult
            return artifact.file.readText()
        }

        fun licenses(coordinates: String): List<String> {
            var c = coordinates
            repeat(10) {
                val xml = pom(c)
                val found = licenseName.findAll(xml).map { it.groupValues[1].trim() }.toList()
                if (found.isNotEmpty()) return found
                val p = parent.find(xml) ?: return emptyList()
                c = "${p.groupValues[1]}:${p.groupValues[2]}:${p.groupValues[3]}"
            }
            return emptyList()
        }

        fun allowed(name: String): Boolean {
            val n = name.lowercase()
            return (n.contains("apache") && n.contains("2")) || n == "mit" || n.contains("mit license") ||
                n.startsWith("bsd") || n.contains("bsd license") || n.contains("bsd-") || n == "isc" || n.contains("isc license")
        }
        val lines = mutableListOf<String>()
        val bad = mutableListOf<String>()
        for (m in modules) {
            val ls = licenses(m)
            val key = m.substringBeforeLast(':')
            val ok = ls.isNotEmpty() && ls.any(::allowed)
            lines +=
                "$m\t${ls.joinToString(
                    " | ",
                ).ifEmpty { "(none)" }}${if (!ok && key in licenseExceptions) "\texception: ${licenseExceptions[key]}" else ""}"
            if (!ok && key !in licenseExceptions) bad += "$m: ${ls.ifEmpty { listOf("no licence in its POM") }}"
        }
        report.get().asFile.writeText(lines.joinToString("\n", postfix = "\n"))
        if (bad.isNotEmpty()) throw GradleException("licences outside MIT/BSD/Apache-2.0/ISC:\n" + bad.joinToString("\n"))
        logger.lifecycle("checkLicenses: ${modules.size} runtime modules, all MIT, BSD, Apache-2.0 or ISC (${report.get().asFile})")
    }
}


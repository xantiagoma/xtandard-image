// The Kotlin Multiplatform client of xtandard-image (clients/kotlin, ADR 0013).
//
// Targets: JVM (servers, desktop, and Android apps, which consume the JVM
// variant), iosArm64, iosSimulatorArm64 and macosArm64. Everything but the
// HTTP engine choice and the HMAC/AES/random primitives is common code.
//
//   gradle assemble         every target's library (warnings are errors)
//   gradle allTests         JVM, macOS and iOS simulator tests (the Apple ones on macOS only)
//   gradle checkLicenses    the runtime closure of every target against ADR 0006
//   gradle dokkaGeneratePublicationHtml
//   gradle publishAllPublicationsToBuildRepository   publish dry run into build/repo
//   gradle publishToMavenLocal                       to try a snapshot from another project
//
// ktlint runs outside Gradle (`task lint`, pinned in mise.toml).

